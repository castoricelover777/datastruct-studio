const SLOTS = 6;

/** 某个格子在某个时刻显示某个值 */
const cell = (at, value, vis, accent) => ({ at, value, vis, accent });

/**
 * 表达"数组在 t0 时刻变成 values"：
 * 旧的值淡出、新的值淡入 —— 用两组 cell 叠在同一格上实现。
 */
function morph(at, from, to, t, accent) {
  return [
    cell(at, String(from), [[0, t]], accent),
    cell(at, String(to), [[t, 99]], accent),
  ];
}

