#%module | 01 | countConst | countConst —— 数一数执行了多少次 | 1 |
#%summary | 给三段代码各装一个计数器，看它们的执行次数随 n 怎么增长。
#@d ============ 为什么不直接掐表 ============
#@d 同一段代码，在快的机器上跑 1 秒，在慢的机器上可能跑 5 秒；
#@d 换个编译器、加个优化选项，结果又会变。**掐表测出来的是机器，不是算法。**
#@d
#@d 所以我们要数的是"与机器无关"的东西：关键操作执行了多少次。
#@d 下面三段代码都只做一件事 —— 不停地对 cnt 做加法，然后看加了多少次。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 要写返回类型 long、参数类型 int n，一行里类型占了一半；
#@d   Python 写成 def countConst(n): 就完事，什么都不用标。
#@d
#@d   C 有 cnt++ 这种"自己加一"的写法，Python 里压根没有 ++ 这个符号，
#@d   只能写 cnt += 1，写成 cnt++ 是会直接报错的。
#@d
#@d   C 的 long 有上限，加到太大就溢出；Python 的整数想多长就多长，
#@d   加到一百万、一万亿都照样存得下，这里不用替溢出操心。

#@s 参数 n 是问题规模；返回值是"加法执行了多少次"
#@d 返回类型用 long，因为 O(n²) 那段在 n = 1000 时会加到一百万次
def countConst(n):
    #@s 计数器
    cnt = 0
    #@s 不管 n 多大，这里都只加一次 —— 这就是 O(1)
    #@d 常数阶的意思不是"很快"，而是"与 n 无关"。哪怕写 1000 次加法，它也是 O(1)。
    cnt += 1
    #@s 把次数交回去
    return cnt
#%end

#%module | 02 | countLinear | countLinear —— 线性阶 O(n) | 1 |
#%summary | 单层循环走 n 遍，执行次数与 n 成正比。
#@d ============ 线性阶长什么样 ============
#@d
#@d   n = 10    →  加 10 次
#@d   n = 100   →  加 100 次      （n 变大 10 倍，次数也变大 10 倍）
#@d   n = 1000  →  加 1000 次
#@d
#@d "成正比"就是这个意思。写成 O(n)。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 要先写 int i; 把循环变量备好，循环头是 for (i = 0; i < n; i++)；
#@d   Python 直接 for i in range(n)，i 是跑到这一行才现造出来的，前面不写 int i。
#@d
#@d   range(n) 吐出来的是 0, 1, 2, ..., n-1，正好对上 C 的 i < n；
#@d   要是手滑写成 range(n + 1) 就多跑一圈变成 n+1 次，这是最容易踩的坑。

#@s 计数器
def countLinear(n):
    #@s 计数器
    cnt = 0
    #@s 循环变量
    #@d C 在这里还有一行 int i;，Python 不用提前声明，下面的 for 会自己把 i 造出来
    #@s 循环 n 次，每轮加一次
    for i in range(n):
        #@s 关键操作：这一次加法要被数进去
        cnt += 1

    #@s 返回总次数，答案应该正好是 n
    return cnt
#%end

#%module | 03 | countQuadratic | countQuadratic —— 平方阶 O(n²) | 2 |
#%summary | 双层循环，执行次数是 n 的平方 —— 差距从这里开始吓人。
#@d ============ 平方阶的增长有多快 ============
#@d
#@d   n = 10    →  加 100 次
#@d   n = 100   →  加 10000 次      （n 变大 10 倍，次数变大 100 倍！）
#@d   n = 1000  →  加 1000000 次
#@d
#@d 对比一下线性阶：同样是 n 从 10 涨到 1000，
#@d 线性阶的代价涨了 100 倍，平方阶的代价涨了 10000 倍。
#@d 这就是为什么 O(n²) 的算法在数据量大时会突然"跑不动"。
#@d
#@d ============ 嵌套循环怎么数 ============
#@d
#@d   外层 i = 0 :   内层跑 n 次
#@d   外层 i = 1 :   内层跑 n 次
#@d   ...
#@d   外层 i = n-1:  内层跑 n 次
#@d   ────────────────────────────
#@d   一共 n × n = n² 次
#@d
#@d 记住一条：**嵌套循环相乘，并列循环相加**。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 要先声明 int i, j 两个循环变量；Python 两个 for 各写各的 range(n)，
#@d   声明都省了，一眼就能看出跑的是 n × n 次。
#@d
#@d   写法不一样，数出来的次数必须一样：这个函数返回的就是 n²。
#@d   翻译完记得跟 C 版对一下结果，别只看它跑通了就算完。

#@s 计数器
def countQuadratic(n):
    #@s 计数器
    cnt = 0
    #@s 两个循环变量
    #@d C 这里是 int i, j; —— Python 没有这种声明语句，i 和 j 由两个 for 各自现造
    #@s 外层跑 n 次
    for i in range(n):
        #@s 内层也跑 n 次 —— 两层相乘就是 n²
        for j in range(n):
            #@s 关键操作：每进一次内层就加一次
            cnt += 1

    #@s 返回总次数，答案应该正好是 n²
    return cnt
#%end

#%module | 04 | main | main —— 把三种量级摆在一起看 | 1 | 01,02,03
#%summary | 让 n 从 10 涨到 1000，把三段的执行次数并排打出来。
#@d ============ 这张表就是复杂度分析的直觉来源 ============
#@d 自己把输出抄一遍、比一比，比背定义有用得多：
#@d
#@d   n        O(1)     O(n)        O(n²)
#@d   10       1        10          100
#@d   100      1        100         10000
#@d   1000     1        1000        1000000
#@d
#@d 看最后一列：n 才涨到 1000，平方阶已经要一百万次了。
#@d 如果 n 是一百万呢？那就是一万亿次 —— 再快的机器也救不了。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 的入口是 int main(void)，系统会自动来调它；Python 没有这么个入口，
#@d   惯例是写 if __name__ == '__main__': —— 意思是"这个文件被直接运行时才跑"。
#@d
#@d   C 的 for (n = 10; n <= 1000; n *= 10) 是"初始化；判断；步长"三段式，
#@d   Python 的 for 只会一样样遍历现成的东西，所以这里换成 while 自己管 n。
#@d
#@d   printf 里的 %d、%ld 得跟类型一个个对上，Python 用 f'{n}' 直接塞进去，
#@d   不用挑 %d 还是 %ld，也不会因为格式符写错打出乱的数。

#@s 主函数不需要参数
#@d C 里这里是 int main(void)，Python 用下面这行固定写法代替
if __name__ == '__main__':
    #@s 问题规模，从 10 开始每次乘 10
    #@d C 在这儿单独有一行 int n; 声明变量，Python 直接 n = 10 就有了
    n = 10

    #@s 先打表头（\t 是制表符，用来对齐）
    #@d C 写的是 printf("n\tO(1)\tO(n)\tO(n^2)\n")，Python 末尾的 \n 可以省掉，print 自己会换行
    print('n\tO(1)\tO(n)\tO(n^2)')

    #@s 依次测试三个规模：10、100、1000
    #@d C 的三段式 for 在 Python 里换成 while，n 怎么变、什么时候停都写在循环体里
    while n <= 1000:
        #@s 把三种量级的执行次数并排打出来
        #@d C 的 printf("%d\t%ld\t%ld\t%ld\n", n, countConst(n), countLinear(n), countQuadratic(n))
        #@d 在那儿拆成好几行只是排版，作用就是按制表符把四个数并排打出来
        print(f'{n}\t{countConst(n)}\t{countLinear(n)}\t{countQuadratic(n)}')
        #@s 规模乘 10，进入下一轮
        n *= 10

    #@s 正常结束
    #@d C 在这儿写 return 0;，Python 脚本跑到最后一行就算正常结束，不用写 return
#%end
