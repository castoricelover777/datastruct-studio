//%driver | 01
/* 验证算法1（三重循环） */
int main(void)
{
    int a[] = { -2, 11, -4, 13, -5, -2 };
    int n = 6;

    printf("算法1 结果 = %d（应该是 20）\n", MaxSubseqSum1(a, n));
    printf("（三重循环：枚举所有子列，最里面那层每次重头加）\n");

    return 0;
}
//%driver-end

//%driver | 02
/* 验证算法2（两重循环） */
int main(void)
{
    int a[] = { -2, 11, -4, 13, -5, -2 };
    int n = 6;

    printf("算法2 结果 = %d（应该和算法1一样是 20）\n", MaxSubseqSum2(a, n));
    printf("（省掉了最里面那层：右端每右移一格，只在原来的和上再加一个）\n");

    return 0;
}
//%driver-end

//%driver | 03
/* 验证算法3（分治） */
int main(void)
{
    int a[] = { -2, 11, -4, 13, -5, -2 };
    int n = 6;

    printf("算法3 结果 = %d（应该是 20）\n", MaxSubseqSum3(a, 0, n - 1));
    printf("（分治：左半、右半、跨中线三者取大）\n");

    /* 单独验证一段跨中线的数据 */
    {
        int b[] = { 4, -3, 5, -2, -1, 2, 6, -2 };
        int m = 8;
        printf("另一组数据结果 = %d\n", MaxSubseqSum3(b, 0, m - 1));
    }

    return 0;
}
//%driver-end

//%driver | 04
/* 验证算法4（在线处理） */
int main(void)
{
    int a[] = { -2, 11, -4, 13, -5, -2 };
    int n = 6;
    int neg[] = { -3, -1, -7, -2 };
    int one[] = { 5 };
    int m;

    printf("算法4 结果 = %d（应该是 20）\n", MaxSubseqSum4(a, n));

    m = MaxSubseqSum4(neg, 4);
    printf("全是负数 = %d（约定空子列和为 0，所以是 0）\n", m);

    m = MaxSubseqSum4(one, 1);
    printf("只有一个正数 = %d\n", m);

    printf("（在线处理：当前和变负就扔掉重来，只扫一遍）\n");

    return 0;
}
//%driver-end
