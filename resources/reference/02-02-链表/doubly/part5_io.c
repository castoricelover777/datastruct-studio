//%module | 11 | printList | printList —— 正向打印 | 1 | 01
//%summary | 顺着 next 从头走到尾，把每个结点的数据打出来。
//@d ============ 正向遍历：和单链表一模一样 ============
//@d
//@d   p = L->next;              ← 跳过不存数据的头结点
//@d   while (p != NULL) {       ← 走到 NULL 说明到尾了
//@d       ... 处理 p->data ...
//@d       p = p->next;          ← 千万别忘了这一句，否则死循环
//@d   }
//@d
//@d 输出用 `⇄` 而不是 `->`，是为了提醒这条链是**双向**的：
//@d 屏幕上看到的每个 `⇄`，在内存里都对应两根指针。
//@d
//@d 真正体现双向价值的是下一个模块 —— 反向打印。

//@s 只读操作，参数直接传 DuLinkList（一级指针）
void printList(DuLinkList L)
{
//@s 从第一个真实结点开始
    DuLNode *p = L->next;

//@s 空表单独处理，提示比"什么都不打印"清楚得多
    if (p == NULL)
    {
//@s 空表提示
        printf("(空表)\n");
//@s 直接返回，不再进入循环
        return;
    }

//@s 标准遍历
    while (p != NULL)
    {
//@s 打印当前数据，`⇄` 表示这里是双向连接
        printf("%d ⇄ ", p->data);
//@s 推进到下一个结点
        p = p->next;
    }

//@s 收尾打印 NULL，标明链表末端
    printf("NULL\n");
}
//%end

//%module | 12 | printListReverse | printListReverse —— 反向打印 | 2 | 01,03
//%summary | 先走到尾结点，再顺着 prior 一路走回头结点 —— 单链表做不到这件事。
//@d ============ 这就是双向链表多一个指针换来的能力 ============
//@d 单链表想倒着打印，只有两条路：
//@d   1. 递归（函数调用栈替你记住来路，但表长了会爆栈）；
//@d   2. 先把数据全拷进数组，再倒着输出（额外 O(n) 空间）。
//@d 双向链表不用这么麻烦 —— prior 就在结点里，直接往回走。
//@d
//@d ============ 为什么循环条件是 p != L 而不是 p != NULL ============
//@d 这是本模块最容易写错的地方。
//@d
//@d   反向走的时候，如果写 while (p != NULL)：
//@d     p 会一路走过头结点，而头结点的 data 是**没意义的垃圾值**，
//@d     屏幕上会莫名其妙多打一个数；再往后 p 变成 NULL 才停。
//@d
//@d   正确写法是 while (p != L)：
//@d     走到头结点就停 —— 头结点是哨兵，不该被当成数据打印。
//@d
//@d 顺带一提：正因为头结点的 prior 是 NULL，如果哪一步把"停"的条件写错，
//@d 就会顺着 NULL 继续取 prior，直接崩掉。
//@d
//@d ============ 走法示意 ============
//@d
//@d  第一步：顺着 next 找到尾结点
//@d    L ─▶ [头] ⇄ [10] ⇄ [20] ⇄ [30]
//@d                                  p
//@d
//@d  第二步：顺着 prior 一路往回，边走边打印，直到撞上头结点
//@d    L ─▶ [头] ⇄ [10] ⇄ [20] ⇄ [30]
//@d            p ◀──── 返回路径
//@d
//@d  屏幕上得到：  30 ⇄ 20 ⇄ 10 ⇄ NULL

//@s 只读操作，不需要修改链表
void printListReverse(DuLinkList L)
{
//@s 从头结点后面开始
    DuLNode *p = L->next;

//@s 空表同样单独处理
    if (p == NULL)
    {
//@s 空表提示
        printf("(空表)\n");
//@s 直接返回
        return;
    }

//@s 第一步：顺着 next 走到尾结点
//@d 条件写 p->next != NULL，所以停下时 p 正好是最后一个结点
    while (p->next != NULL)
    {
//@s 指针后移
        p = p->next;
    }

//@s 第二步：顺着 prior 往回走，撞到头结点就停
//@d 这里必须写 p != L，不能写 p != NULL —— 头结点不能被当成数据打印
    while (p != L)
    {
//@s 打印当前数据
        printf("%d ⇄ ", p->data);
//@s 顺着 prior 往回走一格（单链表没有这一步可走）
        p = p->prior;
    }

//@s 收尾
    printf("NULL\n");
}
//%end

//%module | 13 | freeList | freeList —— 释放内存 | 2 | 01,03
//%summary | 逐个释放每个结点，最后把头结点也释放掉，并把指针置 NULL。
//@d ============ 释放只需要 next 方向 ============
//@d 虽然结点里有 prior，但释放时**根本用不到它** ——
//@d 因为必须先把整条链走完才能全部释放，而"走完"只需要 next。
//@d
//@d ============ 为什么必须先保存 next ============
//@d
//@d  错误写法：                正确写法：
//@d    free(p);                  q = p;
//@d    p = p->next;   ← 危险!    p = p->next;
//@d                             free(q);
//@d
//@d free(p) 之后那块内存已经还给系统，p->next 读到的是垃圾值，
//@d 用这个垃圾值当地址去访问就是"释放后使用"（use after free）。
//@d
//@d 更危险的是：如果在 free(p) 之前先去动 p->prior->next 之类的指针
//@d （双向链表很容易顺手这么写），会把已经损坏的链再改一次，
//@d 崩溃点离真正的错误点非常远，极难排查。

//@s 参数是 DuLinkList *，因为最后要把调用者的 L 改成 NULL
void freeList(DuLinkList *L)
{
//@s 从第一个真实结点开始清理
    DuLNode *p = (*L)->next;
//@s q 用来暂存"即将被释放"的那个结点
    DuLNode *q = NULL;

//@s 逐个结点释放
    while (p != NULL)
    {
//@s 先记住当前结点
        q = p;
//@s 再让 p 走到下一个（此时 p 已经安全了）
        p = p->next;
//@s 最后才释放 q
//@d 这三步顺序固定：存 → 走 → 放，缺一不可
        free(q);
    }

//@s 数据结点都清完了，头结点也要还回去
    free(*L);
//@s 把调用者的指针置 NULL，避免它继续指向已释放的内存
    *L = NULL;
}
//%end

//%module | 14 | main | main —— 主函数测试 | 2 | 01,02,03,04,05,06,07,08,09,10,11,12,13
//%summary | 把增、删、查、改四类操作各跑一遍，正反向遍历对照验证 prior 没写错。
//@d ============ 双向链表的测试要多做一件事 ============
//@d 单链表只要正向打印对，基本就对了。
//@d 双向链表**每一步都要正反向打印对照** —— 因为漏改 prior 的 bug
//@d 正向完全看不出来，只有反向遍历（或后续的删除）才会暴露。
//@d
//@d 所以本测试里每次改动链表之后，都会同时打印正向和反向，
//@d 两个方向互为对方的"校验和"。
//@d
//@d 另外一定要测三种边界：
//@d   1. 空表      （初始化后立刻打印）
//@d   2. 越界位置  （插入/查找/修改/删除一个不存在的位置，应返回 ERROR）
//@d   3. 删尾结点  （专门验证 p->next == NULL 那条判空分支）

//@s 主函数不需要参数，返回 0 表示正常结束
int main(void)
{
//@s L 是头结点指针，先置 NULL，等 InitList 去创建头结点
    DuLinkList L = NULL;
//@s p 用来接 LocateElem 返回的结点地址
    DuLNode *p = NULL;
//@s e 用来接按位查找 / 删除带回来的数据
    ElemType e = 0;

//@s ========== 第 1 步：初始化 ==========
    printf("========== 1. 初始化 ==========\n");
//@s 检查返回值，初始化失败就没必要继续了
    if (InitList(&L) != OK)
    {
//@s 失败提示
        printf("初始化失败！\n");
//@s 直接返回错误码
        return ERROR;
    }
//@s 打印验证：此时应该是空表
    printf("初始化完成，当前链表：");
    printList(L);

//@s ========== 第 2 步：尾部追加 ==========
    printf("\n========== 2. 尾部追加 10 20 30 ==========\n");
//@s 依次追加三个数
    applist(L, 10);
    applist(L, 20);
    applist(L, 30);
//@s 期望正向：10 ⇄ 20 ⇄ 30 ⇄ NULL
    printf("追加后（正向）：");
    printList(L);
//@s 期望反向：30 ⇄ 20 ⇄ 10 ⇄ NULL
//@d 反向能打对，说明尾插时 s->prior = p 那一句没漏
    printf("追加后（反向）：");
    printListReverse(L);

//@s ========== 第 3 步：头插法 ==========
    printf("\n========== 3. 头插法插入 5 ==========\n");
//@s 头插 5：不遍历，直接变成第 1 个结点
    HeadInsert(L, 5);
//@s 期望正向：5 ⇄ 10 ⇄ 20 ⇄ 30 ⇄ NULL
    printf("头插 5 后（正向）：");
    printList(L);
//@s 反向也要对：30 ⇄ 20 ⇄ 10 ⇄ 5 ⇄ NULL
    printf("头插 5 后（反向）：");
    printListReverse(L);

//@s ========== 第 4 步：按位插入 ==========
    printf("\n========== 4. 在第 2 位插入 15 ==========\n");
//@s 插到第 2 个位置，即 5 和 10 之间
    ListInsert(L, 2, 15);
//@s 期望正向：5 ⇄ 15 ⇄ 10 ⇄ 20 ⇄ 30 ⇄ NULL
    printf("插入后（正向）：");
    printList(L);
//@s 反向核对：30 ⇄ 20 ⇄ 10 ⇄ 15 ⇄ 5 ⇄ NULL
    printf("插入后（反向）：");
    printListReverse(L);

//@s 越界测试：在第 99 位插入必须失败
    printf("在第 99 位插入 5 ：%s\n", ListInsert(L, 99, 5) == OK ? "成功" : "失败（越界，符合预期）");

//@s ========== 第 5 步：按位查找 ==========
    printf("\n========== 5. 按位查找 ==========\n");
//@s 查第 3 个元素，用 e 带回结果
//@d 此时链表是 5 ⇄ 15 ⇄ 10 ⇄ 20 ⇄ 30，第 3 个是 10
    if (GetElem_L(L, 3, &e) == OK)
    {
//@s 期望输出：10
        printf("第 3 个元素的值是 %d\n", e);
    }
//@s 越界查找测试
    if (GetElem_L(L, 100, &e) == ERROR)
    {
//@s 期望走到这里
        printf("查第 100 个元素失败（越界，符合预期）\n");
    }

//@s ========== 第 6 步：按值查找 ==========
    printf("\n========== 6. 按值查找 ==========\n");
//@s 找值为 20 的结点
    p = LocateElem(L, 20);
//@s 找到就同时验证前后两个方向
    if (p != NULL)
    {
//@s 双向链表的好处：拿到结点就能同时说出它的前驱和后继
        printf("找到 20：它的前驱是 %d，后继是 %s\n",
               p->prior->data,
               p->next != NULL ? "一个有效结点" : "NULL");
    }
//@s 找不存在的值应当返回 NULL
    if (LocateElem(L, 99) == NULL)
    {
//@s 期望走到这里
        printf("查找值 99 返回 NULL（符合预期）\n");
    }

//@s ========== 第 7 步：按位修改 ==========
    printf("\n========== 7. 按位修改 ==========\n");
//@s 把第 1 个元素改成 99
    if (ModifyElem(L, 1, 99) == OK)
    {
//@s 期望正向：99 ⇄ 15 ⇄ 10 ⇄ 20 ⇄ 30 ⇄ NULL
        printf("把第 1 个元素改成 99 后：");
        printList(L);
    }
//@s 越界修改测试
    printf("改第 100 个元素：%s\n", ModifyElem(L, 100, 1) == OK ? "成功" : "失败（越界，符合预期）");

//@s ========== 第 8 步：正反向遍历对照 ==========
    printf("\n========== 8. 正反向遍历对照 ==========\n");
//@s 同一份链表，两个方向必须互为倒序
    printf("正向：");
    printList(L);
    printf("反向：");
    printListReverse(L);

//@s ========== 第 9 步：按位删除 ==========
    printf("\n========== 9. 删除第 2 个结点 ==========\n");
//@s 删除第 2 个结点（值为 15），被删的值通过 e 带出来
    if (ListDelete(L, 2, &e) == OK)
    {
//@s 期望输出：被删除的是 15
        printf("已删除第 2 个结点，它的值是 %d\n", e);
    }
//@s 期望正向：99 ⇄ 10 ⇄ 20 ⇄ 30 ⇄ NULL
    printf("删除后（正向）：");
    printList(L);
//@s 反向核对：30 ⇄ 20 ⇄ 10 ⇄ 99 ⇄ NULL
    printf("删除后（反向）：");
    printListReverse(L);

//@s 越界删除测试
    printf("删除第 10 个结点：%s\n", ListDelete(L, 10, &e) == OK ? "成功" : "失败（越界，符合预期）");

//@s ========== 第 10 步：删尾结点（专测判空分支）==========
    printf("\n========== 10. 删除尾结点 ==========\n");
//@s 此时链表是 99 ⇄ 10 ⇄ 20 ⇄ 30，共 4 个结点
//@d 删尾结点会走到 p->next == NULL 那条分支 —— 也就是不执行"后继的 prior 改指"。
//@d 这条分支不测，删尾结点时的崩溃就永远不会被发现。
    if (ListDelete(L, 4, &e) == OK)
    {
        printf("已删除尾结点，它的值是 %d\n", e);
    }
//@s 期望正向：99 ⇄ 10 ⇄ 20 ⇄ NULL
    printf("删除尾结点后（正向）：");
    printList(L);
//@s 反向核对：20 ⇄ 10 ⇄ 99 ⇄ NULL
    printf("删除尾结点后（反向）：");
    printListReverse(L);

//@s ========== 第 11 步：释放整表 ==========
    printf("\n========== 11. 释放内存 ==========\n");
//@s 释放所有结点，并把 L 置为 NULL
    freeList(&L);
//@s 期望输出：NULL，证明 L 已被正确置空
    printf("释放完成，L = %s\n", L == NULL ? "NULL" : "非 NULL");

//@s 正常结束
    return 0;
}
//%end
