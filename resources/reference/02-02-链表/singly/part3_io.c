//%module | 10 | printList | printList —— 打印链表 | 1 | 01
//%summary | 从头到尾走一遍，把每个结点的数据打出来，最后打一个 NULL 收尾。
//@d ============ 遍历的固定套路 ============
//@d
//@d   p = L->next;              ← 跳过不存数据的头结点
//@d   while (p != NULL) {       ← 走到 NULL 说明到尾了
//@d       ... 处理 p->data ...
//@d       p = p->next;          ← 千万别忘了这一句，否则死循环
//@d   }
//@d
//@d 输出格式 10 -> 20 -> 30 -> NULL，最后那个 NULL 是"链尾"的可视化，
//@d 方便一眼看出链表在哪里结束。

//@s 只读操作，不需要修改链表，参数直接传 LinkList（一级指针）
void printList(LinkList L)
{
//@s 从第一个真实结点开始
    LNode *p = L->next;

//@s 空表单独处理，提示比"什么都不打印"清楚得多
    if (p == NULL)
    {
//@s 空表提示
        printf("(空表)\n");
//@s 直接返回，不再进入循环
        return;
    }

//@s 标准遍历
    while (p != NULL)
    {
//@s 打印当前数据，"->" 是链表的视觉箭头
        printf("%d -> ", p->data);
//@s 推进到下一个结点
        p = p->next;
    }

//@s 收尾打印 NULL，标明链表末端
    printf("NULL\n");
}
//%end

//%module | 11 | freeList | freeList —— 释放内存 | 2 | 01,03
//%summary | 逐个释放每个结点，最后把头结点也释放掉，并把指针置 NULL。
//@d ============ 为什么必须先保存 next ============
//@d
//@d  错误写法：                正确写法：
//@d    free(p);                  q = p;
//@d    p = p->next;   ← 危险!    p = p->next;
//@d                             free(q);
//@d
//@d free(p) 之后那块内存已经还给系统，p->next 读到的是垃圾值，
//@d 用这个垃圾值当地址去访问就是"释放后使用"（use after free）。
//@d 所以要先记住后继，再释放当前。

//@s 参数是 LinkList *，因为最后要把调用者的 L 改成 NULL
//@d 如果传一级指针，函数内把 L 置 NULL 传不回去，调用者手里就是野指针
void freeList(LinkList *L)
{
//@s 从第一个真实结点开始清理
    LNode *p = (*L)->next;
//@s q 用来暂存"即将被释放"的那个结点
    LNode *q = NULL;

//@s 逐个结点释放
    while (p != NULL)
    {
//@s 先记住当前结点
        q = p;
//@s 再让 p 走到下一个（此时 p 已经安全了）
        p = p->next;
//@s 最后才释放 q
//@d 这三步顺序固定：存 → 走 → 放，缺一不可
        free(q);
    }

//@s 数据结点都清完了，头结点也要还回去
    free(*L);
//@s 把调用者的指针置 NULL，避免它继续指向已释放的内存
    *L = NULL;
}
//%end

//%module | 12 | main | main —— 主函数测试 | 2 | 01,02,03,04,05,06,07,08,09,10,11
//%summary | 把 9 个基本操作串起来跑一遍，用输出验证每一步的结果是否符合预期。
//@d ============ 测试程序的编排思路 ============
//@d 千万不要一次性把所有操作写完再运行，那样出错无从下手。
//@d 正确做法是"一步一打印"：每做完一个操作就 printList，
//@d 让输出自己告诉你哪一步开始不对。
//@d
//@d 另外一定要测三种边界：
//@d   1. 空表      （初始化后立刻打印）
//@d   2. 越界位置  （插入/查找/删除一个不存在的位置，应返回 ERROR）
//@d   3. 空表释放  （防止 freeList 对空表崩溃）

//@s 主函数不需要参数，返回 0 表示正常结束
int main(void)
{
//@s L 是头结点指针，先置 NULL，等 InitList 去创建头结点
    LinkList L = NULL;
//@s p 用来接 LocateElem 返回的结点地址
    LNode *p = NULL;
//@s e 用来接按位查找 / 删除带回来的数据
    ElemType e = 0;

//@s ========== 第 1 步：初始化 ==========
    printf("========== 1. 初始化 ==========\n");
//@s 检查返回值，初始化失败就没必要继续了
    if (InitList(&L) != OK)
    {
//@s 失败提示
        printf("初始化失败！\n");
//@s 直接返回错误码
        return ERROR;
    }
//@s 打印验证：此时应该是空表
    printf("初始化完成，当前链表：");
    printList(L);

//@s ========== 第 2 步：尾部追加 ==========
    printf("\n========== 2. 尾部追加 10 20 30 ==========\n");
//@s 依次追加三个数
    applist(L, 10);
    applist(L, 20);
    applist(L, 30);
//@s 期望输出：10 -> 20 -> 30 -> NULL
    printf("追加后：");
    printList(L);

//@s ========== 第 3 步：头插法 ==========
    printf("\n========== 3. 头插法插入 ==========\n");
//@s 头插 5：不遍历，直接变成第 1 个结点
    HeadInsert(L, 5);
//@s 期望输出：5 -> 10 -> 20 -> 30 -> NULL
    printf("头插后：");
    printList(L);

//@s 再头插 3，亲眼看一次"头插会颠倒顺序"
    HeadInsert(L, 3);
//@s 期望输出：3 -> 5 -> 10 -> 20 -> 30 -> NULL
//@d 头插法建出来的表天生是逆序的，所以"头插法建表"常被拿来倒序一个数组
    printf("再头插 3 后：");
    printList(L);

//@s ========== 第 4 步：按位插入 ==========
    printf("\n========== 4. 在第 2 位插入 15 ==========\n");
//@s 插到第 2 个位置，即 3 和 5 之间
    ListInsert(L, 2, 15);
//@s 期望输出：3 -> 15 -> 5 -> 10 -> 20 -> 30 -> NULL
    printf("插入后：");
    printList(L);

//@s 越界测试：在第 99 位插入必须失败
    printf("在第 99 位插入 5 ：%s\n", ListInsert(L, 99, 5) == OK ? "成功" : "失败（越界，符合预期）");

//@s ========== 第 5 步：按位查找 ==========
    printf("\n========== 5. 按位查找 ==========\n");
//@s 查第 3 个元素，用 e 带回结果
//@d 此时链表是 3 -> 15 -> 5 -> 10 -> 20 -> 30，第 3 个是 5
    if (GetElem_L(L, 3, &e) == OK)
    {
//@s 期望输出：5
        printf("第 3 个元素的值是 %d\n", e);
    }
//@s 越界查找测试
    if (GetElem_L(L, 100, &e) == ERROR)
    {
//@s 期望走到这里
        printf("查第 100 个元素失败（越界，符合预期）\n");
    }

//@s ========== 第 6 步：按值查找 ==========
    printf("\n========== 6. 按值查找 ==========\n");
//@s 找值为 20 的结点
    p = LocateElem(L, 20);
//@s 找到就打印它的后继信息
    if (p != NULL)
    {
//@s p->next 非空则说明 20 不是尾结点
        printf("找到值为 20 的结点，它的后继是 %s\n", p->next != NULL ? "一个有效结点" : "NULL");
    }
//@s 找不存在的值应当返回 NULL
    if (LocateElem(L, 99) == NULL)
    {
//@s 期望走到这里
        printf("查找值 99 返回 NULL（符合预期）\n");
    }

//@s ========== 第 7 步：按位删除 ==========
    printf("\n========== 7. 删除第 1 个结点 ==========\n");
//@s 删除第 1 个结点，被删的值通过 e 带出来
    if (ListDelete(L, 1, &e) == OK)
    {
//@s 期望输出：被删除的是 3
        printf("已删除第 1 个结点，它的值是 %d\n", e);
    }
//@s 期望输出：15 -> 5 -> 10 -> 20 -> 30 -> NULL
    printf("删除后：");
    printList(L);

//@s 越界删除测试
    printf("删除第 10 个结点：%s\n", ListDelete(L, 10, &e) == OK ? "成功" : "失败（越界，符合预期）");

//@s ========== 第 8 步：释放整表 ==========
    printf("\n========== 8. 释放内存 ==========\n");
//@s 释放所有结点，并把 L 置为 NULL
    freeList(&L);
//@s 期望输出：NULL，证明 L 已被正确置空
    printf("释放完成，L = %s\n", L == NULL ? "NULL" : "非 NULL");

//@s 正常结束
    return 0;
}
//%end
