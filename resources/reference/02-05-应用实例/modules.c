/*
 * ============================================================================
 *  数据结构研习社 —— 02 线性结构 / 02-05 应用实例
 * ============================================================================
 *
 *  堆栈最经典的两个应用，连在一起就是一个能算数的计算器：
 *
 *      "3+4*2"  ──①中缀转后缀──▶  "342*+"  ──②后缀求值──▶  11
 *
 *  为什么要绕这一圈？因为人写的中缀表达式（运算符夹在中间）对计算机很不友好：
 *  它牵扯括号、优先级、结合性。而后缀表达式（运算符在后）**没有括号，
 *  也不需要优先级规则** —— 从左往右扫一遍就能算，规则只有一条。
 *
 *  两个算法都只靠一个栈。这一节的重点是"运算符什么时候可以出栈"。
 *
 *  简化说明：为了把注意力放在栈上，这里假设输入里的操作数都是**个位数字**
 *  （0-9），运算符只支持 + - * / 和括号。
 *
 *  标记约定同前（本文件本身可编译）。
 * ============================================================================
 */

#include <stdio.h>

//%module | 01 | priority | priority —— 运算符优先级 | 1 |
//%summary | 给运算符排个座次，转后缀时靠它决定"谁该先出栈"。
//@d ============ 优先级表 ============
//@d
//@d   运算符  优先级      说明
//@d   ──────  ────────   ──────────────────────
//@d     +        1       同级，从左往右算
//@d     -        1
//@d     *        2       同级，比加减高
//@d     /        2
//@d     (        0       栈内的左括号：优先级最低，谁来了都不弹它
//@d
//@d 为什么左括号在栈内要算 0？
//@d
//@d 因为左括号一旦入栈，就必须等到**遇到右括号**才能弹出。
//@d 把它的优先级设成最低，任何运算符来比较时都会觉得"它比我低，
//@d 不用弹"—— 正好实现了"括号内先算完再说"。
//@d
//@d 这是个小技巧，但很关键：如果左括号优先级设高了，
//@d 它会被后面的运算符弹出去，括号就白写了。

//@s 返回运算符 c 的优先级；不是运算符就返回 -1
//@d 返回 -1 是给调用者一个"这不是运算符"的信号，
//@d 顺便也覆盖了"右括号不该出现在这个比较里"的情况。
int priority(char c)
{
    switch (c)
    {
    case '+':
    case '-':
//@s 加减同级，最低
        return 1;
    case '*':
    case '/':
//@s 乘除同级，比加减高
        return 2;
    case '(':
//@s 栈内的左括号：最低，保证不会被提前弹出
        return 0;
    default:
//@s 不是运算符（包括右括号、操作数）
        return -1;
    }
}
//%end

//%module | 02 | InfixToPostfix | InfixToPostfix —— 中缀转后缀 | 3 | 01 |
//%summary | 从左往右扫一遍，操作数直接输出，运算符按优先级进出栈。
//@d ============ 四条规则 ============
//@d
//@d   遇到 操作数 （0-9）  →  直接输出
//@d   遇到 左括号          →  入栈
//@d   遇到 右括号          →  弹出并输出，直到遇上左括号（左括号弹出但不输出）
//@d   遇到 运算符          →  弹出并输出所有"优先级 >= 自己"的栈顶运算符，然后自己入栈
//@d   扫完之后             →  把栈里剩下的运算符全部弹出输出
//@d
//@d ============ 走一遍 "3+4*2" ============
//@d
//@d   输入    栈（底→顶）   输出
//@d   ─────  ───────────  ──────────
//@d    3       空           3          操作数，直接输出
//@d    +       +            3          栈空，直接入栈
//@d    4       +            34         操作数
//@d    *       + *          34         '*' 比栈顶 '+' 优先级**高**，不弹，入栈
//@d    2       + *          342        操作数
//@d   结束     空           342*+      剩余的依次弹出
//@d
//@d 注意第 4 步：如果来的是 '+'（而不是 '*'），那栈顶的 '+' 优先级**不低于**它，
//@d 就得先弹出输出 —— 这就是"同级从左往右算"的由来。
//@d
//@d 再看一个带括号的 "3*(4+2)"：
//@d
//@d   输入    栈          输出        说明
//@d   ─────  ─────────  ─────────  ──────────────────
//@d    3       空          3
//@d    *       *           3         '*' 比空栈，入
//@d    (       * (         3         左括号无条件入栈
//@d    4       * (         34
//@d    +       * ( +       34        '(' 优先级 0，不弹
//@d    2       * ( +       342
//@d    )       *           342+      弹到 '(' 为止，'(' 弹出但不输出
//@d   结束     空          342+*     弹出剩余的 '*'
//@d
//@d 结果 "342+*" 读回来就是 3*(4+2)=18 —— 括号消失了，
//@d 但运算顺序被完整地"编码"进了后缀式里。

//@s 把中缀表达式 src 转成后缀，写进 dst
//@d 返回值是后缀串的长度，方便调用者直接当字符串用
int InfixToPostfix(const char *src, char *dst)
{
//@s 运算符栈：只存运算符，容量给够就行
    char stack[64];
//@s 栈顶下标，-1 表示空栈（和 02-03 的约定保持一致）
    int top = -1;
//@s 输出位置
    int k = 0;
//@s 扫描下标
    int i;

//@s 从左往右扫一遍
    for (i = 0; src[i] != '\0'; i++)
    {
        char c = src[i];

//@s ① 操作数：直接输出，不进栈
        if (c >= '0' && c <= '9')
        {
            dst[k++] = c;
            continue;
        }

//@s ② 左括号：无条件入栈，它在等它的右括号
        if (c == '(')
        {
            stack[++top] = c;
            continue;
        }

//@s ③ 右括号：把括号里的运算符全部弹出输出
        if (c == ')')
        {
//@d 一直弹到左括号为止。左括号本身弹出后**不输出** ——
//@d 后缀式里没有括号的位置。
            while (top >= 0 && stack[top] != '(')
            {
                dst[k++] = stack[--top];
            }
//@s 把左括号也弹掉（不输出）
            if (top >= 0)
            {
                top--;
            }
            continue;
        }

//@s ④ 运算符：先让"优先级不低于自己"的栈顶元素出去
//@d 这里用的是 >= 而不是 >，这一条决定了同级运算"从左往右"。
//@d 如果写成 >，那么 "3-4+5" 会算成 3-(4+5)，结果就错了。
        while (top >= 0 && priority(stack[top]) >= priority(c))
        {
            dst[k++] = stack[--top];
        }
//@s 自己再入栈
        stack[++top] = c;
    }

//@s ⑤ 扫完了，把栈里剩下的全弹出来
    while (top >= 0)
    {
        dst[k++] = stack[--top];
    }

//@s 收尾：补字符串结束符
    dst[k] = '\0';

//@s 返回长度
    return k;
}
//%end

//%module | 03 | EvalPostfix | EvalPostfix —— 后缀求值 | 2 | 01 |
//%summary | 操作数入栈，遇到运算符就弹出两个算一下再放回去。
//@d ============ 规则只有一条 ============
//@d
//@d   遇到 操作数  →  入栈
//@d   遇到 运算符  →  弹出两个数，算完把结果压回去
//@d   扫完之后     →  栈里只剩一个数，那就是答案
//@d
//@d 没有括号、没有优先级 —— 后缀式已经把运算顺序编码好了。
//@d
//@d ============ 走一遍 "342*+" ============
//@d
//@d   输入   栈（底→顶）    说明
//@d   ─────  ───────────  ──────────────────────
//@d    3      [3]          操作数入栈
//@d    4      [3, 4]       操作数入栈
//@d    2      [3, 4, 2]    操作数入栈
//@d    *      [3, 8]       弹出 4 和 2 → 4*2=8，压回
//@d    +      [11]         弹出 3 和 8 → 3+8=11，压回
//@d   结束    [11]         答案就是 11
//@d
//@d ============ 顺序陷阱：谁减谁 ============
//@d
//@d 弹出两个数时，**先弹出的是右操作数**！
//@d
//@d   "34-" 表示 3-4，扫描到 '-' 时：
//@d      第一次弹出的是 4（右操作数）
//@d      第二次弹出的是 3（左操作数）
//@d      所以计算应该是 b - a，而不是 a - b
//@d
//@d 加法和乘法无所谓（可交换），但减法和除法写反了结果就完全错。
//@d 这是后缀求值最经典的坑。

//@s 计算后缀表达式的值；出错返回 0 并把 ok 置 0
int EvalPostfix(const char *src, int *ok)
{
//@s 操作数栈：存的是数值，不是字符
    int stack[64];
//@s 栈顶下标
    int top = -1;
//@s 扫描下标
    int i;

//@s 先假设一切正常
    *ok = 1;

    for (i = 0; src[i] != '\0'; i++)
    {
        char c = src[i];

//@s ① 操作数：字符转数字后入栈
//@d c - '0' 就是字符到数字的转换：'3' 的 ASCII 是 51，减去 '0'(48) 得 3。
        if (c >= '0' && c <= '9')
        {
            stack[++top] = c - '0';
            continue;
        }

//@s ② 运算符：需要两个操作数
        if (top < 1)
        {
//@d 栈里不足两个数，说明表达式本身有问题（比如 "3+"）。
//@d 后缀式虽然好算，但**合法性检查还是得自己做**。
            *ok = 0;
            return 0;
        }

        {
//@s 先弹出的是右操作数
            int b = stack[top--];
//@s 后弹出的是左操作数
            int a = stack[top--];
//@s 结果
            int r = 0;

//@s 按运算符计算 —— 注意减法和除法的顺序
            switch (c)
            {
            case '+':
                r = a + b;
                break;
            case '-':
//@d 是 a - b（左减右），不是 b - a。写反了 "7 3 -"（=4）会算成 -4。
                r = a - b;
                break;
            case '*':
                r = a * b;
                break;
            case '/':
//@d 除数不能为 0，这里必须挡住，否则程序直接崩。
                if (b == 0)
                {
                    *ok = 0;
                    return 0;
                }
                r = a / b;
                break;
            default:
//@d 后缀式里不该出现别的字符（包括括号）
                *ok = 0;
                return 0;
            }

//@s 结果压回栈里，继续参与后面的运算
            stack[++top] = r;
        }
    }

//@s 扫完之后，栈里应该**正好剩一个数**
    if (top != 0)
    {
//@d 多了说明有多余操作数，空了说明表达式不完整 —— 都算失败。
        *ok = 0;
        return 0;
    }

//@s 栈顶就是答案
    return stack[0];
}
//%end

//%module | 04 | main | main —— 拼成一个能算数的计算器 | 2 | 01,02,03 |
//%summary | 中缀进、后缀转、结果出 —— 三步串起来。
//@d ============ 这两个算法是同一个思想的两次应用 ============
//@d
//@d 它们都靠一个栈，都在回答同一个问题：**"什么时候可以结算"**。
//@d
//@d   转后缀时：新来的运算符优先级不高于栈顶 → 栈顶那个可以先结算了
//@d   求值时  ：遇到运算符 → 前面攒够两个操作数了，可以结算了
//@d
//@d 把"迟到的计算"先存起来，等条件成熟再处理 —— 这个思路后面还会反复出现
//@d （递归、DFS、表达式树都是它）。

//@s 测试若干表达式，逐个对比
static void Try(const char *expr, const char *expectNote)
{
    char postfix[64];
    int ok = 0;
    int v;

    InfixToPostfix(expr, postfix);
    v = EvalPostfix(postfix, &ok);

    if (ok)
    {
        printf("%-12s -> 后缀 %-12s = %d\t%s\n", expr, postfix, v, expectNote);
    }
    else
    {
        printf("%-12s -> 后缀 %-12s = 表达式有误\t%s\n", expr, postfix, expectNote);
    }
}

//@s 主函数
int main(void)
{
//@s 第一组：验证优先级
    printf("=== 优先级 ===\n");
    Try("3+4*2", "先乘后加，= 11");
    Try("3*4+2", "先乘后加，= 14");
    Try("3+4-2", "同级从左往右，= 5");

//@s 第二组：验证括号
//@d 括号在后缀式里消失了，但运算顺序没有丢。
    printf("\n=== 括号 ===\n");
    Try("3*(4+2)", "括号优先，= 18");
    Try("(3+4)*2", "括号优先，= 14");
    Try("(1+2)*(3+4)", "两个括号，= 21");

//@s 第三组：验证减法顺序（最容易写错的地方）
    printf("\n=== 减法与除法（验证左右操作数顺序）===\n");
    Try("7-3", "应该是 4，不是 -4");
    Try("8/2", "应该是 4，不是 0");
    Try("8/2/2", "同级从左往右，= 2");

//@s 第四组：非法输入
//@d 后缀式好算，但不代表可以不做检查。
    printf("\n=== 非法输入 ===\n");
    Try("3+", "操作数不够");
    Try("3 4", "空格不是操作数");
    Try("3/0", "除数为 0");

//@s 正常结束
    return 0;
}
//%end
