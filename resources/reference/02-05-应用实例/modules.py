#%module | 01 | priority | priority —— 运算符优先级 | 1 |
#%summary | 给运算符排个座次，转后缀时靠它决定"谁该先出栈"。
#@d ============ 优先级表 ============
#@d
#@d   运算符  优先级      说明
#@d   ──────  ────────   ──────────────────────
#@d     +        1       同级，从左往右算
#@d     -        1
#@d     *        2       同级，比加减高
#@d     /        2
#@d     (        0       栈内的左括号：优先级最低，谁来了都不弹它
#@d
#@d 为什么左括号在栈内要算 0？
#@d
#@d 因为左括号一旦入栈，就必须等到**遇到右括号**才能弹出。
#@d 把它的优先级设成最低，任何运算符来比较时都会觉得「它比我低，
#@d 不用弹」—— 正好实现了「括号内先算完再说」。
#@d
#@d 这是个小技巧，但很关键：如果左括号优先级设高了，
#@d 它会被后面的运算符弹出去，括号就白写了。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 的函数头上写的是 int priority(char c)，返回什么类型、参数什么类型
#@d   都要标出来；Python 只写 def priority(c)，类型一个字都不用提。
#@d
#@d   C 的 switch 是一条条 case 去比，而且每个 case 后面都得记着写 break，
#@d   漏了 break 就会"穿透"到下一个 case 里去；Python 没有 switch 这个东西，
#@d   改成一串 if，比中一个就 return 走了，压根不会穿透。
#@d
#@d   C 里两个 case 叠在一起（'+' 和 '-' 共用一段代码）表示"两个都走这条"，
#@d   Python 写成 if c in '+-'，一句话就把两个字符都盖住了，
#@d   读起来就是"c 是加号，或者 c 是减号"。

#@s 返回运算符 c 的优先级；不是运算符就返回 -1
#@d 返回 -1 是给调用者一个"这不是运算符"的信号，
#@d 顺便也覆盖了"右括号不该出现在这个比较里"的情况。
def priority(c):
    #@s 加减同级，最低
    if c in '+-':
        return 1
    #@s 乘除同级，比加减高
    if c in '*/':
        return 2
    #@s 栈内的左括号：最低，保证不会被提前弹出
    if c == '(':
        return 0
    #@s 不是运算符（包括右括号、操作数）
    return -1
#%end

#%module | 02 | InfixToPostfix | InfixToPostfix —— 中缀转后缀 | 3 | 01 |
#%summary | 从左往右扫一遍，操作数直接输出，运算符按优先级进出栈。
#@d ============ 四条规则 ============
#@d
#@d   遇到 操作数 （0-9）  →  直接输出
#@d   遇到 左括号          →  入栈
#@d   遇到 右括号          →  弹出并输出，直到遇上左括号（左括号弹出但不输出）
#@d   遇到 运算符          →  弹出并输出所有"优先级 >= 自己"的栈顶运算符，然后自己入栈
#@d   扫完之后             →  把栈里剩下的运算符全部弹出输出
#@d
#@d ============ 走一遍 "3+4*2" ============
#@d
#@d   输入    栈（底→顶）   输出
#@d   ─────  ───────────  ──────────
#@d    3       空           3          操作数，直接输出
#@d    +       +            3          栈空，直接入栈
#@d    4       +            34         操作数
#@d    *       + *          34         '*' 比栈顶 '+' 优先级**高**，不弹，入栈
#@d    2       + *          342        操作数
#@d   结束     空           342*+      剩余的依次弹出
#@d
#@d 注意第 4 步：如果来的是 '+'（而不是 '*'），那栈顶的 '+' 优先级**不低于**它，
#@d 就得先弹出输出 —— 这就是"同级从左往右算"的由来。
#@d
#@d 再看一个带括号的 "3*(4+2)"：
#@d
#@d   输入    栈          输出        说明
#@d   ─────  ─────────  ─────────  ──────────────────
#@d    3       空          3
#@d    *       *           3         '*' 比空栈，入
#@d    (       * (         3         左括号无条件入栈
#@d    4       * (         34
#@d    +       * ( +       34        '(' 优先级 0，不弹
#@d    2       * ( +       342
#@d    )       *           342+      弹到 '(' 为止，'(' 弹出但不输出
#@d   结束     空          342+*     弹出剩余的 '*'
#@d
#@d 结果 "342+*" 读回来就是 3*(4+2)=18 —— 括号消失了，
#@d 但运算顺序被完整地"编码"进了后缀式里。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   出口参数没有了：C 写 InfixToPostfix(expr, postfix)，后缀串是函数往调用者
#@d   递进来的那个数组里塞的；Python 直接 return k, dst，调用者用
#@d   k, postfix = ... 一次就接住了。
#@d
#@d   C 的字符串靠末尾那个 '\0' 才知道到哪儿结束，所以最后必须自己补一句
#@d   dst[k] = '\0'；Python 的字符串自己知道有多长，没有这一步，
#@d   改成 ''.join(dst[:k]) 把字符拼成字符串。
#@d
#@d   C 的 dst[k++] = c、stack[++top] = c 是"赋值顺便加减一"的紧凑写法，
#@d   Python 没有 ++ 和 --，只能拆成两行：先算好下标，再赋值。
#@d
#@d   C 的 for 条件是 src[i] != '\0'，要一个字符一个字符试着走到结尾；
#@d   Python 写 for i in range(len(src))，一上来就知道这个串有多长。

#@s 把中缀表达式 src 转成后缀，写进 dst
#@d 返回值是后缀串的长度，方便调用者直接当字符串用
def InfixToPostfix(src):
    #@s 运算符栈：只存运算符，容量给够就行
    #@d 偷偷说一句：Python 的 list 自带 append 和 pop，本来可以把 top 也扔了；
    #@d 这里故意手写下标，是为了跟 C 版一行一行对得上。
    stack = [''] * 64
    #@s 栈顶下标，-1 表示空栈（和 02-03 的约定保持一致）
    top = -1
    #@s 输出位置
    k = 0
    #@s 输出缓冲：C 里这个是调用者递进来的 dst 数组，Python 自己开一个
    dst = [''] * 64
    #@s 扫描下标
    #@d C 的上一行是 int i; —— 先把 i 声明出来，下面的 for 才能用它。
    #@d Python 的 for 会自己把 i 造出来，所以这句声明没有了。

    #@s 从左往右扫一遍
    for i in range(len(src)):
        c = src[i]

        #@s ① 操作数：直接输出，不进栈
        #@d C 的 dst[k++] = c 一行干两件事：先把 c 写进 k 号格，再让 k 加一。
        #@d Python 没有 ++，老老实实拆成两行，顺序和效果都一模一样。
        if '0' <= c <= '9':
            dst[k] = c
            k += 1
            continue

        #@s ② 左括号：无条件入栈，它在等它的右括号
        #@d C 的 stack[++top] = c 是"top 先加一，再把 c 放进新位置"，
        #@d 加号在前和在后差别很大；Python 拆成 top += 1 和 stack[top] = c 两行，
        #@d 顺序同样不能反，反了就把栈顶原来的东西覆盖掉了。
        if c == '(':
            top += 1
            stack[top] = c
            continue

        #@s ③ 右括号：把括号里的运算符全部弹出输出
        if c == ')':
            #@d 一直弹到左括号为止。左括号本身弹出后**不输出** ——
            #@d 后缀式里没有括号的位置。
            while top >= 0 and stack[top] != '(':
                dst[k] = stack[top]
                top -= 1
                k += 1
            #@s 把左括号也弹掉（不输出）
            if top >= 0:
                top -= 1
            continue

        #@s ④ 运算符：先让"优先级不低于自己"的栈顶元素出去
        #@d 这里用的是 >= 而不是 >，这一条决定了同级运算"从左往右"。
        #@d 如果写成 >，那么 "3-4+5" 会算成 3-(4+5)，结果就错了。
        while top >= 0 and priority(stack[top]) >= priority(c):
            dst[k] = stack[top]
            top -= 1
            k += 1
        #@s 自己再入栈
        top += 1
        stack[top] = c

    #@s ⑤ 扫完了，把栈里剩下的全弹出来
    while top >= 0:
        dst[k] = stack[top]
        top -= 1
        k += 1

    #@s 收尾：补字符串结束符
    #@d C 的字符串全靠末尾那个 '\0' 才知道读到哪里停，dst[k] = '\0' 这句省不得；
    #@d Python 的字符串自己带着长度，没有结束符这回事，所以这句没有了 ——
    #@d 改成把 dst 里攒的字符 join 成一个字符串，作为第二个返回值交出去。
    #@s 返回长度
    return k, ''.join(dst[:k])
#%end

#%module | 03 | EvalPostfix | EvalPostfix —— 后缀求值 | 2 | 01 |
#%summary | 操作数入栈，遇到运算符就弹出两个算一下再放回去。
#@d ============ 规则只有一条 ============
#@d
#@d   遇到 操作数  →  入栈
#@d   遇到 运算符  →  弹出两个数，算完把结果压回去
#@d   扫完之后     →  栈里只剩一个数，那就是答案
#@d
#@d 没有括号、没有优先级 —— 后缀式已经把运算顺序编码好了。
#@d
#@d ============ 走一遍 "342*+" ============
#@d
#@d   输入   栈（底→顶）    说明
#@d   ─────  ───────────  ──────────────────────
#@d    3      [3]          操作数入栈
#@d    4      [3, 4]       操作数入栈
#@d    2      [3, 4, 2]    操作数入栈
#@d    *      [3, 8]       弹出 4 和 2 → 4*2=8，压回
#@d    +      [11]         弹出 3 和 8 → 3+8=11，压回
#@d   结束    [11]         答案就是 11
#@d
#@d ============ 顺序陷阱：谁减谁 ============
#@d
#@d 弹出两个数时，**先弹出的是右操作数**！
#@d
#@d   "34-" 表示 3-4，扫描到 '-' 时：
#@d      第一次弹出的是 4（右操作数）
#@d      第二次弹出的是 3（左操作数）
#@d      所以计算应该是 b - a，而不是 a - b
#@d
#@d 加法和乘法无所谓（可交换），但减法和除法写反了结果就完全错。
#@d 这是后缀求值最经典的坑。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   出口参数 ok 也变成返回值了：C 写 EvalPostfix(postfix, &ok)，算出来的值
#@d   靠 return 带回来、成功失败靠指针写回 ok；Python 写成 return ok, v，
#@d   调用者 ok, v = ... 一次接住两个，不用先声明再传地址。
#@d
#@d   除法这里要特别当心：C 的 a / b 是两个 int 相除，小数部分直接扔掉；
#@d   Python 的 / 一定算出小数，8/2 会变成 4.0，所以这里必须写成 a // b。
#@d   （两个数都是正数时结果和 C 一样；负数时 C 的 / 往 0 截断、
#@d   Python 的 // 往下取整，会差 1，本节的操作数都是正数，碰不到这个坑。）
#@d
#@d   C 里 int b、int a、int r = 0 这些声明 Python 全都不用写，
#@d   下面赋值的时候变量自己就冒出来了；那对大括号 { } 也没有了，
#@d   Python 靠缩进就能划清范围。
#@d
#@d   C 的 switch 每个 case 结尾都得写 break 才停得住，Python 换成 if / elif，
#@d   走完一支自动就出去了，没有 break 要写。

#@s 计算后缀表达式的值；出错返回 0 并把 ok 置 0
def EvalPostfix(src):
    #@s 操作数栈：存的是数值，不是字符
    stack = [0] * 64
    #@s 栈顶下标
    top = -1
    #@s 扫描下标
    #@d C 的上一行是 int i; 声明下标，Python 的 for 自己造 i，这行没有了。
    #@s 先假设一切正常
    ok = 1

    for i in range(len(src)):
        c = src[i]

        #@s ① 操作数：字符转数字后入栈
        #@d c - '0' 就是字符到数字的转换：'3' 的 ASCII 是 51，减去 '0'(48) 得 3。
        #@d Python 的字符不能做减法（'3' - '0' 直接报错），改成 int(c) 一步到位，
        #@d 结果和 C 的 c - '0' 完全一样。
        if '0' <= c <= '9':
            top += 1
            stack[top] = int(c)
            continue

        #@s ② 运算符：需要两个操作数
        if top < 1:
            #@d 栈里不足两个数，说明表达式本身有问题（比如 "3+"）。
            #@d 后缀式虽然好算，但**合法性检查还是得自己做**。
            ok = 0
            return ok, 0

        #@s 先弹出的是右操作数
        #@d C 的 int b = stack[top--] 一行里"先取值、再让 top 减一"，
        #@d Python 没有 --，拆成取值和 top -= 1 两行，先取后减不能颠倒。
        b = stack[top]
        top -= 1
        #@s 后弹出的是左操作数
        a = stack[top]
        top -= 1
        #@s 结果
        #@d C 在这里声明 int r = 0 给个初值，Python 不用声明，
        #@d 下面每个分支都会给 r 赋值，用的时候它肯定已经有了。
        #@d C 还多套了一对大括号想把临时变量的范围缩小，Python 没有块作用域，
        #@d 靠缩进分就够了，所以那对括号不见了。

        #@s 按运算符计算 —— 注意减法和除法的顺序
        if c == '+':
            r = a + b
        elif c == '-':
            #@d 是 a - b（左减右），不是 b - a。写反了 "7 3 -"（=4）会算成 -4。
            r = a - b
        elif c == '*':
            r = a * b
        elif c == '/':
            #@d 除数不能为 0，这里必须挡住，否则程序直接崩。
            #@d Python 里 a // 0 会抛 ZeroDivisionError，一样是崩，也得先判。
            if b == 0:
                ok = 0
                return ok, 0
            r = a // b
        else:
            #@d 后缀式里不该出现别的字符（包括括号）
            ok = 0
            return ok, 0

        #@s 结果压回栈里，继续参与后面的运算
        top += 1
        stack[top] = r

    #@s 扫完之后，栈里应该**正好剩一个数**
    if top != 0:
        #@d 多了说明有多余操作数，空了说明表达式不完整 —— 都算失败。
        ok = 0
        return ok, 0

    #@s 栈顶就是答案
    return ok, stack[0]
#%end

#%module | 04 | main | main —— 拼成一个能算数的计算器 | 2 | 01,02,03 |
#%summary | 中缀进、后缀转、结果出 —— 三步串起来。
#@d ============ 这两个算法是同一个思想的两次应用 ============
#@d
#@d 它们都靠一个栈，都在回答同一个问题：**"什么时候可以结算"**。
#@d
#@d   转后缀时：新来的运算符优先级不高于栈顶 → 栈顶那个可以先结算了
#@d   求值时  ：遇到运算符 → 前面攒够两个操作数了，可以结算了
#@d
#@d 把"迟到的计算"先存起来，等条件成熟再处理 —— 这个思路后面还会反复出现
#@d （递归、DFS、表达式树都是它）。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 的 Try 一进门要写 char postfix[64]; int ok = 0; int v;，
#@d   Python 不用声明，下面两个赋值语句直接把 postfix、ok、v 造出来。
#@d
#@d   C 用 printf 的 %-12s 让字符串左对齐占满 12 格，
#@d   Python 的 f-string 写成 {expr:<12}，那个小于号就是"左对齐"。
#@d
#@d   C 的 printf 得自己写 \n 才换行，Python 的 print 打完了自动换行，
#@d   所以 C 那些 "=== 优先级 ===" 后面带的 \n 在 Python 里全都不用了。
#@d
#@d   C 的 int main(void) 由运行时自动调用，Python 没有"入口函数"这回事，
#@d   固定写 if __name__ == '__main__':，意思是"直接运行这个文件才跑，
#@d   被别人 import 的时候不跑"。

#@s 测试若干表达式，逐个对比
def Try(expr, expectNote):
    #@s 中缀转后缀：C 靠出口参数 postfix 带回串，Python 用两个变量接
    #@d 第一个返回值 k 是后缀串的长度（就是 C 的返回值），这里用不上，
    #@d 只要后面那个 postfix。
    k, postfix = InfixToPostfix(expr)
    #@s 后缀求值：ok 也从出口参数变成了第一个返回值
    ok, v = EvalPostfix(postfix)

    if ok:
        print(f'{expr:<12} -> 后缀 {postfix:<12} = {v}\t{expectNote}')
    else:
        print(f'{expr:<12} -> 后缀 {postfix:<12} = 表达式有误\t{expectNote}')

#@s 主函数
if __name__ == '__main__':
    #@s 第一组：验证优先级
    print('=== 优先级 ===')
    Try('3+4*2', '先乘后加，= 11')
    Try('3*4+2', '先乘后加，= 14')
    Try('3+4-2', '同级从左往右，= 5')

    #@s 第二组：验证括号
    #@d 括号在后缀式里消失了，但运算顺序没有丢。
    print('\n=== 括号 ===')
    Try('3*(4+2)', '括号优先，= 18')
    Try('(3+4)*2', '括号优先，= 14')
    Try('(1+2)*(3+4)', '两个括号，= 21')

    #@s 第三组：验证减法顺序（最容易写错的地方）
    print('\n=== 减法与除法（验证左右操作数顺序）===')
    Try('7-3', '应该是 4，不是 -4')
    Try('8/2', '应该是 4，不是 0')
    Try('8/2/2', '同级从左往右，= 2')

    #@s 第四组：非法输入
    #@d 后缀式好算，但不代表可以不做检查。
    print('\n=== 非法输入 ===')
    Try('3+', '操作数不够')
    Try('3 4', '空格不是操作数')
    Try('3/0', '除数为 0')

    #@s 正常结束
    #@d C 的 main 结尾有一句 return 0; 表示"正常退出"，Python 脚本跑到
    #@d 文件末尾就结束了，这一行不用写，想中途退出才用 sys.exit()。
#%end
