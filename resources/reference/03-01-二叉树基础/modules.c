/*
 * ============================================================================
 *  数据结构研习社 —— 03 树 / 03-01 二叉树基础
 * ============================================================================
 *
 *  二叉树：每个结点最多两个孩子，而且左右是**有区别的**（左孩子和右孩子
 *  不能互换，这一点和"度为 2 的树"不一样）。
 *
 *  树的所有操作几乎都长一个样：**递归**。先处理根、还是先处理左右子树，
 *  顺序换一下就是不同的遍历。
 *
 *      先序：根 → 左 → 右        （复制一棵树、输出前缀表达式）
 *      中序：左 → 根 → 右        （二叉搜索树的中序是有序的！）
 *      后序：左 → 右 → 根        （释放内存、算表达式值）
 *      层序：一层一层来          （需要队列）
 *
 *  标记约定同前（本文件本身可编译）。
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

//%module | 01 | typedef | 头文件与 typedef | 1 |
//%summary | 一个数据域 + 左右两个孩子指针。
//@d ============ 二叉树结点长什么样 ============
//@d
//@d           data
//@d          ┌────┐
//@d          │ A  │
//@d          └─┬──┘
//@d        left │ right
//@d         ┌───┴───┐
//@d        ▼       ▼
//@d      ┌────┐  ┌────┐
//@d      │ B  │  │ C  │
//@d      └────┘  └────┘
//@d
//@d 每个结点除了存数据，还要存**两个孩子在哪**。
//@d 没有孩子就是 NULL —— 所以"空指针"在树里是个正常状态，到处都是。
//@d
//@d ============ 和链表的区别 ============
//@d
//@d   链表结点：一个 next，一条链走到底          → 线性
//@d   树结点  ：一个 left、一个 right，两个岔路   → 层次
//@d
//@d 多出来的这个指针，正是"树"能表达层次关系的原因。

//@s 数据元素类型：换成 int 也只要改这一行
typedef char ElemType;

//@s 二叉树结点
typedef struct TNode
{
//@s 数据域
    ElemType data;
//@s 左孩子
    struct TNode *left;
//@s 右孩子
    struct TNode *right;
} TNode, *BinTree;

//@s 状态码（沿用前面的约定）
#define OK 1
#define ERROR 0
typedef int Status;
//%end

//%module | 02 | NewNode | NewNode —— 造一个结点 | 1 | 01 |
//%summary | 申请内存、填数据、两个孩子置空。
//@d ============ 和链表的 creatNode 一模一样 ============
//@d
//@d 区别只有一点：链表要置一个 next，树要置**两个**指针（left 和 right）。
//@d 少置一个就是野指针，遍历时随机崩溃 —— 而且往往不在出错的那一行崩，
//@d 找起来很痛苦。
//@d
//@d 所以这里用 malloc 之后立刻把两个指针都写上 NULL，不给野指针留机会。
//@d （用 calloc 也可以，它会自动清零，但显式写出来意图更清楚。）

//@s 造一个值为 e 的孤立结点
BinTree NewNode(ElemType e)
{
//@s 申请一块 TNode 大小的内存
    BinTree t = (BinTree)malloc(sizeof(TNode));
//@s 满内存要挡住
    if (t == NULL)
    {
        printf("内存分配失败\n");
        exit(1);
    }
//@s 填数据
    t->data = e;
//@s 两个孩子都置空 —— 树里 NULL 表示"没有孩子"
    t->left = NULL;
    t->right = NULL;
//@s 返回
    return t;
}
//%end

//%module | 03 | CreateTree | CreateTree —— 先序建树 | 2 | 01,02 |
//%summary | 按"先序 + # 表示空"的序列递归建树。
//@d ============ 用一段字符描述一棵树 ============
//@d
//@d 直接写代码一棵一棵拼结点太啰嗦，所以约定一种**先序序列**：
//@d
//@d   先输出根，再递归输出左子树，再递归输出右子树；
//@d   遇到空孩子就输出一个 '#'。
//@d
//@d 比如这棵树：
//@d
//@d           A
//@d         /   \
//@d        B     C
//@d       / \     \
//@d      D   E     F
//@d
//@d 它的先序序列就是：**A B D # # E # # C # F # #**
//@d
//@d 读法：A 是根；接着 B 是 A 的左孩子；D 是 B 的左孩子；
//@d 两个 # 说明 D 没有孩子；回到 B，E 是它的右孩子…… 一路递归下去。
//@d
//@d ============ 为什么用先序 ============
//@d
//@d 因为**先序序列的第一个一定是根**，读完根立刻知道接下来要去建左子树。
//@d 换成中序或后序就没法这样一边读一边建（得先把整串读完才能定位根）。
//@d
//@d 这也是"先序遍历可以用来序列化一棵树"的原因。

//@s i 是当前读到序列的哪一位 —— 必须传指针，因为递归时要"共享进度"
//@d 如果按值传 i，每个递归层都有自己的 i，整串就被重复读了。
BinTree CreateTree(const char *s, int *i)
{
//@s 取出当前字符并把游标往后挪
    char c = s[(*i)++];

//@s '#' 表示这里没有结点（空孩子），直接返回 NULL
    if (c == '#' || c == '\0')
    {
        return NULL;
    }

//@s 建根结点
    BinTree t = NewNode(c);

//@s 递归建左子树 —— 紧接着的那些字符就是左子树的先序序列
    t->left = CreateTree(s, i);

//@s 再递归建右子树
//@d 这一步看起来"什么都没做"，其实全靠 (*i) 在递归过程中被一路推进 ——
//@d 左子树消费掉多少个字符，右子树就从下一个位置接着读。
    t->right = CreateTree(s, i);

//@s 返回这棵子树
    return t;
}
//%end

//%module | 04 | PreOrder | PreOrder —— 先序遍历 | 1 | 01 |
//%summary | 根 → 左 → 右：先打印自己，再管孩子。
//@d ============ 递归三行就够 ============
//@d
//@d   先序：打印自己 → 递归左 → 递归右
//@d
//@d 走一遍这棵树：
//@d
//@d           A
//@d         /   \
//@d        B     C
//@d       / \     \
//@d      D   E     F
//@d
//@d   访问 A → 进左子树：访问 B → 进左子树：访问 D → D 无孩子，回退
//@d            → 进 B 的右子树：访问 E → E 无孩子，回退
//@d        → 进右子树：访问 C → C 没有左孩子 → 进右子树：访问 F
//@d
//@d   结果：A B D E C F
//@d
//@d ============ 递归为什么能"回退" ============
//@d
//@d 函数调用栈帮你记着"我走到哪儿了"。访问完 D 返回时，程序自动回到
//@d "B 的左子树刚处理完"这个位置，接着去处理 B 的右子树。
//@d
//@d 递归的写法之所以短，就是把这份"记账"交给了调用栈。

//@s 先序遍历并打印
void PreOrder(BinTree T)
{
//@s 空树是递归的出口
//@d 树的每个操作几乎都以这一句开头。漏了它，遇到空结点解引用就会崩。
    if (T == NULL)
    {
        return;
    }

//@s 先处理根（先序的关键就在这一句的位置）
    printf("%c ", T->data);

//@s 再递归左子树
    PreOrder(T->left);

//@s 最后递归右子树
    PreOrder(T->right);
}
//%end

//%module | 05 | InOrder | InOrder —— 中序遍历 | 1 | 01 |
//%summary | 左 → 根 → 右：先走完左边，再打印自己。
//@d ============ 只把打印挪了个位置 ============
//@d
//@d 和先序相比，代码几乎一样，只是 printf 从"最前面"挪到了"中间"：
//@d
//@d   先序：printf → 递归左 → 递归右
//@d   中序：递归左 → printf → 递归右
//@d
//@d 就这一挪，输出的含义完全不同。还是那棵树：
//@d
//@d           A
//@d         /   \
//@d        B     C
//@d       / \     \
//@d      D   E     F
//@d
//@d   先走完左边：D、B、E（注意 B 夹在中间）→ 再 A → 再右边：C、F
//@d   结果：D B E A C F
//@d
//@d ============ 中序的地位 ============
//@d
//@d 中序遍历有一个别的遍历都没有的性质：
//@d **对二叉搜索树做中序遍历，结果一定是递增有序的。**
//@d
//@d 所以在接下来 BST 那一节里，验证一棵树对不对，最省事的办法就是中序打一遍。
//@d 反过来，如果题目给的序列是有序的，那多半是在提示你"用中序"。

//@s 中序遍历并打印
void InOrder(BinTree T)
{
//@s 空树返回
    if (T == NULL)
    {
        return;
    }

//@s 先递归左子树 —— 先把左边走到底
    InOrder(T->left);

//@s 再打印自己（中序的关键位置）
    printf("%c ", T->data);

//@s 最后递归右子树
    InOrder(T->right);
}
//%end

//%module | 06 | PostOrder | PostOrder —— 后序遍历 | 1 | 01 |
//%summary | 左 → 右 → 根：孩子都处理完，最后才轮到自己。
//@d ============ 后序的独特价值 ============
//@d
//@d   后序：递归左 → 递归右 → printf
//@d
//@d 还是那棵树，输出是：D E B F C A（根 A 跑到最后）
//@d
//@d 为什么"根在最后"很有用？因为凡是**必须等孩子处理完才能处理自己**
//@d 的事情，都得用后序：
//@d
//@d   ① 释放整棵树 —— 你要是先 free 了根，就再也找不到孩子了
//@d   ② 计算表达式树 —— 得先算出左右子树的值，才能算运算符
//@d   ③ 统计树的高度 —— 得先知道左右子树多高
//@d
//@d 这三个操作在写法上有共同点：都是**先递归，拿到返回值，再处理自己**。
//@d 下面的 main 里会用到第 ① 个。

//@s 后序遍历并打印
void PostOrder(BinTree T)
{
//@s 空树返回
    if (T == NULL)
    {
        return;
    }

//@s 先递归左子树
    PostOrder(T->left);

//@s 再递归右子树
    PostOrder(T->right);

//@s 最后才打印自己（后序的关键位置）
    printf("%c ", T->data);
}
//%end

//%module | 07 | LevelOrder | LevelOrder —— 层序遍历 | 2 | 01 |
//%summary | 一层一层来，靠队列把"下一层"排好队。
//@d ============ 递归做不了层序 ============
//@d
//@d 前三种遍历都是"一路往下钻"，递归天然合适。
//@d 层序要求**横向**推进：先访问第 1 层所有结点，再第 2 层……
//@d 递归的调用栈是纵向的，帮不上忙，得另外借一个**队列**。
//@d
//@d 做法：
//@d
//@d   ① 根入队
//@d   ② 循环：出队一个 → 打印它 → 把它的左右孩子依次入队
//@d   ③ 队空就结束
//@d
//@d 走一遍：
//@d
//@d   队列 [A]        → 出 A，打印 A，入 B、C          队列 [B C]
//@d   队列 [B C]      → 出 B，打印 B，入 D、E          队列 [C D E]
//@d   队列 [C D E]    → 出 C，打印 C，入 F（没有左孩子）队列 [D E F]
//@d   ... → 结果：A B C D E F
//@d
//@d 关键点：**入队顺序决定了下一层的访问顺序**，所以先左后右不能反。
//@d
//@d 这里为了不依赖 02-04 的队列代码，用一个数组加两个下标直接当队列用。

//@s 层序遍历并打印
void LevelOrder(BinTree T)
{
//@s 自己搭一个简单队列：定长数组 + 头尾下标
//@d 树最多几十个结点，开 64 个位置绰绰有余。
    BinTree q[64];
//@s 队头下标（出队处）
    int front = 0;
//@s 队尾下标（入队处）
    int rear = 0;

//@s 空树直接返回
    if (T == NULL)
    {
        return;
    }

//@s ① 根入队
    q[rear++] = T;

//@s ② 队列不空就一直转
    while (front < rear)
    {
//@s 出队一个并打印
        BinTree cur = q[front++];
        printf("%c ", cur->data);

//@s ③ 左孩子入队 —— 必须先左后右，否则同一层的顺序会颠倒
        if (cur->left != NULL)
        {
            q[rear++] = cur->left;
        }
//@s 右孩子入队
        if (cur->right != NULL)
        {
            q[rear++] = cur->right;
        }
    }
}
//%end

//%module | 08 | FreeTree | FreeTree —— 释放整棵树 | 2 | 01 |
//%summary | 后序释放：先孩子、后自己。顺序反了就找不到孩子，内存直接泄漏。
//@d ============ 为什么必须是后序 ============
//@d
//@d 释放一棵树，直觉上会想"从根开始 free"。但 free 掉根之后，
//@d 你就**再也找不到它的孩子了** —— 那些结点谁也没记着地址，永远收不回来。
//@d
//@d 所以正确顺序只有一个：**先把左右子树都释放干净，最后才 free 自己**。
//@d 这恰好就是后序遍历的顺序。
//@d
//@d 凡是"必须等孩子处理完才能处理自己"的操作，都得用后序 ——
//@d 释放内存、算表达式树、求树高，都是这一类。

//@d 先释放根就找不到孩子了，所以一定是"先孩子、后自己"。
void FreeTree(BinTree T)
{
//@s 空树返回
    if (T == NULL)
    {
        return;
    }
//@s 先把左子树整个释放掉
    FreeTree(T->left);
//@s 再释放右子树
    FreeTree(T->right);
//@s 最后才释放自己
    free(T);
}

//%end

//%module | 09 | main | main —— 四种遍历摆在一起 | 2 | 01,02,03,04,05,06,07,08 |
//%summary | 同一棵树，四种遍历给出四个不同的序列。
//@d ============ 一眼看清四种遍历的差别 ============
//@d
//@d 用的是同一棵树：
//@d
//@d           A
//@d         /   \
//@d        B     C
//@d       / \     \
//@d      D   E     F
//@d
//@d 先序  A B D E C F      （根最先）
//@d 中序  D B E A C F      （根居中）
//@d 后序  D E B F C A      （根最后）
//@d 层序  A B C D E F      （一层一层）
//@d
//@d 前三个只差 printf 的位置，序列却完全不同 —— 这就是递归顺序的威力。

//@s 主函数
int main(void)
{
//@s 先序序列：# 表示空孩子
    const char *s = "ABD##E##C#F##";
//@s 读序列用的游标
    int i = 0;
//@s 树根
    BinTree root;

//@s 打印建树用的序列，方便对照
    printf("建树序列(先序, #=空): %s\n\n", s);

//@s 建树
    root = CreateTree(s, &i);
    printf("建树完成，共读取 %d 个字符\n\n", i);

//@s 四种遍历各来一遍
    printf("先序 (根 左 右): ");
    PreOrder(root);
    printf("\n");

    printf("中序 (左 根 右): ");
    InOrder(root);
    printf("\n");

    printf("后序 (左 右 根): ");
    PostOrder(root);
    printf("\n");

    printf("层序 (一层一层): ");
    LevelOrder(root);
    printf("\n");

//@s 释放
//@d 每个 malloc 都要有对应的 free —— 树也一样，只是顺序必须是后序。
    FreeTree(root);
    printf("\n整棵树已释放（后序：先孩子后自己）\n");

//@s 正常结束
    return 0;
}
//%end
