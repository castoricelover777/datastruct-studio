/*
 * ============================================================================
 *  数据结构研习社 —— 03 树 / 03-02 二叉搜索树
 * ============================================================================
 *
 *  二叉搜索树（BST）在二叉树的基础上加一条规矩：
 *
 *      左子树的所有结点 < 根 < 右子树的所有结点
 *
 *  这一条规矩带来两个后果：
 *
 *    · 查找可以"一路比较、每次扔掉一半"，平均 O(log n)（树越平衡越快）
 *    · **中序遍历一定得到递增序列** —— 这是验证 BST 对不对的最快办法
 *
 *  代价是：删除比较麻烦（要分三种情况），而且树可能退化成链表。
 *
 *  标记约定同前（本文件本身可编译）。
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>

//%module | 01 | typedef | 头文件与 typedef | 1 |
//%summary | 结构还是二叉树，但多了一条「左 < 根 < 右」的规矩。
//@d ============ 什么是二叉搜索树 ============
//@d
//@d          8
//@d        /   \
//@d       3     10
//@d      / \      \
//@d     1   6      14
//@d        / \    /
//@d       4   7  13
//@d
//@d 每个结点都满足：**左边的都比它小，右边的都比它大**。
//@d 注意是"所有结点"而不只是"直接孩子"：比如 13 在 14 的左边，
//@d 它比 14 小；同时 13 比 10 大，所以它在 10 的右子树里。
//@d
//@d ============ 这条规矩带来什么 ============
//@d
//@d ① **查找像猜数字**：拿目标值和当前结点比，小了就往左、大了就往右，
//@d    每走一步就扔掉一半的候选。这就是"二叉搜索"这个名字的由来。
//@d
//@d ② **中序遍历一定递增**：
//@d
//@d      1  3  4  6  7  8  10  13  14
//@d
//@d    所以想检查一棵树是不是合法 BST，最省事的办法就是中序打一遍，
//@d    看它是不是有序的。
//@d
//@d ============ 也要知道它的坏处 ============
//@d
//@d 如果按 1 2 3 4 5 的顺序插入，树会变成一条"右斜链"：
//@d
//@d      1
//@d       \
//@d        2
//@d         \
//@d          3   ...
//@d
//@d 这时候查找退化成 O(n)，和链表一样慢。下一节的 AVL 树就是来解决这个的。

//@s 数据元素类型
typedef int ElemType;

//@s 结点结构：和普通二叉树完全一样
//@d 差异不在结构上，而在"怎么用它" —— 这是数据结构里很常见的情况：
//@d 同一种结构，加不同的约束，就是不同的数据结构。
typedef struct TNode
{
//@s 数据域
    ElemType data;
//@s 左子树（都比它小）
    struct TNode *left;
//@s 右子树（都比它大）
    struct TNode *right;
} TNode, *BinTree;

//@s 状态码
#define OK 1
#define ERROR 0
typedef int Status;
//%end

//%module | 02 | NewNode | NewNode —— 造一个结点 | 1 | 01 |
//%summary | 和二叉树一样：申请、填值、两个孩子置空。
//@d ============ 一样的代码，不一样的含义 ============
//@d
//@d 这个函数和 03-01 里的 NewNode 一模一样，不多解释。
//@d 要说的是**它在 BST 里的位置**：新结点永远是被"挂到某个空位置上"的，
//@d 挂上去之后它就成了叶子 —— BST 的插入从不改动已有结点之间的关系。

//@s 造一个值为 x 的孤立结点
BinTree NewNode(ElemType x)
{
//@s 申请内存
    BinTree t = (BinTree)malloc(sizeof(TNode));
//@s 挡住分配失败
    if (t == NULL)
    {
        printf("内存分配失败\n");
        exit(1);
    }
//@s 填值
    t->data = x;
//@s 两个孩子置空 —— 新结点一定是叶子
    t->left = NULL;
    t->right = NULL;
//@s 返回
    return t;
}
//%end

//%module | 03 | BSTFind | BSTFind —— 查找 | 2 | 01 |
//%summary | 比当前结点小就往左、大就往右，一路扔掉一半候选。
//@d ============ 查找的路径 ============
//@d
//@d 在以 8 为根的 BST 里找 7：
//@d
//@d          8         7 < 8  → 往左
//@d        /   \
//@d       3     10     7 > 3  → 往右
//@d      / \      \
//@d     1   6      14  7 > 6  → 往右
//@d        / \    /
//@d       4   7  13    相等！找到了
//@d
//@d 一共比较了 4 次。如果这是有序数组用二分，也要 log 次 ——
//@d **BST 的查找本质就是"写成树的二分查找"**。
//@d
//@d ============ 递归还是循环 ============
//@d
//@d 递归写起来最贴题意（三行），缺点是树很深时会消耗调用栈。
//@d 这里两个版本都给：递归看思路，循环看工程。
//@d 循环版其实更好 —— 尾递归本来就能直接改成 while。

//@s 递归版：返回找到的结点，找不到返回 NULL
BinTree BSTFind(BinTree T, ElemType x)
{
//@s 走到空说明整棵树都找遍了，没有
    if (T == NULL)
    {
        return NULL;
    }

//@s 目标更小 → 只可能在左子树
    if (x < T->data)
    {
        return BSTFind(T->left, x);
    }
//@s 目标更大 → 只可能在右子树
    if (x > T->data)
    {
        return BSTFind(T->right, x);
    }

//@s 相等 —— 命中，返回这个结点
//@d 返回结点地址而不是 1/0，是因为调用者往往还要用到它（比如接着删除、
//@d 或者读它的其他字段）。
    return T;
}

//@s 循环版：功能相同，但不占调用栈
//@d 尾递归可以直接改写成循环 —— 这是在工程代码里更常见的写法。
BinTree BSTFindIter(BinTree T, ElemType x)
{
//@s 一路往下走，直到走到空或者命中
    while (T != NULL && T->data != x)
    {
//@s 比当前小就往左，否则往右 —— 一次比较决定一半的去留
        T = (x < T->data) ? T->left : T->right;
    }
//@s 循环结束时 T 要么是要找的结点，要么是 NULL
    return T;
}
//%end

//%module | 04 | BSTInsert | BSTInsert —— 插入 | 2 | 01,02,03 |
//%summary | 像查找一样走下去，走到空位置就把新结点挂上去。
//@d ============ 插入的路径 ============
//@d
//@d 往上面那棵树里插 5：
//@d
//@d          8         5 < 8  → 往左
//@d        /   \
//@d       3     10     5 > 3  → 往右
//@d      / \      \
//@d     1   6      14  5 < 6  → 往左
//@d        / \    /
//@d       4   7  13    ← 这个位置是空的，就插在 6 的左孩子
//@d
//@d          8
//@d        /   \
//@d       3     10
//@d      / \      \
//@d     1   6      14
//@d        / \    /
//@d       4   5  13
//@d          ↑ 新来的
//@d
//@d 插入和查找走的是**完全相同的路径** —— 区别只在"走到空的时候"：
//@d 查找返回 NULL，插入则造一个结点挂上去。
//@d
//@d ============ 关于重复值 ============
//@d
//@d 如果插入的值已经存在怎么办？本实现选择"什么都不做"。
//@d 也可以改成计数 +1、或者规定"相等的往右走"。
//@d 关键是**要有一条明确的规矩**，不能今天不动明天往右 —— 那样中序就不再有序了。

//@s 插入 x，返回新的树根
//@d 为什么返回树根？因为空树插入时根本身会变，调用者必须接收返回值：
//@d     T = BSTInsert(T, x);
BinTree BSTInsert(BinTree T, ElemType x)
{
//@s 走到空位置 → 这就是新结点该待的地方
    if (T == NULL)
    {
        return NewNode(x);
    }

//@s 比当前小 → 递归插到左子树，并把结果接回左指针
    if (x < T->data)
    {
        T->left = BSTInsert(T->left, x);
    }
//@s 比当前大 → 插到右子树
    else if (x > T->data)
    {
        T->right = BSTInsert(T->right, x);
    }
//@s 相等 → 已经存在，什么也不做（也可以改成计数）
//@d 注意这里没有 else 分支也不返回，直接落到最后的 return T。
//@d 千万别写成"相等就插到右边" —— 那样重复值会越堆越多，中序也不再严格有序。

//@s 返回（可能被修改过的）根
    return T;
}
//%end

//%module | 05 | FindMin | FindMin —— 找最小值 | 1 | 01 |
//%summary | 从根一路往左走到底，最左下的那个就是最小。
//@d ============ 为什么最小值一定在"最左边" ============
//@d
//@d 因为 BST 的规矩是"左边都比根小"。所以：
//@d
//@d   · 任何一个结点，只要它有左孩子，那左孩子一定比它小
//@d   · 所以最小值不可能在"有左孩子的结点"上
//@d   · 一路往左走到底，那个没有左孩子的结点就是最小
//@d
//@d 走的过程（还是那棵树）：
//@d
//@d   8 → 左孩子 3 → 左孩子 1 → 1 没有左孩子，停
//@d   最小值是 1
//@d
//@d 最大值对称：一路往右走到没有右孩子为止。
//@d
//@d ============ 这个函数在删除时会用到 ============
//@d
//@d 删除有两个孩子的结点时，需要找一个"替身"来顶替被删的位置。
//@d 这个替身有两个合法选择：
//@d
//@d   ① 右子树的**最小值**（它比右子树其它都小，接到左边也不会破坏规矩）
//@d   ② 左子树的**最大值**
//@d
//@d 本实现用 ①。所以 FindMin 不是一个"顺便讲讲"的辅助函数，
//@d 它是删除算法的组成部分。

//@s 返回最小结点；空树返回 NULL
BinTree FindMin(BinTree T)
{
//@s 空树直接返回
    if (T == NULL)
    {
        return NULL;
    }
//@s 一路往左，直到没有左孩子
//@d 用循环而不是递归：这里没有"回退"的需求，循环更直白也更快。
    while (T->left != NULL)
    {
        T = T->left;
    }
//@s 停下来时 T 就是最小结点
    return T;
}

//@s 返回最大结点；空树返回 NULL
BinTree FindMax(BinTree T)
{
//@s 空树
    if (T == NULL)
    {
        return NULL;
    }
//@s 一路往右
    while (T->right != NULL)
    {
        T = T->right;
    }
//@s 停下来的就是最大
    return T;
}
//%end

//%module | 06 | BSTDelete | BSTDelete —— 删除 | 3 | 01,04,05 |
//%summary | 分三种情况：叶子直接删、一个孩子顶上来、两个孩子找右子树最小值替代。
//@d ============ 三种情况 ============
//@d
//@d **情况一：要删的是叶子**（没有孩子）
//@d
//@d       ... 6               ... 6
//@d          / \      →         /
//@d         4   7              4        直接拿掉 7，什么都不用管
//@d
//@d **情况二：只有一个孩子**
//@d
//@d       14                13
//@d      /         →       /         拿孩子顶替自己的位置
//@d    13                 11
//@d   /
//@d  11
//@d
//@d **情况三：有两个孩子** —— 麻烦在这里
//@d
//@d          8                    10
//@d        /   \                /    \
//@d       3     10     →       3      14
//@d      / \      \           / \    /
//@d     1   6      14         1   6  13
//@d                                     ← 13 还在，位置没变
//@d
//@d 删 8 不能直接把 8 拿掉 —— 那样左右两棵子树就没法拼成一棵树了。
//@d 办法是**找个替身**：用右子树里最小的那个（10）的值覆盖 8，
//@d 然后再去右子树里把那个"10 号结点"删掉（它最多只有一个孩子，好删）。
//@d
//@d ============ 为什么替身是"右子树最小值" ============
//@d
//@d 因为它比右子树里所有结点都小、又比左子树里所有结点都大 ——
//@d 放在根的位置正好满足 BST 的规矩。
//@d 换成左子树的最大值也可以，对称的。
//@d
//@d ============ 写这段代码的关键 ============
//@d
//@d 一定要**先递归、再把返回值接回去**：
//@d
//@d     T->left = BSTDelete(T->left, x);
//@d
//@d 因为删掉左子树的根之后，左子树的根可能换人了，必须重新接上。
//@d 漏掉这个赋值是这一节最常见的 bug。

//@s 删除值为 x 的结点，返回新的树根
//@d 同样要接收返回值：T = BSTDelete(T, x);
BinTree BSTDelete(BinTree T, ElemType x)
{
//@s 被删结点
    BinTree tmp;

//@s 走到空也没找到 —— 什么也不做
    if (T == NULL)
    {
        return NULL;
    }

//@s 还没找到：继续往左
    if (x < T->data)
    {
//@d 这一句的赋值千万不能省。删完之后左子树的根可能变了，必须接回来。
        T->left = BSTDelete(T->left, x);
    }
//@s 继续往右
    else if (x > T->data)
    {
        T->right = BSTDelete(T->right, x);
    }
//@s 找到了，就是当前这个结点
    else
    {
//@s 情况三：两个孩子都在
        if (T->left != NULL && T->right != NULL)
        {
//@s 找右子树里的最小值当替身
            tmp = FindMin(T->right);
//@s 用替身的值覆盖自己
//@d 只改值不改结构 —— 这是最省事的做法（如果结点里还有别的数据，
//@d 别忘了也一起搬过来）。
            T->data = tmp->data;
//@s 再去右子树里把那个替身结点删掉
//@d 它能走到这里，说明它一定没有左孩子（一路向左走到底的），
//@d 所以下一轮递归最多只有一个孩子，问题规模缩小了。
            T->right = BSTDelete(T->right, tmp->data);
        }
//@s 情况一 / 二：至多一个孩子
        else
        {
//@s 先记住要被 free 的结点
            tmp = T;
//@s 让唯一的孩子（或者 NULL）顶替上来
//@d 左孩子存在就用左孩子，否则用右孩子。两个都没有时
//@d 表达式的结果正好是 NULL —— 一个式子覆盖了两种情况。
            T = (T->left != NULL) ? T->left : T->right;
//@s 释放被删结点
            free(tmp);
        }
    }

//@s 返回（可能已经换人的）根
    return T;
}
//%end

//%module | 07 | InOrder | InOrder —— 中序验证 | 1 | 01 |
//%summary | 把 BST 打成递增序列 —— 验证结构有没有被破坏的最快办法。
//@d ============ 为什么单给它一个模块 ============
//@d
//@d 中序遍历在普通二叉树里只是"三种遍历之一"，但在 BST 里它有个特殊身份：
//@d **它输出的一定是递增序列**。
//@d
//@d 所以写 BST 的时候要养成一个习惯：每次插入或删除之后，中序打一遍。
//@d
//@d   · 输出有序 → 结构没坏
//@d   · 哪里乱了序 → 那一步的插入或者删除写错了
//@d
//@d 这比"盯着树看"可靠得多。树一深，人是看不出问题的；
//@d 但有序性一乱，一眼就能发现。

//@s 中序遍历（把 BST 打成有序序列）
void InOrder(BinTree T)
{
//@s 空树返回
    if (T == NULL)
    {
        return;
    }
//@s 左
    InOrder(T->left);
//@s 根
    printf("%d ", T->data);
//@s 右
    InOrder(T->right);
}
//%end

//%module | 08 | FreeTree | FreeTree —— 释放整棵树 | 2 | 01 |
//%summary | 后序释放：先孩子、后自己。
//@d ============ 顺序不能反 ============
//@d
//@d free 掉根之后，就再也找不到它的孩子了 —— 那些内存永远收不回来。
//@d 所以只能"先把左右子树都清干净，最后 free 自己"，也就是后序。
//@d
//@d 同类的还有算表达式树的值、求树高 —— 凡是"必须等孩子处理完"的操作都用后序。

//@s 后序释放整棵树
void FreeTree(BinTree T)
{
//@s 空树返回
    if (T == NULL)
    {
        return;
    }
//@s 先孩子
    FreeTree(T->left);
    FreeTree(T->right);
//@s 后自己
    free(T);
}
//%end

//%module | 09 | main | main —— 把 BST 跑一遍 | 2 | 01,02,03,04,05,06,07,08 |
//%summary | 插入、查找、找最值、删三种情况，最后用中序验证有序性。
//@d ============ 用中序验证 BST 对不对 ============
//@d
//@d 这一节最该养成的习惯：**每次改完 BST，中序打一遍**。
//@d
//@d 只要输出是有序的，结构就一定没被破坏；
//@d 反过来，如果哪里乱了序，说明删除或插入写错了。
//@d
//@d 比"盯着树看"可靠得多 —— 树一深，人是看不出问题的。

//@s 主函数
int main(void)
{
//@s 树根，空树从 NULL 开始
    BinTree T = NULL;
//@s 插入序列
//@d 故意选一个"顺序有点乱"的序列，这样建出来的树两边都长，不会退化成链。
    static const int ins[] = { 8, 3, 10, 1, 6, 14, 4, 7, 13 };
//@s 计数
    int i;
//@s 查找结果
    BinTree found;

//@s 逐个插入
    for (i = 0; i < (int)(sizeof(ins) / sizeof(ins[0])); i++)
    {
        T = BSTInsert(T, ins[i]);
    }

//@s 用中序验证：必须递增
    printf("插入 %d 个值后，中序遍历: ", (int)(sizeof(ins) / sizeof(ins[0])));
    InOrder(T);
    printf("\n（BST 的中序一定递增 —— 只要有序就说明结构是对的）\n\n");

//@s 查找命中
    found = BSTFind(T, 7);
    printf("查 7  → %s\n", found ? "找到" : "没找到");
//@s 查找未命中
    found = BSTFind(T, 99);
    printf("查 99 → %s\n", found ? "找到" : "没找到（BST 里没有）");

//@s 找最值
    printf("最小值 = %d，最大值 = %d\n\n", FindMin(T)->data, FindMax(T)->data);

//@s 情况一：删叶子
    T = BSTDelete(T, 7);
    printf("删 7 （叶子）     : ");
    InOrder(T);
    printf("\n");

//@s 情况二：删只有一个孩子的结点（13 只有左孩子 11？这里删 1 是叶子）
//@d 为了演示情况二，15 是挂在 14 右边的单孩子结点。
    T = BSTInsert(T, 15);
    T = BSTDelete(T, 14);
    printf("删 14（一个孩子） : ");
    InOrder(T);
    printf("\n");

//@s 情况三：删有两个孩子的结点
    T = BSTDelete(T, 3);
    printf("删 3 （两个孩子） : ");
    InOrder(T);
    printf("\n");

//@s 删根
    T = BSTDelete(T, 8);
    printf("删 8 （树根）     : ");
    InOrder(T);
    printf("\n");

//@s 删一个不存在的值：应该什么都不做
    T = BSTDelete(T, 999);
    printf("删 999（不存在）  : ");
    InOrder(T);
    printf("\n（什么都没变 —— 删除不存在的值不应该破坏结构）\n");

//@s 释放
    FreeTree(T);
//@s 正常结束
    return 0;
}
