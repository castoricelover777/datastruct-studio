#%module | 03 | BSTFind | BSTFind —— 查找 | 2 | 01 |
#%summary | 比当前结点小就往左、大就往右，一路扔掉一半候选。
#@d ============ 查找的路径 ============
#@d
#@d 在以 8 为根的 BST 里找 7：
#@d
#@d          8         7 < 8  → 往左
#@d        /   \
#@d       3     10     7 > 3  → 往右
#@d      / \      \
#@d     1   6      14  7 > 6  → 往右
#@d        / \    /
#@d       4   7  13    相等！找到了
#@d
#@d 一共比较了 4 次。如果这是有序数组用二分，也要 log 次 ——
#@d **BST 的查找本质就是"写成树的二分查找"**。
#@d
#@d ============ 递归还是循环 ============
#@d
#@d 递归写起来最贴题意（三行），缺点是树很深时会消耗调用栈。
#@d 这里两个版本都给：递归看思路，循环看工程。
#@d 循环版其实更好 —— 尾递归本来就能直接改成 while。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   这一段几乎是照着 C 抄的：递归的写法和比较顺序一个字没挪。
#@d   只有三处换了写法：T == NULL 换成 T is None；T->left 换成 T.left；
#@d   循环版里 C 的 ?: 换成 Python 的 if ... else ...，意思一样。
#@d   C 的 NULL 到了 Python 就是 None，返回 None 照样表示"没找到"。

#@s 递归版：返回找到的结点，找不到返回 NULL
def BSTFind(T, x):
    #@s 走到空说明整棵树都找遍了，没有
    if T is None:
        return None

    #@s 目标更小 → 只可能在左子树
    if x < T.data:
        return BSTFind(T.left, x)
    #@s 目标更大 → 只可能在右子树
    if x > T.data:
        return BSTFind(T.right, x)

    #@s 相等 —— 命中，返回这个结点
    #@d 返回结点地址而不是 1/0，是因为调用者往往还要用到它（比如接着删除、
    #@d 或者读它的其他字段）。
    return T

#@s 循环版：功能相同，但不占调用栈
#@d 尾递归可以直接改写成循环 —— 这是在工程代码里更常见的写法。
def BSTFindIter(T, x):
    #@s 一路往下走，直到走到空或者命中
    while T is not None and T.data != x:
        #@s 比当前小就往左，否则往右 —— 一次比较决定一半的去留
        T = T.left if x < T.data else T.right
    #@s 循环结束时 T 要么是要找的结点，要么是 NULL
    return T
#%end

#%module | 04 | BSTInsert | BSTInsert —— 插入 | 2 | 01,02,03 |
#%summary | 像查找一样走下去，走到空位置就把新结点挂上去。
#@d ============ 插入的路径 ============
#@d
#@d 往上面那棵树里插 5：
#@d
#@d          8         5 < 8  → 往左
#@d        /   \
#@d       3     10     5 > 3  → 往右
#@d      / \      \
#@d     1   6      14  5 < 6  → 往左
#@d        / \    /
#@d       4   7  13    ← 这个位置是空的，就插在 6 的左孩子
#@d
#@d          8
#@d        /   \
#@d       3     10
#@d      / \      \
#@d     1   6      14
#@d        / \    /
#@d       4   5  13
#@d          ↑ 新来的
#@d
#@d 插入和查找走的是**完全相同的路径** —— 区别只在"走到空的时候"：
#@d 查找返回 NULL，插入则造一个结点挂上去。
#@d
#@d ============ 关于重复值 ============
#@d
#@d 如果插入的值已经存在怎么办？本实现选择"什么都不做"。
#@d 也可以改成计数 +1、或者规定"相等的往右走"。
#@d 关键是**要有一条明确的规矩**，不能今天不动明天往右 —— 那样中序就不再有序了。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   除了 T->left 换成 T.left，别的一个字没改，递归写法两边长得一模一样。
#@d   C 的 else if 到 Python 里写作 elif，只是换了个词，判断顺序还是先小后大。
#@d   "空树插入时根会变"这件事两边都得应付：C 要写 T = BSTInsert(T, x);，
#@d   Python 也一样 —— 传进去的 T 是 None，改它没意义，只能靠返回值接回来。

#@s 插入 x，返回新的树根
#@d 为什么返回树根？因为空树插入时根本身会变，调用者必须接收返回值：
#@d     T = BSTInsert(T, x);
def BSTInsert(T, x):
    #@s 走到空位置 → 这就是新结点该待的地方
    if T is None:
        return NewNode(x)

    #@s 比当前小 → 递归插到左子树，并把结果接回左指针
    if x < T.data:
        T.left = BSTInsert(T.left, x)
    #@s 比当前大 → 插到右子树
    elif x > T.data:
        T.right = BSTInsert(T.right, x)
    #@s 相等 → 已经存在，什么也不做（也可以改成计数）
    #@d 注意这里没有 else 分支也不返回，直接落到最后的 return T。
    #@d 千万别写成"相等就插到右边" —— 那样重复值会越堆越多，中序也不再严格有序。

    #@s 返回（可能被修改过的）根
    return T
#%end

#%module | 05 | FindMin | FindMin —— 找最小值 | 1 | 01 |
#%summary | 从根一路往左走到底，最左下的那个就是最小。
#@d ============ 为什么最小值一定在"最左边" ============
#@d
#@d 因为 BST 的规矩是"左边都比根小"。所以：
#@d
#@d   · 任何一个结点，只要它有左孩子，那左孩子一定比它小
#@d   · 所以最小值不可能在"有左孩子的结点"上
#@d   · 一路往左走到底，那个没有左孩子的结点就是最小
#@d
#@d 走的过程（还是那棵树）：
#@d
#@d   8 → 左孩子 3 → 左孩子 1 → 1 没有左孩子，停
#@d   最小值是 1
#@d
#@d 最大值对称：一路往右走到没有右孩子为止。
#@d
#@d ============ 这个函数在删除时会用到 ============
#@d
#@d 删除有两个孩子的结点时，需要找一个"替身"来顶替被删的位置。
#@d 这个替身有两个合法选择：
#@d
#@d   ① 右子树的**最小值**（它比右子树其它都小，接到左边也不会破坏规矩）
#@d   ② 左子树的**最大值**
#@d
#@d 本实现用 ①。所以 FindMin 不是一个"顺便讲讲"的辅助函数，
#@d 它是删除算法的组成部分。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   这一模块基本只换了写法：T->left 写成 T.left，T != NULL 写成 is not None。
#@d   C 的循环里 T 是指针，往前走一句 T = T->left 就完事；
#@d   Python 里 T 是结点对象，同样一句 T = T.left，往后 T 指的就是左孩子那个结点了。
#@d   空树返回的是 NULL / None，两边的调用者都得先判一下再取 .data。

#@s 返回最小结点；空树返回 NULL
def FindMin(T):
    #@s 空树直接返回
    if T is None:
        return None
    #@s 一路往左，直到没有左孩子
    #@d 用循环而不是递归：这里没有"回退"的需求，循环更直白也更快。
    while T.left is not None:
        T = T.left
    #@s 停下来时 T 就是最小结点
    return T

#@s 返回最大结点；空树返回 NULL
def FindMax(T):
    #@s 空树
    if T is None:
        return None
    #@s 一路往右
    while T.right is not None:
        T = T.right
    #@s 停下来的就是最大
    return T
#%end

#%module | 06 | BSTDelete | BSTDelete —— 删除 | 3 | 01,04,05 |
#%summary | 分三种情况：叶子直接删、一个孩子顶上来、两个孩子找右子树最小值替代。
#@d ============ 三种情况 ============
#@d
#@d **情况一：要删的是叶子**（没有孩子）
#@d
#@d       ... 6               ... 6
#@d          / \      →         /
#@d         4   7              4        直接拿掉 7，什么都不用管
#@d
#@d **情况二：只有一个孩子**
#@d
#@d       14                13
#@d      /         →       /         拿孩子顶替自己的位置
#@d    13                 11
#@d   /
#@d  11
#@d
#@d **情况三：有两个孩子** —— 麻烦在这里
#@d
#@d          8                    10
#@d        /   \                /    \
#@d       3     10     →       3      14
#@d      / \      \           / \    /
#@d     1   6      14         1   6  13
#@d                                     ← 13 还在，位置没变
#@d
#@d 删 8 不能直接把 8 拿掉 —— 那样左右两棵子树就没法拼成一棵树了。
#@d 办法是**找个替身**：用右子树里最小的那个（10）的值覆盖 8，
#@d 然后再去右子树里把那个"10 号结点"删掉（它最多只有一个孩子，好删）。
#@d
#@d ============ 为什么替身是"右子树最小值" ============
#@d
#@d 因为它比右子树里所有结点都小、又比左子树里所有结点都大 ——
#@d 放在根的位置正好满足 BST 的规矩。
#@d 换成左子树的最大值也可以，对称的。
#@d
#@d ============ 写这段代码的关键 ============
#@d
#@d 一定要**先递归、再把返回值接回去**：
#@d
#@d     T->left = BSTDelete(T->left, x);
#@d
#@d 因为删掉左子树的根之后，左子树的根可能换人了，必须重新接上。
#@d 漏掉这个赋值是这一节最常见的 bug。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   去掉 T->left 变成 T.left、else if 变成 elif，递归的结构和 C 完全对得上。
#@d   最要紧的差别在末尾那句 free：C 靠 free(tmp) 把内存还给系统，忘了写就是内存泄漏；
#@d   Python 没有 free，改成 tmp = None 剪断最后一根引用，剩下的交给 Python 自己回收。
#@d   tmp = None 这一行删掉其实也照样跑，写出来只是为了和 C 的 free 对得上。

#@s 删除值为 x 的结点，返回新的树根
#@d 同样要接收返回值：T = BSTDelete(T, x);
def BSTDelete(T, x):
    #@s 被删结点
    #@d C 写的是 BinTree tmp; —— 声明一个还没赋值的临时变量；Python 不用声明，
    #@d 这里写 tmp = None 只是给这个变量安个家，下面两个分支各给它赋一次真值。
    tmp = None

    #@s 走到空也没找到 —— 什么也不做
    if T is None:
        return None

    #@s 还没找到：继续往左
    if x < T.data:
        #@d 这一句的赋值千万不能省。删完之后左子树的根可能变了，必须接回来。
        T.left = BSTDelete(T.left, x)
    #@s 继续往右
    elif x > T.data:
        T.right = BSTDelete(T.right, x)
    #@s 找到了，就是当前这个结点
    else:
        #@s 情况三：两个孩子都在
        if T.left is not None and T.right is not None:
            #@s 找右子树里的最小值当替身
            tmp = FindMin(T.right)
            #@s 用替身的值覆盖自己
            #@d 只改值不改结构 —— 这是最省事的做法（如果结点里还有别的数据，
            #@d 别忘了也一起搬过来）。
            T.data = tmp.data
            #@s 再去右子树里把那个替身结点删掉
            #@d 它能走到这里，说明它一定没有左孩子（一路向左走到底的），
            #@d 所以下一轮递归最多只有一个孩子，问题规模缩小了。
            T.right = BSTDelete(T.right, tmp.data)
        #@s 情况一 / 二：至多一个孩子
        else:
            #@s 先记住要被 free 的结点
            tmp = T
            #@s 让唯一的孩子（或者 NULL）顶替上来
            #@d 左孩子存在就用左孩子，否则用右孩子。两个都没有时
            #@d 表达式的结果正好是 NULL —— 一个式子覆盖了两种情况。
            T = T.left if T.left is not None else T.right
            #@s 释放被删结点
            #@d C 这里写的是 free(tmp)，把这块内存还给系统；Python 没有 free，
            #@d 把 tmp 指向 None，剪断最后一根引用，这个结点就被 Python 收走了。
            tmp = None

    #@s 返回（可能已经换人的）根
    return T
#%end

#%module | 07 | InOrder | InOrder —— 中序验证 | 1 | 01 |
#%summary | 把 BST 打成递增序列 —— 验证结构有没有被破坏的最快办法。
#@d ============ 为什么单给它一个模块 ============
#@d
#@d 中序遍历在普通二叉树里只是"三种遍历之一"，但在 BST 里它有个特殊身份：
#@d **它输出的一定是递增序列**。
#@d
#@d 所以写 BST 的时候要养成一个习惯：每次插入或删除之后，中序打一遍。
#@d
#@d   · 输出有序 → 结构没坏
#@d   · 哪里乱了序 → 那一步的插入或者删除写错了
#@d
#@d 这比"盯着树看"可靠得多。树一深，人是看不出问题的；
#@d 但有序性一乱，一眼就能发现。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   三行递归的顺序原封不动，先左、再自己、后右。
#@d   只有 printf("%d ", T->data) 换成了 print(T.data, end=' ')。
#@d   那个 end=' ' 千万不能少：Python 的 print 默认末尾要加换行，C 的 printf 不会，
#@d   少了它每个数就占一行，和 C 版的输出对不上（C 是每个数后面跟一个空格）。

#@s 中序遍历（把 BST 打成有序序列）
def InOrder(T):
    #@s 空树返回
    if T is None:
        return
    #@s 左
    InOrder(T.left)
    #@s 根
    print(T.data, end=' ')
    #@s 右
    InOrder(T.right)
#%end

#%module | 08 | FreeTree | FreeTree —— 释放整棵树 | 2 | 01 |
#%summary | 后序释放：先孩子、后自己。
#@d ============ 顺序不能反 ============
#@d
#@d free 掉根之后，就再也找不到它的孩子了 —— 那些内存永远收不回来。
#@d 所以只能"先把左右子树都清干净，最后 free 自己"，也就是后序。
#@d
#@d 同类的还有算表达式树的值、求树高 —— 凡是"必须等孩子处理完"的操作都用后序。
#@d
#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 的最后一步是 free(T)，把内存还给系统；Python 里没有 free 这个东西。
#@d   下面两句只是把通到孩子的那两根线剪断，好把"先孩子、后自己"这个顺序演给你看。
#@d   其实这个函数一行都不干也行：只要没人再引用这棵树，Python 会自己数着引用
#@d   把整棵树一起收走，回收的顺序根本不用你操心。

#@s 后序释放整棵树
def FreeTree(T):
    #@s 空树返回
    if T is None:
        return
    #@s 先孩子
    FreeTree(T.left)
    FreeTree(T.right)
    #@s 后自己
    T.left = None
    T.right = None
#%end

