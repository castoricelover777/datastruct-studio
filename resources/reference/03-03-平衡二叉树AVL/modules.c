/*
 * ============================================================================
 *  数据结构研习社 —— 03 树 / 03-03 平衡二叉树 AVL
 * ============================================================================
 *
 *  BST 有个致命弱点：插入序列如果恰好有序，树就退化成一条链。
 *
 *      插入 1 2 3 4 5         插入 3 1 2 4 5
 *          1                        3
 *           \                     /   \
 *            2                   1     4
 *             \                          \
 *              3                          5
 *               \                    高度 3，查找 3 次
 *                4
 *                 \              高度 5，查找 5 次 —— 退化成链表了
 *                  5
 *
 *  AVL 树（Adelson-Velsky & Landis）的解决办法：**每次插入后检查平衡，
 *  一旦某个结点的左右子树高度差超过 1，就转一下把它掰回来**。
 *
 *  四种旋转，看着花样多，其实是两对镜像：
 *
 *      LL（左孩子的左边太高）→ 右单旋
 *      RR（右孩子的右边太高）→ 左单旋
 *      LR（左孩子的右边太高）→ 先左旋再右旋
 *      RL（右孩子的左边太高）→ 先右旋再左旋
 *
 *  标记约定同前（本文件本身可编译）。
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>

//%module | 01 | typedef | 头文件与 typedef | 2 |
//%summary | 结点里多存一个「高度」，用来算平衡因子。
//@d ============ 为什么要存高度 ============
//@d
//@d 平衡因子 = 左子树高 - 右子树高，AVL 要求它只能是 -1、0、1。
//@d
//@d 如果每次要判断平衡都现场递归求高度，插入一次就要 O(n) 的额外开销，
//@d 整体复杂度会退化。所以干脆**在结点里存一个高度字段**，插入时顺便更新，
//@d 用 O(1) 就能拿到。
//@d
//@d 这就是空间换时间的典型：每个结点多 4 个字节，换来判断平衡不用递归。
//@d
//@d ============ 空树的高度是多少 ============
//@d
//@d 约定成 **0**（而不是 -1）。这样：
//@d
//@d   叶子结点高度 = max(0, 0) + 1 = 1
//@d   只有一个孩子的结点 = max(孩子高, 0) + 1
//@d
//@d 式子统一，不用到处特判空指针。

//@s 数据元素类型
typedef int ElemType;

//@s AVL 结点：比普通二叉树多一个 height
typedef struct AVLNode
{
//@s 数据域
    ElemType data;
//@s 左子树
    struct AVLNode *left;
//@s 右子树
    struct AVLNode *right;
//@s 以自己为根的子树高度（空树记 0）
    int height;
} AVLNode, *AVLTree;

//@s 状态码
#define OK 1
#define ERROR 0
typedef int Status;
//%end

//%module | 02 | Height | Height —— 求高度与更新 | 1 | 01 |
//%summary | 取高度要能容忍空树；更新高度就是「两个孩子取大的，再加一」。
//@d ============ 两个小函数，但是所有旋转的基础 ============
//@d
//@d **GetHeight(T)**：取一棵树的高度。空树返回 0。
//@d 把它单独包一层，是为了让后面的代码不用到处写 `T ? T->height : 0`。
//@d
//@d **UpdateHeight(T)**：重新算并写回 T 的高度。
//@d 注意它假设**孩子的高度已经是正确的** —— 所以调用时机永远是
//@d "先处理好孩子，再更新自己"，也就是后序的顺序。
//@d
//@d ============ 什么时候要更新 ============
//@d
//@d 旋转之后、插入回溯的路上，都要更新。
//@d 漏掉更新会出现"树看着是对的、平衡因子却是错的"这种最难查的 bug ——
//@d 因为它不会崩，只会在某次插入时做出错误的旋转判断。

//@s 取高度：空树是 0
int GetHeight(AVLTree T)
{
//@s 空树高度 0
    if (T == NULL)
    {
        return 0;
    }
//@s 否则就是存着的那个值
    return T->height;
}

//@s 取两个数的较大者
int MaxInt(int a, int b)
{
    return a > b ? a : b;
}

//@s 重新计算 T 的高度并写回
//@d 前提：T 的左右孩子高度都已经是对的
void UpdateHeight(AVLTree T)
{
//@s 空树不用管
    if (T == NULL)
    {
        return;
    }
//@s 高度 = 两个孩子里高的那个 + 1
    T->height = MaxInt(GetHeight(T->left), GetHeight(T->right)) + 1;
}

//@s 平衡因子 = 左高 - 右高
//@d AVL 要求它只能是 -1、0、1。绝对值到 2 就必须旋转了。
int BalanceFactor(AVLTree T)
{
//@s 空树认为平衡
    if (T == NULL)
    {
        return 0;
    }
//@s 左减右
    return GetHeight(T->left) - GetHeight(T->right);
}
//%end

//%module | 03 | RotateLL | RotateLL —— 左单旋 | 2 | 01,02 |
//%summary | 麻烦出在「左孩子的左边」，把左孩子提上来当根。
//@d ============ 什么时候用：LL ============
//@d
//@d 判断口诀：**从出问题的结点往下走两步，方向都是「左」**，就是 LL。
//@d
//@d 插入前是平衡的：
//@d
//@d          5                   5
//@d         /                   /
//@d        3        插入 1 后   3          ← 5 的左子树高 2，右子树高 0，失衡
//@d                           /
//@d                          1
//@d
//@d 从 5 往下走：左（到 3）、再左（到 1）→ LL → 用**右单旋**。
//@d
//@d 旋转动作（把 3 提上来，5 降下去当它的右孩子）：
//@d
//@d          5                    3
//@d         /        →           / \
//@d        3                    1   5
//@d       /
//@d      1
//@d
//@d 为什么这样转完还是 BST？因为中序都是 1 3 5 —— 旋转**不改变中序**，
//@d 这是它能保持搜索树性质的根本原因。
//@d
//@d ============ 代码怎么写 ============
//@d
//@d 四步：
//@d   ① 记住左孩子（它要升上来当新根）
//@d   ② 把左孩子的右子树接到原来的根上（原来根的左边腾空）
//@d   ③ 让原来的根成为新根的右孩子
//@d   ④ 更新这两个结点的高度
//@d
//@d 第 ② 步是初学者最容易漏的 —— 少了它，左孩子的右子树就丢了。

//@s 右单旋（处理 LL 情况），返回新的子树根
AVLTree RotateLL(AVLTree T)
{
//@s ① 新根就是左孩子
    AVLTree newRoot = T->left;

//@s ② 把新根的右子树挂到旧根的左边
//@d 这一步最容易忘。忘了就直接丢一棵子树。
    T->left = newRoot->right;

//@s ③ 旧根成为新根的右孩子
    newRoot->right = T;

//@s ④ 更新高度 —— 必须先更新旧根（它现在是孩子了）
//@d 顺序不能反：更新自己要用到孩子的高度，所以孩子得先算好。
    UpdateHeight(T);
    UpdateHeight(newRoot);

//@s 返回新根
    return newRoot;
}
//%end

//%module | 04 | RotateRR | RotateRR —— 右单旋 | 2 | 01,02 |
//%summary | 麻烦出在「右孩子的右边」，把右孩子提上来当根。
//@d ============ 和 LL 完全镜像 ============
//@d
//@d 从出问题的结点往下走两步都是「右」→ RR → 用**左单旋**。
//@d
//@d          3                  3
//@d           \                    \
//@d            5     插入 7 后       5        ← 3 的右子树高 2，左子树高 0，失衡
//@d                                  \
//@d                                   7
//@d
//@d 旋转（把 5 提上来）：
//@d
//@d        3                      5
//@d         \        →           / \
//@d          5                  3   7
//@d           \
//@d            7
//@d
//@d 代码就是把 LL 的 left / right 全反过来：
//@d
//@d   RotateLL：newRoot = T->left;   T->left = newRoot->right;   newRoot->right = T;
//@d   RotateRR：newRoot = T->right;  T->right = newRoot->left;   newRoot->left = T;
//@d
//@d ============ 名字的坑 ============
//@d
//@d 注意命名：**LL 用右旋，RR 用左旋** —— 方向和名字是反的。
//@d 名字说的是"麻烦在哪"（LL = 左孩子的左边），不是"往哪转"。
//@d 记混了会写出把树转歪的代码，而且往往还能跑，只是不再平衡。

//@s 左单旋（处理 RR 情况），返回新的子树根
AVLTree RotateRR(AVLTree T)
{
//@s ① 新根是右孩子
    AVLTree newRoot = T->right;

//@s ② 新根的左子树改挂到旧根的右边
    T->right = newRoot->left;

//@s ③ 旧根成为新根的左孩子
    newRoot->left = T;

//@s ④ 先更新旧根，再更新新根
    UpdateHeight(T);
    UpdateHeight(newRoot);

//@s 返回新根
    return newRoot;
}
//%end

//%module | 05 | RotateLR | RotateLR —— 左右双旋 | 3 | 01,02,03,04 |
//%summary | 麻烦在「左孩子的右边」，先对左孩子左旋、再对自己右旋。
//@d ============ 单旋搞不定的情况 ============
//@d
//@d          5                 5
//@d         /                 /
//@d        3      插入 4 后   3        ← 5 失衡了
//@d                            \
//@d                             4
//@d
//@d 从 5 往下走：左（到 3）、再右（到 4）→ **LR**。
//@d
//@d 这时候直接右单旋行不行？试试看：
//@d
//@d          5                3
//@d         /                / \
//@d        3        →       1*  5     转完还是不平衡！
//@d         \
//@d          4
//@d
//@d 因为麻烦藏在"左孩子的右边"，直接转会把那棵子树原样带过去。
//@d
//@d ============ 分两步 ============
//@d
//@d **先对左孩子做一次左旋**，把它变成 LL 的样子，**再对自己做右单旋**：
//@d
//@d      5            5                4
//@d     /            /                / \
//@d    3      →     4        →       3   5
//@d     \          /
//@d      4        3
//@d
//@d 第一步（对 3 左旋）之后，5 的左边就是"左孩子的左边"了 —— 变成 LL，
//@d 于是第二步照 LL 处理即可。
//@d
//@d ============ 本质 ============
//@d
//@d 双旋不是"新的旋转类型"，只是**把两种情况拆成两次单旋**。
//@d 理解了这点，RL 就不用另记了 —— 它是对称的。

//@s 左右双旋（处理 LR），返回新的子树根
AVLTree RotateLR(AVLTree T)
{
//@s 第一步：先对左孩子做左单旋，把 LR 掰成 LL
    T->left = RotateRR(T->left);

//@s 第二步：再对自己做右单旋（这一步就是 LL 的处理方式）
    return RotateLL(T);
}
//%end

//%module | 06 | RotateRL | RotateRL —— 右左双旋 | 3 | 01,02,03,04 |
//%summary | 麻烦在「右孩子的左边」，先对右孩子右旋、再对自己左旋。
//@d ============ LR 的镜像 ============
//@d
//@d          3                3
//@d           \                \
//@d            5     插入 4 后  5       ← 3 失衡
//@d                           /
//@d                          4
//@d
//@d 从 3 往下：右（到 5）、再左（到 4）→ **RL**。
//@d
//@d 处理方式和 LR 完全对称：
//@d
//@d   ① 先对右孩子做一次右单旋，把 RL 掰成 RR
//@d   ② 再对自己做左单旋
//@d
//@d      3              3                4
//@d       \              \              / \
//@d        5      →       4      →     3   5
//@d       /                \
//@d      4                  5
//@d
//@d ============ 四种旋转汇总 ============
//@d
//@d   名字   麻烦在哪          怎么转
//@d   ────  ───────────────  ──────────────────────
//@d   LL    左孩子的左边      对自己右单旋
//@d   RR    右孩子的右边      对自己左单旋
//@d   LR    左孩子的右边      先对左孩子左旋，再对自己右旋
//@d   RL    右孩子的左边      先对右孩子右旋，再对自己左旋
//@d
//@d 记忆窍门：**单旋 = 麻烦在外侧，双旋 = 麻烦在内侧**。
//@d 双旋的第一步永远是"把内侧的麻烦挪到外侧去"。

//@s 右左双旋（处理 RL），返回新的子树根
AVLTree RotateRL(AVLTree T)
{
//@s 第一步：先对右孩子做右单旋，把 RL 掰成 RR
    T->right = RotateLL(T->right);

//@s 第二步：再对自己做左单旋
    return RotateRR(T);
}
//%end

//%module | 07 | AVLInsert | AVLInsert —— 插入并自动平衡 | 3 | 01,02,03,04,05,06 |
//%summary | 先按 BST 插进去，回溯时更新高度、发现失衡就转。
//@d ============ 插入的四步 ============
//@d
//@d   ① 按 BST 的规矩往下走，走到空位置造结点
//@d   ② **回溯的路上**更新自己的高度
//@d   ③ 算平衡因子，如果绝对值到 2 就判断是哪种情况
//@d   ④ 对应的旋转，返回新的子树根
//@d
//@d 关键在于**第 ② 步的位置**：更新高度必须在递归回来之后、
//@d 也就是"孩子都处理好了"，这正是后序的顺序。
//@d
//@d ============ 谁先失衡 ============
//@d
//@d 插入只会让**从新结点到根这条路径上**的结点失衡，而且
//@d **最先失衡的一定是离新结点最近的那个**。
//@d
//@d 递归回溯天然是从下往上走的，所以遇到的第一个失衡结点就是它 ——
//@d 转它一次，整棵树就恢复平衡了（不需要继续往上修）。
//@d 这也是 AVL 插入只要 O(log n) 的原因。
//@d
//@d ============ 判断属于哪种情况 ============
//@d
//@d 先看平衡因子：
//@d
//@d   左高（BF > 1）→ 麻烦在左边，再看左孩子的哪边高
//@d        左孩子的左边高（BF(左孩子) >= 0）→ LL
//@d        左孩子的右边高（BF(左孩子) <  0）→ LR
//@d
//@d   右低（BF < -1）→ 麻烦在右边，对称处理
//@d
//@d 注意判断用的是**左孩子的平衡因子**，不是"新插入的值比左孩子大还是小" ——
//@d 两者有时结论不同，用平衡因子才可靠。

//@s 插入 x，返回新的子树根
AVLTree AVLInsert(AVLTree T, ElemType x)
{
//@s ① 走到空位置，造结点（新结点高度是 1）
    if (T == NULL)
    {
        AVLTree node = (AVLTree)malloc(sizeof(AVLNode));
        if (node == NULL)
        {
            printf("内存分配失败\n");
            exit(1);
        }
        node->data = x;
        node->left = NULL;
        node->right = NULL;
        node->height = 1;
        return node;
    }

//@s 比当前小 → 插到左子树
    if (x < T->data)
    {
        T->left = AVLInsert(T->left, x);
    }
//@s 比当前大 → 插到右子树
    else if (x > T->data)
    {
        T->right = AVLInsert(T->right, x);
    }
//@s 相等 → 不插（和 BST 一致）
    else
    {
        return T;
    }

//@s ② 回溯到这一步时孩子已经处理好了，更新自己的高度
    UpdateHeight(T);

//@s ③ 算平衡因子，看有没有失衡
    {
//@s 平衡因子
        int bf = BalanceFactor(T);

//@s 左边太高
        if (bf > 1)
        {
//@s 再看左孩子：左边高是 LL，右边高是 LR
//@d 用 >= 0 而不是 > 0，是为了把"左孩子平衡"也归到 LL ——
//@d 那种情况下单旋就够了。
            if (BalanceFactor(T->left) >= 0)
            {
//@s LL：右单旋
                return RotateLL(T);
            }
//@s LR：先左后右的双旋
            return RotateLR(T);
        }

//@s 右边太高（镜像处理）
        if (bf < -1)
        {
//@s 右孩子右边高是 RR，左边高是 RL
            if (BalanceFactor(T->right) <= 0)
            {
//@s RR：左单旋
                return RotateRR(T);
            }
//@s RL：先右后左的双旋
            return RotateRL(T);
        }
    }

//@s ④ 没失衡，原样返回
    return T;
}
//%end

//%module | 08 | InOrder | InOrder —— 中序验证 | 1 | 01 |
//%summary | 旋转不改变中序 —— 所以中序有序就说明树还是 BST。
//@d ============ 为什么旋转不会破坏 BST ============
//@d
//@d 因为旋转只是**换了父子关系，没有换左右顺序**。
//@d
//@d 以 LL 为例：
//@d
//@d       5                3
//@d      /                / \
//@d     3        →       1   5
//@d    /
//@d   1
//@d
//@d 两棵树的中序都是 **1 3 5**。中序不变，而中序就是排序顺序，
//@d 所以 BST 的性质保住了。
//@d
//@d 这也是验证 AVL 写没写对的两把尺子之一：
//@d
//@d   ① 中序必须递增          → 还是 BST
//@d   ② 每个结点的平衡因子都在 -1..1 → 还是平衡的
//@d
//@d 两个都对，这棵树就合格了。

//@s 中序遍历，顺便看是不是有序
void InOrder(AVLTree T)
{
//@s 空树返回
    if (T == NULL)
    {
        return;
    }
//@s 左
    InOrder(T->left);
//@s 根
    printf("%d ", T->data);
//@s 右
    InOrder(T->right);
}
//%end

//%module | 09 | FreeTree | FreeTree —— 释放整棵树 | 2 | 01 |
//%summary | 后序释放：先孩子、后自己。
//@d 和普通二叉树一样，AVL 也必须后序释放 —— 先 free 根就再也找不到孩子了。

//@s 后序释放
void FreeTree(AVLTree T)
{
//@s 空树返回
    if (T == NULL)
    {
        return;
    }
//@s 先孩子
    FreeTree(T->left);
    FreeTree(T->right);
//@s 后自己
    free(T);
}
//%end

//%module | 10 | CheckBalance | CheckBalance —— 逐结点检查平衡 | 2 | 01,02 |
//%summary | 递归看每个结点的平衡因子是否都在 -1..1 之间。
//@d ============ 验证 AVL 的两把尺子 ============
//@d
//@d 写完 AVL 要用两个条件自查：
//@d
//@d   ① 中序递增          → 还是 BST（旋转不改变中序）
//@d   ② 每个结点都平衡     → 确实做到了 AVL 的要求
//@d
//@d 第一个用 InOrder 看输出，第二个就是这个函数。
//@d 两个都过，这棵树才合格。
//@d
//@d 只查根是不够的 —— 旋转写出问题时，往往是某个子树里失衡，
//@d 而根看起来还正常。

//@s 检查每个结点的平衡因子是否都在 -1..1
//@d 返回 1 表示全部合法
int CheckBalance(AVLTree T)
{
//@s 空树算合法
    if (T == NULL)
    {
        return 1;
    }
//@s 自己失衡就直接返回 0
//@d 平衡因子的绝对值超过 1 就是不合格的 AVL。
    if (BalanceFactor(T) > 1 || BalanceFactor(T) < -1)
    {
        printf("  结点 %d 失衡，平衡因子 = %d\n", T->data, BalanceFactor(T));
        return 0;
    }
//@s 两个孩子也都要合法
    return CheckBalance(T->left) && CheckBalance(T->right);
}
//%end

//%module | 11 | main | main —— 让 AVL 自己找平衡 | 3 | 01,02,03,04,05,06,07,08,09,10 |
//%summary | 故意用有序序列插入，看它怎么把自己掰平衡。
//@d ============ 这个测试为什么用有序序列 ============
//@d
//@d 因为**有序序列正是普通 BST 的死穴** —— 1 2 3 4 5 6 7 会退化成一条链。
//@d
//@d 而 AVL 会把这种输入自动掰成一棵平衡树。用它来测，最能看出价值。
//@d
//@d ============ 顺便验证两件事 ============
//@d
//@d   ① 中序递增 → 旋转没破坏 BST 性质
//@d   ② 根的高度 ≈ log2(n+1) → 树确实是平衡的
//@d
//@d 7 个结点的平衡树高度是 3（2³-1 = 7）。如果打出来是 7，
//@d 说明根本没平衡，得回头查旋转。

//@s 主函数
int main(void)
{
//@s 故意用有序序列 —— 这正是普通 BST 会退化的情况
    static const int ins[] = { 1, 2, 3, 4, 5, 6, 7 };
//@s 计数
    int i;
//@s 树根
    AVLTree T = NULL;

//@s 打印说明
    printf("插入序列：1 2 3 4 5 6 7（普通 BST 会退化成一条链）\n\n");

//@s 逐个插入并观察
    for (i = 0; i < 7; i++)
    {
        T = AVLInsert(T, ins[i]);
        printf("插入 %d 后：根 = %d，树高 = %d，中序: ", ins[i], T->data, T->height);
        InOrder(T);
        printf("\n");
    }

//@s 验证 ①：中序必须递增
    printf("\n① 中序结果：");
    InOrder(T);
    printf("\n   （必须递增 —— 说明旋转没有破坏 BST 性质）\n");

//@s 验证 ②：树高应该是 3
    printf("\n② 树高 = %d（7 个结点的平衡树应该是 3）\n", T->height);
    printf("   普通 BST 按这个顺序插会变成高度 7 的链\n");

//@s 验证 ③：每个结点都平衡
    printf("\n③ 逐结点检查平衡因子：");
    if (CheckBalance(T))
    {
        printf("全部在 -1..1 之间，合格\n");
    }

//@s 释放
    FreeTree(T);
//@s 正常结束
    return 0;
}
