/*
 * ============================================================================
 *  数据结构研习社 —— 03 树 / 03-05 哈夫曼树与哈夫曼编码
 * ============================================================================
 *
 *  问题：给一堆带权值的叶子，怎么把它们组织成一棵二叉树，
 *        让**带权路径长度（WPL）最小**？
 *
 *      带权路径长度 = Σ (每个叶子的权值 × 它到根的层数)
 *
 *  哈夫曼的做法非常朴素：**反复挑出两个权值最小的，合并成一个新结点**。
 *
 *      权值 1 2 3 4 5
 *
 *      挑 1 2 → 合并成 3      剩下 3 3 4 5      ← 3 是新结点，也参与挑选
 *      挑 3 3 → 合并成 6      剩下 4 5 6
 *      挑 4 5 → 合并成 9      剩下 6 9
 *      挑 6 9 → 合并成 15     只剩一个 → 它就是根
 *
 *  得到的树 WPL 最小。直觉是：**权值小的放得深一点，权值大的放得浅一点**，
 *  这样"贵的"叶子少走几层。
 *
 *  这个算法有个很实际的应用：**文件压缩**。权值是字符出现次数，
 *  出现得越多编码越短（左 0 右 1 走出来的路径就是编码）。
 *
 *  标记约定同前（本文件本身可编译）。
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

//%module | 01 | typedef | 头文件与 typedef | 2 |
//%summary | 用数组存树：每个结点记权值、父亲、左右孩子（都是下标）。
//@d ============ 为什么用数组而不是指针 ============
//@d
//@d 建哈夫曼树的过程中，要**反复找出权值最小的两个结点**。
//@d 如果用指针，每次都得遍历整棵树去比较，很别扭。
//@d
//@d 用数组就没这个问题：所有结点排成一排，下标一扫就知道谁最小，
//@d 而且新合并出来的结点直接追加在数组后面就行。
//@d
//@d ============ 为什么需要 parent ============
//@d
//@d 有两个原因：
//@d
//@d   ① 挑选的时候，**已经合并过的结点不能再参与** —— 靠 parent != 0 判断
//@d   ② 生成编码的时候，是**从叶子往根走**的（一步步找 parent），
//@d      走出来的 0/1 是倒着的，最后要反过来
//@d
//@d 所以虽然树是"从上往下"的父子关系，但算法里大量用的是"从下往上"。
//@d
//@d ============ 数组要开多大 ============
//@d
//@d n 个叶子，每次合并少一个结点、多一个内部结点，一共要合并 n-1 次，
//@d 所以内部结点有 n-1 个，总数是 **2n-1**。
//@d 数组开 2n 个（下标 0 不用），够用。

//@s 哈夫曼树的结点
//@d parent / left / right 存的都是**数组下标**，0 表示"没有"
//@d （所以下标要从 1 开始用，0 号位置空着当"空指针"）
typedef struct
{
//@s 权值：叶子是给定的，内部结点是两个孩子之和
    int weight;
//@s 父亲的下标
    int parent;
//@s 左孩子的下标
    int left;
//@s 右孩子的下标
    int right;
} HTNode, *HuffmanTree;

//@s 编码表：每个叶子一个字符串
//@d 用 char** 是因为长度各不相同，只能一个叶子分配一个字符串。
typedef char **HuffmanCode;

//@s 状态码
#define OK 1
#define ERROR 0
typedef int Status;
//%end

//%module | 02 | SelectTwoMin | SelectTwoMin —— 选出两个最小的 | 2 | 01 |
//%summary | 在所有「还没有父亲」的结点里挑出权值最小的两个。
//@d ============ 两个条件缺一不可 ============
//@d
//@d 挑选的时候要同时满足：
//@d
//@d   ① **parent == 0**：还没有被合并过。
//@d      合并过的结点已经有父亲了，再挑它就重复了。
//@d
//@d   ② 权值最小 / 次小。
//@d
//@d 为什么必须检查 ①？因为数组里既有"还没用的叶子"，也有"已经合并好的内部结点"，
//@d 还有"已经当过孩子的结点"。只看权值会把已经用过的又挑出来，
//@d 建出来的树就完全错了 —— 而且它照样能跑完，只是 WPL 不对，很难发现。
//@d
//@d ============ 怎么一次遍历找出最小和次小 ============
//@d
//@d 用一个经典写法：
//@d
//@d   遇到比"当前最小"还小的 → 原来的最小降级成次小，新的当最小
//@d   否则如果比"当前次小"还小 → 它当次小
//@d
//@d 这样一遍扫下来两个都拿到了，不用扫两遍。

//@s 在 1..n 范围内找出两个权值最小且没有父亲的结点
//@d 结果通过 s1（最小）、s2（次小）带回去
void SelectTwoMin(HuffmanTree HT, int n, int *s1, int *s2)
{
//@s 扫描下标
    int i;
//@s 记录最小和次小的下标，-1 表示还没找到
    int min1 = -1;
    int min2 = -1;

//@s 一遍扫完
    for (i = 1; i <= n; i++)
    {
//@s 已经有父亲的跳过 —— 这一条千万不能漏
        if (HT[i].parent != 0)
        {
            continue;
        }

//@s 比当前最小还小：原来的冠军降为亚军
        if (min1 == -1 || HT[i].weight < HT[min1].weight)
        {
            min2 = min1;
            min1 = i;
        }
//@s 否则看看能不能当亚军
        else if (min2 == -1 || HT[i].weight < HT[min2].weight)
        {
            min2 = i;
        }
    }

//@s 把结果带回去（用指针，因为要返回两个值）
    *s1 = min1;
    *s2 = min2;
}
//%end

//%module | 03 | HuffmanCreate | HuffmanCreate —— 建树 | 3 | 01,02 |
//%summary | 反复挑两个最小的合并，直到只剩一个结点。
//@d ============ 建树过程走一遍 ============
//@d
//@d 权值 {1, 2, 3, 4, 5}，n = 5，总共要 2n-1 = 9 个结点。
//@d
//@d 一开始 1..5 是五个叶子，6..9 是待填的内部结点：
//@d
//@d   下标:  1    2    3    4    5  │  6    7    8    9
//@d   权值:  1    2    3    4    5  │  ?    ?    ?    ?
//@d
//@d **第 1 轮**：在 1..5 里挑最小的两个 → 1 和 2
//@d
//@d   合并成结点 6，权值 3
//@d   1 的父亲 = 6，2 的父亲 = 6，6 的左孩子 = 1、右孩子 = 2
//@d
//@d   下标:  1    2    3    4    5  │  6    7    8    9
//@d   权值:  1    2    3    4    5  │  3    ?    ?    ?
//@d   父  :  6    6    0    0    0  │  0
//@d
//@d **第 2 轮**：在 1..6 里挑"没有父亲"的最小的两个 → 3（下标 3）和 6
//@d
//@d   注意 1 和 2 因为有父亲了，不再参与挑选。
//@d   合并成结点 7，权值 6。
//@d
//@d   ... 一直做到第 9 号结点，它就是根。
//@d
//@d 最后根的 parent 还是 0，这就是"根"的标志。
//@d
//@d ============ 为什么循环范围是 1..i-1 ============
//@d
//@d 每一轮的范围是"已经建好的所有结点"，也就是 1 到 i-1。
//@d 因为新结点 i 还没填，它不参与这一轮的挑选。

//@s 用 weights[0..n-1] 建一棵哈夫曼树，结果放进 *HT
void HuffmanCreate(HuffmanTree *HT, const int weights[], int n)
{
//@s 结点总数
    int m;
//@s 循环用
    int i;
//@s 两个最小的下标
    int s1, s2;

//@s 只有一个结点就没法合并了
    if (n <= 1)
    {
        *HT = NULL;
        return;
    }

//@s 总数 2n-1，多开一格让下标从 1 开始
    m = 2 * n - 1;
    *HT = (HuffmanTree)malloc((m + 1) * sizeof(HTNode));

//@s 初始化前 n 个：填权值，父亲和孩子都置 0
    for (i = 1; i <= n; i++)
    {
        (*HT)[i].weight = weights[i - 1];
        (*HT)[i].parent = 0;
        (*HT)[i].left = 0;
        (*HT)[i].right = 0;
    }

//@s 后面的内部结点先全部置 0
    for (i = n + 1; i <= m; i++)
    {
        (*HT)[i].weight = 0;
        (*HT)[i].parent = 0;
        (*HT)[i].left = 0;
        (*HT)[i].right = 0;
    }

//@s 从 n+1 号开始，一个一个合并出来
    for (i = n + 1; i <= m; i++)
    {
//@s 在已经建好的 1..i-1 里挑两个最小的
        SelectTwoMin(*HT, i - 1, &s1, &s2);

//@s 两个都认 i 当父亲
        (*HT)[s1].parent = i;
        (*HT)[s2].parent = i;

//@s i 的左右孩子
        (*HT)[i].left = s1;
        (*HT)[i].right = s2;

//@s i 的权值 = 两个孩子之和
        (*HT)[i].weight = (*HT)[s1].weight + (*HT)[s2].weight;
    }

//@s 循环结束时 i = m+1，最后一个建好的结点 m 就是根
}
//%end

//%module | 04 | HuffmanCodes | HuffmanCodes —— 生成编码 | 3 | 01,03 |
//%summary | 从每个叶子往根走，是左孩子记 0、右孩子记 1，最后反过来。
//@d ============ 为什么编码要"倒着走" ============
//@d
//@d 每个结点的左右孩子已经定了（建树时就定了）。约定：
//@d
//@d   往左走 = 0，往右走 = 1
//@d
//@d 那么"从根走到某个叶子"的路径就是一串 0/1，这串就是该叶子的编码。
//@d
//@d 但**数组里只有父子关系，没有"我是左还是右"的信息** —— 那要往下看才知道。
//@d 所以反过来做：**从叶子往上走到根**，每步判断"我是父亲的左孩子还是右孩子"，
//@d 就能记下 0/1。只是这样记出来的顺序是**倒的**，最后要翻过来。
//@d
//@d ============ 走一遍 ============
//@d
//@d 假设某棵哈夫曼树里，结点 4（权值 4）到根的路径是：
//@d
//@d   4 → 8 → 9（根）      且 4 是 8 的右孩子，8 是 9 的右孩子
//@d
//@d   从下往上记：先记 4 是右孩子 → 1，再记 8 是右孩子 → 1
//@d   记下来是 "11"（但这是倒着的，因为先记的是低位）
//@d
//@d 这里有个实现上的小技巧：**从数组尾部往前填**。
//@d
//@d   开一个长度 n 的字符数组 cd，把 cd[n-1] 置成字符串结束符 '\0'，
//@d   然后用 start 从 n-1 往前移动，每走一步 start-- 并写入一位。
//@d   走完之后 &cd[start] 就是正确的字符串（不用再手动翻转）。
//@d
//@d ============ 前缀码 ============
//@d
//@d 哈夫曼编码有一个关键性质：**任何一个编码都不是另一个的前缀**。
//@d
//@d 为什么？因为所有叶子都在树的末端，从根到叶子的路径不可能
//@d 是"到另一个叶子的路径"的前缀 —— 走到叶子就停了，没法继续往下走。
//@d
//@d 这个性质叫**前缀码**，它保证解码时不会歧义：
//@d 拿一串 0/1 过来，从根开始走，走到叶子就解出一个字符，然后回到根继续。

//@s 生成每个叶子的编码，结果放进 *HC
//@d 注意 HC 的下标和叶子下标一一对应（也用 1..n）：
//@d     HC[i] 是第 i 个叶子的编码字符串
void HuffmanCodes(HuffmanTree HT, int n, HuffmanCode *HC)
{
//@s 叶子下标
    int i;
//@s c 是"当前结点"，p 是"它的父亲"
    int c, p;
//@s 从后往前填的位置
    int start;
//@s 临时缓冲区：编码最长不会超过 n 位
    char *cd;

//@s 分配缓冲区
    cd = (char *)malloc((n + 1) * sizeof(char));
//@s 编码表比叶子多一格，方便用 1..n 下标
    *HC = (HuffmanCode)malloc((n + 1) * sizeof(char *));

//@s 从末尾开始填，先放结束符
    cd[n - 1] = '\0';

//@s 每个叶子各生成一条
    for (i = 1; i <= n; i++)
    {
//@s 每次都从缓冲区末尾开始往前填
        start = n - 1;

//@s 从叶子一路走到根
//@d 循环三件事一起做：c 变成 p、p 变成 p 的父亲、start 往前挪一格。
        for (c = i, p = HT[i].parent; p != 0; c = p, p = HT[p].parent)
        {
//@s 是父亲的左孩子就记 0
            if (HT[p].left == c)
            {
                cd[--start] = '0';
            }
//@s 否则（右孩子）记 1
            else
            {
                cd[--start] = '1';
            }
        }

//@s 把 &cd[start] 这一截拷出来，就是该叶子的编码
//@d 长度是 n - start，再加一个结束符的位置。
        (*HC)[i] = (char *)malloc((n - start + 1) * sizeof(char));
        strcpy((*HC)[i], &cd[start]);
    }

//@s 释放缓冲区
    free(cd);
}
//%end

//%module | 05 | GetWPL | GetWPL —— 计算带权路径长度 | 2 | 01 |
//%summary | 每个叶子往上数层数，乘上权值，加起来。
//@d ============ WPL 是什么 ============
//@d
//@d     WPL = Σ (叶子的权值 × 叶子的层数)
//@d
//@d 层数从根算起，根是第 0 层（或者算成第 1 层，只要一致就行；
//@d 这里用"往上走几步"来数，叶子自己算 0 步，所以根下面的叶子是 1）。
//@d
//@d 拿一个例子算算（权值 1 2 3）：
//@d
//@d       (6)              叶子 1 和 2 在第 2 层，叶子 3 在第 1 层
//@d      /   \
//@d    (3)    3            WPL = 1×2 + 2×2 + 3×1 = 9
//@d   /   \
//@d  1     2
//@d
//@d 换一种组织方式：
//@d
//@d      (6)
//@d     /   \
//@d    1    (5)            叶子 1 在第 1 层，2 和 3 在第 2 层
//@d        /   \
//@d       2     3          WPL = 1×1 + 2×2 + 3×2 = 11
//@d
//@d **9 < 11** —— 第一种更好。而第一种正是哈夫曼算法给出的结果：
//@d 权值小的（1、2）放得深，权值大的（3）放得浅。
//@d
//@d 这就是"哈夫曼树是带权路径长度最小的二叉树"的含义。
//@d
//@d ============ 怎么数层数 ============
//@d
//@d 从叶子顺着 parent 往上走，走一步层数加一，直到 parent 为 0（到根了）。
//@d 和生成编码时的走法一样，只是这里只数步数。

//@s 计算并返回 WPL
int GetWPL(HuffmanTree HT, int n)
{
//@s 叶子下标
    int i;
//@s 往上走的指针
    int p;
//@s 当前叶子的层数
    int depth;
//@s 累加结果
    int wpl = 0;

//@s 逐个叶子算
    for (i = 1; i <= n; i++)
    {
//@s 从 0 层开始数
        depth = 0;

//@s 一路往上走到根
//@d 每走一步就多一层。走到 parent == 0 说明到根了。
        for (p = HT[i].parent; p != 0; p = HT[p].parent)
        {
            depth++;
        }

//@s 这一层的代价：权值 × 层数
        wpl += depth * HT[i].weight;
    }

//@s 返回总和
    return wpl;
}
//%end

//%module | 06 | PrintCoding | PrintCoding —— 打印与自查 | 1 | 01 |
//%summary | 把每个叶子的权值和编码列出来，顺便核对前缀码性质。
//@d ============ 自查两件事 ============
//@d
//@d   ① **编码长度和权值成反比**：权值大的编码短。
//@d      这是哈夫曼编码能压缩文件的原因。
//@d
//@d   ② **没有编码是另一个的前缀**。
//@d      可以两两比较一下，确认没有互相"包含"的情况。

//@s 打印每个叶子的权值、编码、以及贡献的位数
void PrintCoding(HuffmanTree HT, HuffmanCode HC, int n)
{
//@s 循环用
    int i;
//@s 总位数（用来算压缩比）
    int totalBits = 0;
//@s 所有叶子的权值之和（= 定长编码时要用到的字符总数）
    int totalWeight = 0;
//@s 如果每个字符都用固定长度编码，需要多少位
    int fixedBits;

//@s 表头
    printf("叶子   权值   编码      长度\n");
    printf("----  -----  --------  ----\n");

    for (i = 1; i <= n; i++)
    {
        printf(" %2d    %4d   %-8s   %d\n", i, HT[i].weight, HC[i], (int)strlen(HC[i]));
        totalBits += HT[i].weight * (int)strlen(HC[i]);
        totalWeight += HT[i].weight;
    }

//@s 固定长度编码需要 log2(n) 上取整位
    fixedBits = 1;
    while ((1 << fixedBits) < n)
    {
        fixedBits++;
    }

//@s 对比一下
    printf("\n哈夫曼编码总位数 = %d\n", totalBits);
    printf("定长编码总位数   = %d（每个字符 %d 位 × 总权重 %d）\n",
           fixedBits * totalWeight, fixedBits, totalWeight);
    printf("（省了 %d 位，约为原来的 %.0f%% —— 这就是压缩的来源）\n",
           fixedBits * totalWeight - totalBits,
           100.0 * totalBits / (fixedBits * totalWeight));
}

//@s 检查前缀码性质：没有任何编码是另一个的前缀
//@d 返回 1 表示性质成立
int CheckPrefixFree(HuffmanCode HC, int n)
{
//@s 两两比较
    int i, j;

    for (i = 1; i <= n; i++)
    {
        for (j = 1; j <= n; j++)
        {
//@s 自己不比自己
            if (i == j)
            {
                continue;
            }
//@s 如果 i 的编码是 j 的前缀，就违反前缀码
//@d strncmp 比较前 strlen(HC[i]) 个字符。
            if (strncmp(HC[i], HC[j], strlen(HC[i])) == 0)
            {
                printf("  违反前缀码：%s 是 %s 的前缀\n", HC[i], HC[j]);
                return 0;
            }
        }
    }
    return 1;
}
//%end

//%module | 07 | FreeAll | FreeAll —— 释放 | 1 | 01 |
//%summary | 先放编码字符串，再放编码表，最后放结点数组。
//@d ============ 释放顺序 ============
//@d
//@d   HC 是 char **，里面每个元素都是单独 malloc 出来的字符串。
//@d   所以必须先一个个 free 掉里面的字符串，再 free HC 这个数组本身。
//@d
//@d 顺序反过来的话，HC 已经被释放，就没法再拿到里面那些指针了 —— 直接泄漏。
//@d
//@d 记住这个套路：**释放"指针的数组"时，永远从里往外放**。

void FreeAll(HuffmanTree HT, HuffmanCode HC, int n)
{
//@s 释放每个编码字符串
    int i;

    if (HC != NULL)
    {
        for (i = 1; i <= n; i++)
        {
            free(HC[i]);
        }
//@s 再释放编码表
        free(HC);
    }

//@s 最后释放结点数组
    free(HT);
}
//%end

//%module | 08 | main | main —— 把哈夫曼树跑一遍 | 2 | 01,02,03,04,05,06,07 |
//%summary | 建树、算 WPL、生成编码，并和定长编码对比压缩率。
//@d ============ 用一个真实场景做例子 ============
//@d
//@d 假设有一段文本，各字符出现次数（也就是权值）是：
//@d
//@d   A: 5   B: 2   C: 7   D: 1   E: 4
//@d
//@d 哈夫曼编码会给出现最多的 C（7）分配最短的编码，
//@d 给最少的 D（1）分配最长的编码。
//@d
//@d 这样整段文本的总位数最少 —— 这就是 gzip、zip、JPEG 里都在用的思路。

//@s 主函数
int main(void)
{
//@s 五个叶子的权值
    static const int w[] = { 5, 2, 7, 1, 4 };
//@s 叶子个数
    int n = 5;
//@s 树
    HuffmanTree HT = NULL;
//@s 编码表
    HuffmanCode HC = NULL;
//@s 循环用
    int i;

//@s 打印输入的权值
    printf("叶子权值: ");
    for (i = 0; i < n; i++)
    {
        printf("%d ", w[i]);
    }
    printf("\n\n");

//@s 建树
    HuffmanCreate(&HT, w, n);

//@s 打印建出来的树（用缩进表示层次）
//@d 从最后一个结点（根）开始递归往下打印。
    printf("建出的哈夫曼树（根在最后，下标 %d）:\n", 2 * n - 1);
    printf("  结点总数 = 2n-1 = %d\n", 2 * n - 1);
    printf("  根权值 = %d（所有叶子之和）\n\n", HT[2 * n - 1].weight);

//@s 打印每个内部结点的合并情况
    printf("合并过程:\n");
    for (i = n + 1; i <= 2 * n - 1; i++)
    {
        printf("  结点 %2d = 结点 %2d + 结点 %2d，权值 %d\n",
               i, HT[i].left, HT[i].right, HT[i].weight);
    }

//@s 算 WPL
    printf("\n带权路径长度 WPL = %d\n", GetWPL(HT, n));
    printf("（权值小的放得深、大的放得浅，这个值就是所有方案里最小的）\n\n");

//@s 生成编码
    HuffmanCodes(HT, n, &HC);
    PrintCoding(HT, HC, n);

//@s 检查前缀码
    printf("\n前缀码检查: %s\n", CheckPrefixFree(HC, n) ? "没有任何编码是别人的前缀" : "发现问题");

//@s 释放
    FreeAll(HT, HC, n);
//@s 正常结束
    return 0;
}
//%end
