#%summary | 建树、算 WPL、生成编码，并和定长编码对比压缩率。
#@d ============ 用一个真实场景做例子 ============
#@d
#@d 假设有一段文本，各字符出现次数（也就是权值）是：
#@d
#@d   A: 5   B: 2   C: 7   D: 1   E: 4
#@d
#@d 哈夫曼编码会给出现最多的 C（7）分配最短的编码，
#@d 给最少的 D（1）分配最长的编码。
#@d
#@d 这样整段文本的总位数最少 —— 这就是 gzip、zip、JPEG 里都在用的思路。
#@d
#@d ============ 和 C 版的写法差别 ============
#@d   1. HT = HuffmanCreate(w, n) 直接接返回值，没有二级指针。
#@d   2. PrintCoding 在 C 里顺便算了 totals 并打印压缩比，
#@d      Python 版把同样的打印放在 main 里 —— 为了和 C 输出顺序完全一致，
#@d      这里让 PrintCoding 自己打完那几行（见它的实现）。
#@d   3. FreeAll 传的是局部变量，Python 里改不了调用者，所以它只是占位。

#@s 主函数：Python 用 if __name__ 的固定写法代替 C 的 main
if __name__ == '__main__':
    #@s 五个叶子的权值
    w = [5, 2, 7, 1, 4]
    #@s 叶子个数
    n = 5
#@s 循环用
#@d C 要在这里声明 int i，Python 的 for 自带循环变量，不用先声明

    #@s 打印输入的权值
    #@d C 是 printf("%d ") 逐个打，每个数后面都有空格（含最后一个），
    #@d 所以这里用 end=' ' 而不是 ' '.join。
    print('叶子权值: ', end='')
    for x in w:
        print(x, end=' ')
    print()
    print()

    #@s 建树
    HT = HuffmanCreate(w, n)

    #@s 打印建出来的树（用缩进表示层次）
    #@d 从最后一个结点（根）开始递归往下打印。
    print(f'建出的哈夫曼树（根在最后，下标 {2 * n - 1}）:')
    print(f'  结点总数 = 2n-1 = {2 * n - 1}')
    print(f'  根权值 = {HT[2 * n - 1].weight}（所有叶子之和）')
    print()

    #@s 打印每个内部结点的合并情况
    print('合并过程:')
    for i in range(n + 1, 2 * n - 1 + 1):
        print(f'  结点 {i:2d} = 结点 {HT[i].left:2d} + 结点 {HT[i].right:2d}，权值 {HT[i].weight}')

    #@s 算 WPL
    print()
    print(f'带权路径长度 WPL = {GetWPL(HT, n)}')
    print('（权值小的放得深、大的放得浅，这个值就是所有方案里最小的）')
    print()

    #@s 生成编码
    HC = HuffmanCodes(HT, n)
    PrintCoding(HT, HC, n)

    #@s 检查前缀码
    print()
    print(f'前缀码检查: {"没有任何编码是别人的前缀" if CheckPrefixFree(HC, n) else "发现问题"}')

    #@s 释放（Python 里是占位，见 FreeAll 的说明）
    FreeAll(HT, HC, n)
#@s 正常结束
#@d C 在这里 return 0。Python 的脚本不需要写返回值。
#%end
