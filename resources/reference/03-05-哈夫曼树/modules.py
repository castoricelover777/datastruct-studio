#%module | 01 | typedef | 头文件与 typedef | 2 |
#%summary | 用数组存树：每个结点记权值、父亲、左右孩子（都是下标）。
#@d ============ 为什么用数组而不是指针 ============
#@d
#@d 建哈夫曼树的过程中，要**反复找出权值最小的两个结点**。
#@d 如果用指针，每次都得遍历整棵树去比较，很别扭。
#@d
#@d 用数组就没这个问题：所有结点排成一排，下标一扫就知道谁最小，
#@d 而且新合并出来的结点直接追加在数组后面就行。
#@d
#@d ============ 为什么需要 parent ============
#@d
#@d 有两个原因：
#@d
#@d   ① 挑选的时候，**已经合并过的结点不能再参与** —— 靠 parent != 0 判断
#@d   ② 生成编码的时候，是**从叶子往根走**的（一步步找 parent），
#@d      走出来的 0/1 是倒着的，最后要反过来
#@d
#@d 所以虽然树是"从上往下"的父子关系，但算法里大量用的是"从下往上"。
#@d
#@d ============ 数组要开多大 ============
#@d
#@d n 个叶子，每次合并少一个结点、多一个内部结点，一共要合并 n-1 次，
#@d 所以内部结点有 n-1 个，总数是 **2n-1**。
#@d 数组开 2n 个（下标 0 不用），够用。
#@d
#@d ============ Python 版为什么几乎一样 ============
#@d
#@d   这一节是少见的"用数组存树"，本来就没有指针链，
#@d   所以 Python 版和 C 版长得非常像，只差三件事：
#@d
#@d   1. struct 换成 class，字段名照抄（weight / parent / left / right）
#@d   2. 下标照旧从 1 开始，列表下标 0 空着当"空指针"用 ——
#@d      所以 Python 的列表要多开一格，初始化成 [None] * (m + 1)
#@d   3. 没有 malloc / free，编码用 Python 的字符串直接拼，不用 '\0'

#@s 哈夫曼树的结点
#@d parent / left / right 存的都是**数组下标**，0 表示"没有"
#@d （所以下标要从 1 开始用，0 号位置空着当"空指针"）
class HTNode:
    #@s 造结点时四个字段一次填好
    def __init__(self, weight=0, parent=0, left=0, right=0):
        #@s 权值：叶子是给定的，内部结点是两个孩子之和
        self.weight = weight
        #@s 父亲的下标
        self.parent = parent
        #@s 左孩子的下标
        self.left = left
        #@s 右孩子的下标
        self.right = right

#@s 状态码
OK = 1
ERROR = 0
Status = int
#@d C 里还有 typedef char **HuffmanCode，也就是"字符串数组"。
#@d Python 里直接用一个列表装字符串就行，不需要这个类型名。
#%end

#%module | 02 | SelectTwoMin | SelectTwoMin —— 选出两个最小的 | 2 | 01 |
#%summary | 在所有「还没有父亲」的结点里挑出权值最小的两个。
#@d ============ 两个条件缺一不可 ============
#@d
#@d 挑选的时候要同时满足：
#@d
#@d   ① **parent == 0**：还没有被合并过。
#@d      合并过的结点已经有父亲了，再挑它就重复了。
#@d
#@d   ② 权值最小 / 次小。
#@d
#@d 为什么必须检查 ①？因为数组里既有"还没用的叶子"，也有"已经合并好的内部结点"，
#@d 还有"已经当过孩子的结点"。只看权值会把已经用过的又挑出来，
#@d 建出来的树就完全错了 —— 而且它照样能跑完，只是 WPL 不对，很难发现。
#@d
#@d ============ 怎么一次遍历找出最小和次小 ============
#@d
#@d 用一个经典写法：
#@d
#@d   遇到比"当前最小"还小的 → 原来的最小降级成次小，新的当最小
#@d   否则如果比"当前次小"还小 → 它当次小
#@d
#@d 这样一遍扫下来两个都拿到了，不用扫两遍。
#@d
#@d ============ 出口参数改成返回值 ============
#@d   C 用两个指针 int *s1, int *s2 把结果带出去，
#@d   Python 直接 return min1, min2。
#@d   比较的严格小于（<）也照抄，所以权值相同时挑中的下标和 C 版完全一致。

#@s 在 1..n 范围内找出两个权值最小且没有父亲的结点
#@s 返回 (最小下标, 次小下标)
def SelectTwoMin(HT, n):
    #@s 记录最小和次小的下标，-1 表示还没找到
    min1 = -1
    min2 = -1

    #@s 一遍扫完
    for i in range(1, n + 1):
        #@s 已经有父亲的跳过 —— 这一条千万不能漏
        if HT[i].parent != 0:
            continue

        #@s 比当前最小还小：原来的冠军降为亚军
        if min1 == -1 or HT[i].weight < HT[min1].weight:
            min2 = min1
            min1 = i
        #@s 否则看看能不能当亚军
        elif min2 == -1 or HT[i].weight < HT[min2].weight:
            min2 = i

    #@s 把两个下标一起交出去
    return min1, min2
#%end

#%module | 03 | HuffmanCreate | HuffmanCreate —— 建树 | 3 | 01,02 |
#%summary | 反复挑两个最小的合并，直到只剩一个结点。
#@d ============ 建树过程走一遍 ============
#@d
#@d 权值 {1, 2, 3, 4, 5}，n = 5，总共要 2n-1 = 9 个结点。
#@d
#@d 一开始 1..5 是五个叶子，6..9 是待填的内部结点：
#@d
#@d   下标:  1    2    3    4    5  │  6    7    8    9
#@d   权值:  1    2    3    4    5  │  ?    ?    ?    ?
#@d
#@d **第 1 轮**：在 1..5 里挑最小的两个 → 1 和 2
#@d
#@d   合并成结点 6，权值 3
#@d   1 的父亲 = 6，2 的父亲 = 6，6 的左孩子 = 1、右孩子 = 2
#@d
#@d   下标:  1    2    3    4    5  │  6    7    8    9
#@d   权值:  1    2    3    4    5  │  3    ?    ?    ?
#@d   父  :  6    6    0    0    0  │  0
#@d
#@d **第 2 轮**：在 1..6 里挑"没有父亲"的最小的两个 → 3（下标 3）和 6
#@d
#@d   注意 1 和 2 因为有父亲了，不再参与挑选。
#@d   合并成结点 7，权值 6。
#@d
#@d   ... 一直做到第 9 号结点，它就是根。
#@d
#@d 最后根的 parent 还是 0，这就是"根"的标志。
#@d
#@d ============ 为什么循环范围是 1..i-1 ============
#@d
#@d 每一轮的范围是"已经建好的所有结点"，也就是 1 到 i-1。
#@d 因为新结点 i 还没填，它不参与这一轮的挑选。
#@d
#@d ============ 二级指针改成返回值 ============
#@d   C 的参数是 HuffmanTree *HT，把新建的数组通过指针带出去。
#@d   Python 直接 return HT 就行，调用者写 HT = HuffmanCreate(w, n)。
#@d   注意列表下标 0 也要占一格（空着不用），这样后面所有下标都是从 1 起，
#@d   和 C 版一模一样，公式 2i / 2i+1 不用重新推导。

#@s 用 weights[0..n-1] 建一棵哈夫曼树，返回结点数组
def HuffmanCreate(weights, n):
    #@s 结点总数
    m = 2 * n - 1

    #@s 只有一个结点就没法合并了
    if n <= 1:
        return None

    #@s 开 m+1 个格子，下标 0 空着不用（对应 C 的 malloc 多开一格）
    HT = [HTNode() for _ in range(m + 1)]

    #@s 初始化前 n 个：填权值，父亲和孩子都置 0
    for i in range(1, n + 1):
        HT[i].weight = weights[i - 1]
        HT[i].parent = 0
        HT[i].left = 0
        HT[i].right = 0

    #@s 后面的内部结点先全部置 0
    for i in range(n + 1, m + 1):
        HT[i].weight = 0
        HT[i].parent = 0
        HT[i].left = 0
        HT[i].right = 0

    #@s 从 n+1 号开始，一个一个合并出来
    for i in range(n + 1, m + 1):
        #@s 在已经建好的 1..i-1 里挑两个最小的
        s1, s2 = SelectTwoMin(HT, i - 1)

        #@s 两个都认 i 当父亲
        HT[s1].parent = i
        HT[s2].parent = i

        #@s i 的左右孩子
        HT[i].left = s1
        HT[i].right = s2

        #@s i 的权值 = 两个孩子之和
        HT[i].weight = HT[s1].weight + HT[s2].weight

    #@s 循环结束时最后一个建好的结点 m 就是根，它的 parent 还是 0
    return HT
#%end

#%module | 04 | HuffmanCodes | HuffmanCodes —— 生成编码 | 3 | 01,03 |
#%summary | 从每个叶子往根走，是左孩子记 0、右孩子记 1，最后反过来。
#@d ============ 为什么编码要"倒着走" ============
#@d
#@d 每个结点的左右孩子已经定了（建树时就定了）。约定：
#@d
#@d   往左走 = 0，往右走 = 1
#@d
#@d 那么"从根走到某个叶子"的路径就是一串 0/1，这串就是该叶子的编码。
#@d
#@d 但**数组里只有父子关系，没有"我是左还是右"的信息** —— 那要往下看才知道。
#@d 所以反过来做：**从叶子往上走到根**，每步判断"我是父亲的左孩子还是右孩子"，
#@d 就能记下 0/1。只是这样记出来的顺序是**倒的**，最后要翻过来。
#@d
#@d ============ 走一遍 ============
#@d
#@d 假设某棵哈夫曼树里，结点 4（权值 4）到根的路径是：
#@d
#@d   4 → 8 → 9（根）      且 4 是 8 的右孩子，8 是 9 的右孩子
#@d
#@d   从下往上记：先记 4 是右孩子 → 1，再记 8 是右孩子 → 1
#@d   记下来是 "11"（但这是倒着的，因为先记的是低位）
#@d
#@d 这里有个实现上的小技巧：**从数组尾部往前填**。
#@d
#@d   开一个长度 n 的字符数组 cd，把 cd[n-1] 置成字符串结束符 '\0'，
#@d   然后用 start 从 n-1 往前移动，每走一步 start-- 并写入一位。
#@d   走完之后 &cd[start] 就是正确的字符串（不用再手动翻转）。
#@d
#@d ============ 前缀码 ============
#@d
#@d 哈夫曼编码有一个关键性质：**任何一个编码都不是另一个的前缀**。
#@d
#@d 为什么？因为所有叶子都在树的末端，从根到叶子的路径不可能
#@d 是"到另一个叶子的路径"的前缀 —— 走到叶子就停了，没法继续往下走。
#@d
#@d 这个性质叫**前缀码**，它保证解码时不会歧义：
#@d 拿一串 0/1 过来，从根开始走，走到叶子就解出一个字符，然后回到根继续。
#@d
#@d ============ Python 版：不用"从后往前填"那一套 ============
#@d
#@d   C 之所以要从 cd 的尾部往前填，是因为 C 的字符串要靠 '\0' 结尾，
#@d   而且没法方便地在前面插入字符。
#@d
#@d   Python 的字符串不可变，但可以直接"往前面拼"：
#@d       code = ('0' if ... else '1') + code
#@d   每走一步把新的一位拼在**左边**，走完自然就是正序，不用翻转、
#@d   也不用提前留缓冲区。这是 Python 写起来更短的地方。

#@s 生成每个叶子的编码，返回编码表（下标 1..n 与叶子对应）
def HuffmanCodes(HT, n):
    #@s 编码表比叶子多一格，方便用 1..n 下标
    HC = [None] * (n + 1)

    #@s 每个叶子各生成一条
    for i in range(1, n + 1):
        #@s 当前这条编码，从空串开始
        code = ''

        #@s 从叶子一路走到根
        #@d 循环三件事一起做：c 变成 p、p 变成 p 的父亲。
        c = i
        p = HT[i].parent
        while p != 0:
            #@s 是父亲的左孩子就记 0
            if HT[p].left == c:
                code = '0' + code
            #@s 否则（右孩子）记 1
            else:
                code = '1' + code
            #@s 往上走一层
            c = p
            p = HT[p].parent

        #@s 走完就是正序的编码
        HC[i] = code

    #@s 把编码表交出去
    return HC
#%end

#%module | 05 | GetWPL | GetWPL —— 计算带权路径长度 | 2 | 01 |
#%summary | 每个叶子往上数层数，乘上权值，加起来。
#@d ============ WPL 是什么 ============
#@d
#@d     WPL = Σ (叶子的权值 × 叶子的层数)
#@d
#@d 层数从根算起，根是第 0 层（或者算成第 1 层，只要一致就行；
#@d 这里用"往上走几步"来数，叶子自己算 0 步，所以根下面的叶子是 1）。
#@d
#@d 拿一个例子算算（权值 1 2 3）：
#@d
#@d       (6)              叶子 1 和 2 在第 2 层，叶子 3 在第 1 层
#@d      /   \
#@d    (3)    3            WPL = 1×2 + 2×2 + 3×1 = 9
#@d   /   \
#@d  1     2
#@d
#@d 换一种组织方式：
#@d
#@d      (6)
#@d     /   \
#@d    1    (5)            叶子 1 在第 1 层，2 和 3 在第 2 层
#@d        /   \
#@d       2     3          WPL = 1×1 + 2×2 + 3×2 = 11
#@d
#@d **9 < 11** —— 第一种更好。而第一种正是哈夫曼算法给出的结果：
#@d 权值小的（1、2）放得深，权值大的（3）放得浅。
#@d
#@d 这就是"哈夫曼树是带权路径长度最小的二叉树"的含义。
#@d
#@d ============ 怎么数层数 ============
#@d
#@d 从叶子顺着 parent 往上走，走一步层数加一，直到 parent 为 0（到根了）。
#@d 和生成编码时的走法一样，只是这里只数步数。

#@s 计算并返回 WPL
def GetWPL(HT, n):
    #@s 累加结果
    wpl = 0

    #@s 逐个叶子算
    for i in range(1, n + 1):
        #@s 从 0 层开始数
        depth = 0

        #@s 一路往上走到根
        #@d 每走一步就多一层。走到 parent == 0 说明到根了。
        p = HT[i].parent
        while p != 0:
            depth += 1
            p = HT[p].parent

        #@s 这一层的代价：权值 × 层数
        wpl += depth * HT[i].weight

    #@s 返回总和
    return wpl
#%end

#%module | 06 | PrintCoding | PrintCoding —— 打印与自查 | 1 | 01 |
#%summary | 把每个叶子的权值和编码列出来，顺便核对前缀码性质。
#@d ============ 自查两件事 ============
#@d
#@d   ① **编码长度和权值成反比**：权值大的编码短。
#@d      这是哈夫曼编码能压缩文件的原因。
#@d
#@d   ② **没有编码是另一个的前缀**。
#@d      可以两两比较一下，确认没有互相"包含"的情况。
#@d
#@d ============ 打印格式要和 C 版一字不差 ============
#@d
#@d   C 的格式串是 printf(" %2d    %4d   %-8s   %d\n", ...)，
#@d   Python 写成 f'{i:2d}    {w:4d}   {code:<8s}   {len(code)}'，
#@d   前面那个空格也要留着（" %2d" 是以空格开头再右对齐 2 位）。
#@d
#@d   %-8s 是"左对齐、补到 8 个字符宽"，Python 的 {code:<8} 一样。

#@s 打印每个叶子的权值、编码、以及贡献的位数
#@s 返回 (总位数, 总权重)，供调用者继续算压缩比
def PrintCoding(HT, HC, n):
    #@s 总位数（用来算压缩比）
    totalBits = 0
    #@s 所有叶子的权值之和（= 定长编码时要用到的字符总数）
    totalWeight = 0

    #@s 表头
    print('叶子   权值   编码      长度')
    print('----  -----  --------  ----')

    for i in range(1, n + 1):
        print(f' {i:2d}    {HT[i].weight:4d}   {HC[i]:<8s}   {len(HC[i])}')
        totalBits += HT[i].weight * len(HC[i])
        totalWeight += HT[i].weight

    #@s 固定长度编码需要 log2(n) 上取整位
    fixedBits = 1
    while (1 << fixedBits) < n:
        fixedBits += 1

    #@s 对比一下
    #@d C 里 %.0f 是"保留 0 位小数"，Python 用 :.0f 一样。
    print()
    print(f'哈夫曼编码总位数 = {totalBits}')
    print(f'定长编码总位数   = {fixedBits * totalWeight}（每个字符 {fixedBits} 位 × 总权重 {totalWeight}）')
    print(f'（省了 {fixedBits * totalWeight - totalBits} 位，约为原来的 {100.0 * totalBits / (fixedBits * totalWeight):.0f}% —— 这就是压缩的来源）')

#@s 检查前缀码性质：没有任何编码是另一个的前缀
#@d 返回 1 表示性质成立
def CheckPrefixFree(HC, n):
    #@s 两两比较
    for i in range(1, n + 1):
        for j in range(1, n + 1):
            #@s 自己不比自己
            if i == j:
                continue
            #@s 如果 i 的编码是 j 的前缀，就违反前缀码
            #@d C 的 strncmp(HC[i], HC[j], strlen(HC[i])) == 0，
            #@d Python 直接写 HC[j].startswith(HC[i])，意思一样但清楚得多。
            if HC[j].startswith(HC[i]):
                print(f'  违反前缀码：{HC[i]} 是 {HC[j]} 的前缀')
                return 0
    return 1
#%end

#%module | 07 | FreeAll | FreeAll —— 释放 | 1 | 01 |
#%summary | 先放编码字符串，再放编码表，最后放结点数组。
#@d ============ 释放顺序 ============
#@d
#@d   HC 是 char **，里面每个元素都是单独 malloc 出来的字符串。
#@d   所以必须先一个个 free 掉里面的字符串，再 free HC 这个数组本身。
#@d
#@d 顺序反过来的话，HC 已经被释放，就没法再拿到里面那些指针了 —— 直接泄漏。
#@d
#@d 记住这个套路：**释放"指针的数组"时，永远从里往外放**。
#@d
#@d ============ Python 版没有 free，但这个顺序仍然值得看 ============
#@d
#@d   Python 里不用手动释放，函数返回后 HT 和 HC 没人引用就自动回收。
#@d   所以这个函数在 Python 里没什么事可做 —— 但保留它有两个好处：
#@d     1. 主函数的结构（建 → 用 → 释放）和 C 版一一对应，好对照；
#@d     2. "从里往外放"这个顺序讲的是**依赖关系**，
#@d        在别的语言里（包括 Python 处理文件、连接这类资源时）照样成立。

#@s Python 版是占位实现：把两个引用置空，说明"用完了"
def FreeAll(HT, HC, n):
    #@d C 里在这里逐个 free(HC[i])、free(HC)、free(HT)。
    #@d Python 不用管，但把引用置成 None 至少表达了"不再使用"的意图。
    HT = None
    HC = None
#%end

