/*
 * ============================================================================
 *  数据结构研习社 —— 03 树 / 03-06 并查集
 * ============================================================================
 *
 *  并查集解决一类很具体的问题：**一堆元素不断被合并成组，随时要问
 *  "这两个是不是同一组的"**。
 *
 *      5 个元素，初始各自一组：  ① ② ③ ④ ⑤
 *
 *      合并 1 和 2            ①②  ③ ④ ⑤
 *      合并 3 和 4            ①②  ③④  ⑤
 *      问 1 和 3 同组吗？      不是
 *      合并 2 和 3            ①②③④  ⑤
 *      问 1 和 4 同组吗？      是
 *
 *  它的实现简单到有点出人意料 —— **就是一个数组**：
 *
 *      parent[i] >= 0  →  i 的父亲是 parent[i]
 *      parent[i] <  0  →  i 是根，绝对值是这个集合的元素个数
 *
 *  两个优化让它快到几乎常数：
 *
 *      按大小合并（Union by Size）—— 避免长成细长的链
 *      路径压缩（Path Compression）—— 查找时顺手把路过的结点直接挂到根上
 *
 *  典型用途：判断无向图有没有环、数连通分量、Kruskal 最小生成树。
 *
 *  标记约定同前（本文件本身可编译）。
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>

//%module | 01 | typedef | 头文件与 typedef | 2 |
//%summary | 一个数组就是一片森林：负数表示根，绝对值是集合大小。
//@d ============ 用负数表示根，这个设计很妙 ============
//@d
//@d 数组里每个位置存一个整数，含义看正负：
//@d
//@d     parent[i] = 3   →  i 的父亲是 3
//@d     parent[i] = -1  →  i 是根，这个集合有 1 个元素（只有它自己）
//@d     parent[i] = -4  →  i 是根，这个集合有 4 个元素
//@d
//@d 为什么用负数而不是另开一个数组存"集合大小"？
//@d
//@d   ① 省一个数组；
//@d   ② **判断根只需要看一个数**：`parent[i] < 0` 就是根，不用再查别的表；
//@d   ③ 合并时也方便：两个根的大小就是两个负数，加起来直接得到新大小。
//@d
//@d 这是个典型的"用一个字段表达两层含义"的技巧。代价是可读性稍差，
//@d 所以注释一定要写清楚。
//@d
//@d ============ 初始状态 ============
//@d
//@d 一开始谁和谁都没关系，所以**每个元素各自成一个集合**：
//@d
//@d     下标:   0   1   2   3   4
//@d     parent: -1  -1  -1  -1  -1
//@d             ↑全部是根，每个集合只有自己
//@d
//@d 注意这里用的是 0 起始的下标，和堆那种"从 1 开始"不一样 ——
//@d 并查集的元素编号本来就是任意的，直接用 0..n-1 最省事。

//@s 最大元素个数
#define MaxSize 1000

//@s 并查集：一个数组 + 元素个数
typedef struct
{
//@s parent[i] >= 0 是父亲下标；< 0 表示它是根，绝对值是集合大小
    int *parent;
//@s 元素个数
    int n;
} DisjSet;

//@s 状态码
#define OK 1
#define ERROR 0
typedef int Status;

//@s 建一个含 n 个元素的并查集，每个元素各自一组
//@d 这个函数和结构定义放一起，因为它就是"结构的一部分"。
DisjSet *InitSet(int n)
{
//@s 分配结构
    DisjSet *S = (DisjSet *)malloc(sizeof(DisjSet));
//@s 分配数组
    int i;

    S->parent = (int *)malloc(n * sizeof(int));
    S->n = n;

//@s 每个元素都置 -1：自己是根，集合大小为 1
    for (i = 0; i < n; i++)
    {
        S->parent[i] = -1;
    }

//@s 返回
    return S;
}
//%end

//%module | 02 | Find | Find —— 查找所在集合 | 3 | 01 |
//%summary | 顺着父亲一路走到根；顺手做路径压缩。
//@d ============ 查找 ============
//@d
//@d "X 属于哪个集合"，等价于"顺着 parent 一路往上，走到那个根"。
//@d **根的下标就是集合的编号**。
//@d
//@d 走一遍（假设 3 和 4 已经并到 1 上）：
//@d
//@d     下标:   0   1   2   3   4
//@d     parent: -4  0   0   1  -1
//@d
//@d   查 3：3 → 1 → 0，0 是根（parent[0] = -4 < 0）
//@d   查 4：4 自己就是根（parent[4] = -1）
//@d
//@d 所以 3 在集合 0 里，4 在集合 4 里，两者不同组。
//@d
//@d ============ 路径压缩：一行代码的优化 ============
//@d
//@d 如果每次都老老实实走到根，遇到很长的链会慢。所以加一个"顺手"的动作：
//@d
//@d     return S->parent[X] = Find(S, S->parent[X]);
//@d              ↑ 这一句赋值就是路径压缩
//@d
//@d 它做的是：**递归返回的路上，把沿途每个结点的父亲都直接改成根**。
//@d
//@d 效果是：
//@d
//@d   压缩前   3 → 1 → 0          查 3 要走 3 步
//@d   压缩后   3 → 0              下次查 3 只要 1 步
//@d
//@d 而且不只是 3，**沿途所有结点**都被挂到根上了。所以第一次查可能慢，
//@d 之后就会很快。
//@d
//@d ============ 平摊下来接近 O(1) ============
//@d
//@d 严格的分析要用到反阿克曼函数 α(n)（增长极慢，n 到宇宙原子数量级时
//@d α(n) 也只有 4）。所以实际可以说：
//@d
//@d     **路径压缩 + 按大小合并 → 每次操作的平摊代价接近 O(1)**
//@d
//@d 两个优化谁更重要？路径压缩贡献更大，但两个一起用才是最优。

//@s 找到 X 所在集合的根（同时做路径压缩）
//@d 返回值是根的下标，也就是"集合编号"
int Find(DisjSet *S, int X)
{
//@s 自己是根 → 找到了
    if (S->parent[X] < 0)
    {
        return X;
    }

//@s 否则继续往上找，并把结果直接写回自己的 parent —— 这就是路径压缩
//@d 递归返回的时候，X 的 parent 被改成了根的下标。
//@d 所以这条路劲上的每个结点，第二次查都会是"一步到根"。
    return S->parent[X] = Find(S, S->parent[X]);
}

//@s 只查不压缩的版本，用来对比效果
//@d 写出来是为了说明"压缩到底省了什么"，实际使用时永远用上面那个。
int FindNoCompress(DisjSet *S, int X)
{
//@s 一路往上，不改任何东西
    while (S->parent[X] >= 0)
    {
        X = S->parent[X];
    }
//@s 返回根
    return X;
}
//%end

//%module | 03 | Union | Union —— 合并两个集合 | 3 | 01,02 |
//%summary | 把小的那棵树挂到大的下面 —— 这是"按大小合并"。
//@d ============ 合并 ============
//@d
//@d "把 X 和 Y 并到一组"，做法是：
//@d
//@d   ① 分别找到两个根
//@d   ② 让其中一个根认另一个根当父亲
//@d   ③ 更新新根的大小
//@d
//@d ============ 为什么要按大小合并 ============
//@d
//@d 随便挂会出问题。假设总是"把 X 的根挂到 Y 的根下面"：
//@d
//@d   依次合并 (1,2) (2,3) (3,4) (4,5) …
//@d
//@d        1
//@d         \
//@d          2
//@d           \
//@d            3        ← 退化成一条链，查找变成 O(n)
//@d             \
//@d              4
//@d
//@d 按大小合并就不会：**永远把小树挂到大树下面**。
//@d
//@d   合并 (1,2)     1 和 2 一样大，随便挂 → 1(大小2)
//@d   合并 (2,3)     3 是小树（大小1），挂到 1 下面
//@d   合并 (3,4)     4 挂到 1 下面
//@d
//@d        1
//@d       / \
//@d      2   3
//@d          \
//@d           4
//@d
//@d 树高只有 2。原因很直观：**每次合并最多让树高增加 1，
//@d 而且只有当两个树一样大时才会增加**。所以树高是 O(log n)。
//@d
//@d ============ 代码里的大小比较 ============
//@d
//@d 因为大小存的是**负数**（-1 表示 1 个元素、-4 表示 4 个元素），
//@d 所以"谁更大"要用 `<` 而不是 `>`：
//@d
//@d     S->parent[Root2] < S->parent[Root1]   →   Root2 更大

//@s 把 Root1 和 Root2 所在的两个集合合并
//@d 参数必须是**根的下标**，不是任意元素 —— 所以调用前先 Find。
void Union(DisjSet *S, int Root1, int Root2)
{
//@s 同一个集合没必要合并
    if (Root1 == Root2)
    {
        return;
    }

//@s 如果 Root2 更大（负数更小），就把 Root1 挂到 Root2 下面
    if (S->parent[Root2] < S->parent[Root1])
    {
//@s 大小相加（两个负数相加，得到新的负数大小）
        S->parent[Root2] += S->parent[Root1];
//@s Root1 认 Root2 当父亲
        S->parent[Root1] = Root2;
    }
//@s 否则 Root1 更大，反着来
    else
    {
        S->parent[Root1] += S->parent[Root2];
        S->parent[Root2] = Root1;
    }
}
//%end

//%module | 04 | IsConnected | IsConnected —— 判断是否同组 | 2 | 01,02 |
//%summary | 两边分别找到根，根相同就是同组。
//@d ============ 判断连通 ============
//@d
//@d 这是并查集最常被问的问题，实现只有两行：
//@d
//@d     return Find(S, X) == Find(S, Y);
//@d
//@d 因为**根就是集合编号** —— 两个元素同组，等价于它们的根是同一个结点。
//@d
//@d 注意一定要比较**根**，不能比较"父亲"。两个元素的父亲可能是同一个，
//@d 也可能不同但根相同（比如一个挂了中间层）。只有根相等才是真的同组。

//@s 判断 X 和 Y 是否在同一个集合里
int IsConnected(DisjSet *S, int X, int Y)
{
//@s 分别找根，相同即同组
//@d 注意这里两次 Find 都会顺带做路径压缩，所以判断本身也让结构变好了。
    return Find(S, X) == Find(S, Y);
}
//%end

//%module | 05 | CountSets | CountSets —— 数一数有几个集合 | 1 | 01 |
//%summary | 数数组里还有几个负数 —— 那正好就是根的个数。
//@d ============ 数集合 ============
//@d
//@d 因为只有根存的是负数，所以"数有几个集合"就是"数数组里有几个负数"。
//@d 一行循环就够。
//@d
//@d 这个操作在图论里很有用：**无向图的连通分量个数**就等于
//@d "把每条边两端的点并起来之后，还剩几个集合"。
//@d
//@d 举个具体例子：n 个点、m 条边，
//@d
//@d     for (每条边 (u, v))  Union(Find(u), Find(v));
//@d     连通分量数 = CountSets();
//@d
//@d 这就是 Kruskal 最小生成树算法里"判断加这条边会不会成环"所用的全部机制。

//@s 返回当前还有几个集合
int CountSets(DisjSet *S)
{
//@s 循环用
    int i;
//@s 计数
    int count = 0;

//@s 数是负数的位置
    for (i = 0; i < S->n; i++)
    {
        if (S->parent[i] < 0)
        {
            count++;
        }
    }

//@s 返回
    return count;
}
//%end

//%module | 06 | CheckCycle | CheckCycle —— 判断无向图有没有环 | 3 | 01,02,03 |
//%summary | 逐条加边：两端已经连通，这条边就构成环。
//@d ============ 并查集最经典的应用 ============
//@d
//@d 给一个无向图，怎么判断它有没有环？
//@d
//@d 想法很直接：**一条一条地把边加进去，每次看两端是不是已经连通**。
//@d
//@d   · 两端还不连通 → 这条边只是把两个集合合并，没成环
//@d   · 两端**已经连通** → 说明之前已经有一条路径把它们连起来了，
//@d                      现在再加一条，就绕成了一个圈
//@d
//@d 走一遍这个图：
//@d
//@d       0 ── 1          边：(0,1) (1,2) (2,0)
//@d        \  /
//@d          2
//@d
//@d   加 (0,1)：0 和 1 不同组 → 合并   { 0,1 } { 2 }
//@d   加 (1,2)：1 和 2 不同组 → 合并   { 0,1,2 }
//@d   加 (2,0)：2 和 0 **同组** → 成环！
//@d
//@d ============ 为什么这样对 ============
//@d
//@d 关键点：**处理到某条边时，前面所有边都已经并进并查集了**。
//@d
//@d 所以"两端已经连通"意味着"存在一条只用前面的边构成的路径"，
//@d 把当前这条边加上去，就形成了一个环。
//@d
//@d 反过来，如果加完所有边都没成环，那这个图就是森林（若干棵树）。
//@d
//@d 这也是 Kruskal 算法的核心：**不断加"不成环"的最短边**，加够 n-1 条
//@d 就得到了最小生成树。判断"会不会成环"用的就是这个函数。

//@s 判断无向图是否有环
//@d edges 是边表，每条边两个端点；edgeCount 是边数
//@d 返回 1 表示有环，0 表示是森林
int CheckCycle(DisjSet *S, const int edges[][2], int edgeCount)
{
//@s 逐条加边
    int i;
//@s 两端的根
    int r1, r2;

    for (i = 0; i < edgeCount; i++)
    {
//@s 找两端的根
        r1 = Find(S, edges[i][0]);
        r2 = Find(S, edges[i][1]);

//@s 已经连通 → 这条边构成环
        if (r1 == r2)
        {
            return 1;
        }

//@s 否则合并，继续下一条
        Union(S, r1, r2);
    }

//@s 全部加完都没成环
    return 0;
}
//%end

//%module | 07 | FreeSet | FreeSet —— 释放 | 1 | 01 |
//%summary | 先放数组，再放结构体。
//@d 和别的结构一样：先放里面那个数组，再放外面这层壳。
//@d 反过来的话，壳没了就再也拿不到数组指针了。

//@s 释放
void FreeSet(DisjSet *S)
{
//@s 空指针不管
    if (S == NULL)
    {
        return;
    }
//@s 先放数组
    free(S->parent);
//@s 再放结构
    free(S);
}
//%end

//%module | 08 | main | main —— 把并查集跑一遍 | 2 | 01,02,03,04,05,06,07 |
//%summary | 合并、判断、数集合，最后用它判断一个图有没有环。
//@d ============ 一个容易忽略的细节 ============
//@d
//@d Union 的参数必须是**根**，不是随便什么元素。
//@d
//@d 所以标准写法永远是：
//@d
//@d     Union(S, Find(S, X), Find(S, Y));
//@d
//@d 而不是
//@d
//@d     Union(S, X, Y);        ← 错！X 可能不是根
//@d
//@d 直接把非根结点的下标传进去，会把父亲关系搞乱，整个结构就毁了。
//@d 这个错误很隐蔽，因为程序不会崩，只是后续的 Find 给出错误结果。

//@s 打印整个数组，方便看结构变化
void PrintSet(const char *tag, DisjSet *S)
{
    int i;

    printf("%s\n  ", tag);
    for (i = 0; i < S->n; i++)
    {
        printf("%3d", S->parent[i]);
    }
    printf("   ← parent 数组\n  ");
    for (i = 0; i < S->n; i++)
    {
        printf("%3d", i);
    }
    printf("   ← 元素下标\n  ");
    for (i = 0; i < S->n; i++)
    {
        printf("%3s", S->parent[i] < 0 ? "根" : "");
    }
    printf("   负数就是根，绝对值是集合大小\n");
}

//@s 主函数
int main(void)
{
//@s 6 个元素的并查集
    DisjSet *S = InitSet(6);
//@s 无向图的边
    static const int edges[][2] = { { 0, 1 }, { 1, 2 }, { 2, 0 } };
//@s 环判断用的另一个并查集
    DisjSet *G;

//@s 初始状态
    PrintSet("初始（各自一组）:", S);
    printf("集合个数 = %d\n\n", CountSets(S));

//@s 合并几对
    Union(S, Find(S, 0), Find(S, 1));
    PrintSet("合并 0 和 1 之后:", S);

//@s 判断连通
    printf("0 和 1 同组吗？%s\n", IsConnected(S, 0, 1) ? "是" : "不是");
    printf("0 和 2 同组吗？%s\n\n", IsConnected(S, 0, 2) ? "是" : "不是");

//@s 再合并
    Union(S, Find(S, 2), Find(S, 3));
    Union(S, Find(S, 4), Find(S, 5));
    PrintSet("再合并 (2,3) 和 (4,5) 之后:", S);
    printf("集合个数 = %d\n", CountSets(S));

//@s 把两个大集合并起来
    Union(S, Find(S, 1), Find(S, 4));
    PrintSet("把 {0,1} 和 {4,5} 并起来之后:", S);
    printf("集合个数 = %d\n", CountSets(S));
    printf("（每次合并少一个集合，所以个数就是从 n 递减下来的）\n\n");

//@s 路径压缩的效果
    printf("查一次 3（会顺带压缩路径）: 根 = %d\n", Find(S, 3));
    PrintSet("查过 3 之后的数组:", S);
    printf("（沿途结点的父亲都直接改成根了）\n\n");

//@s 用并查集判断无向图有没有环
    G = InitSet(3);
    printf("图：0-1，1-2，2-0（三角形，有环）\n");
    printf("判断结果: %s\n", CheckCycle(G, edges, 3) ? "有环" : "没有环");
    FreeSet(G);

//@s 换一个没有环的图
    {
        static const int tree[][2] = { { 0, 1 }, { 1, 2 } };
        DisjSet *T = InitSet(3);
        printf("\n图：0-1，1-2（一条链，没有环）\n");
        printf("判断结果: %s\n", CheckCycle(T, tree, 2) ? "有环" : "没有环");
        printf("（加完所有边都没遇到「两端已连通」，所以是森林）\n");
        FreeSet(T);
    }

//@s 释放
    FreeSet(S);
//@s 正常结束
    return 0;
}
//%end
