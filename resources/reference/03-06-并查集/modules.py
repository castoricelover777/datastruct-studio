#%module | 01 | typedef | 头文件与 typedef | 2 |
#%summary | 一个数组就是一片森林：负数表示根，绝对值是集合大小。
#@d ============ 用负数表示根，这个设计很妙 ============
#@d
#@d 数组里每个位置存一个整数，含义看正负：
#@d
#@d     parent[i] = 3   →  i 的父亲是 3
#@d     parent[i] = -1  →  i 是根，这个集合有 1 个元素（只有它自己）
#@d     parent[i] = -4  →  i 是根，这个集合有 4 个元素
#@d
#@d 为什么用负数而不是另开一个数组存"集合大小"？
#@d
#@d   ① 省一个数组；
#@d   ② **判断根只需要看一个数**：`parent[i] < 0` 就是根，不用再查别的表；
#@d   ③ 合并时也方便：两个根的大小就是两个负数，加起来直接得到新大小。
#@d
#@d 这是个典型的"用一个字段表达两层含义"的技巧。代价是可读性稍差，
#@d 所以注释一定要写清楚。
#@d
#@d ============ 初始状态 ============
#@d
#@d 一开始谁和谁都没关系，所以**每个元素各自成一个集合**：
#@d
#@d     下标:   0   1   2   3   4
#@d     parent: -1  -1  -1  -1  -1
#@d             ↑全部是根，每个集合只有自己
#@d
#@d 注意这里用的是 0 起始的下标，和堆那种"从 1 开始"不一样 ——
#@d 并查集的元素编号本来就是任意的，直接用 0..n-1 最省事。

#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 的 struct 到 Python 里就是一个 class：parent 和 n 这两个字段照搬，
#@d   取值从 S->parent[i]、S->n 变成 S.parent[i]、S.n，箭头换成一个小圆点。
#@d   这里没用"两个列表"存并查集：两个列表会走散 —— 函数得收两个参数，
#@d   换一个并查集还要换一套变量名，传错一个就悄悄算错，包进 class 就绑死了。
#@d   C 要 malloc 两次还得自己算字节数，Python 一个 [0] * n 就是 n 个格子。
#@d   C 的 typedef int Status; 是给返回值起别名，Python 不看类型，这句省了。

#@s 最大元素个数
MAXSIZE = 1000

#@s 并查集：一个数组 + 元素个数
class DisjSet:
    #@d C 的 struct 只是把字段摆在那儿，真正填值是在 InitSet 里；
    #@d Python 这里也先只摆好字段，等 InitSet 把 parent 和 n 填上，时机一样。
    def __init__(self):
        #@s parent[i] >= 0 是父亲下标；< 0 表示它是根，绝对值是集合大小
        self.parent = None
        #@s 元素个数
        self.n = 0

#@s 状态码
OK = 1
ERROR = 0

#@s 建一个含 n 个元素的并查集，每个元素各自一组
#@d 这个函数和结构定义放一起，因为它就是"结构的一部分"。
def InitSet(n):
    #@s 分配结构
    S = DisjSet()
    #@s 分配数组
    #@d C 这里还有一行 int i; 和一次 malloc，Python 直接用 [0] * n 造出 n 个格子，
    #@d 循环变量 i 由下面的 for 自己造，不用提前声明。
    S.parent = [0] * n
    S.n = n

    #@s 每个元素都置 -1：自己是根，集合大小为 1
    #@d 其实一行 S.parent = [-1] * n 就写完了，这里留着循环是为了和 C 一步一步对上。
    for i in range(n):
        S.parent[i] = -1

    #@s 返回
    return S
#%end

#%module | 02 | Find | Find —— 查找所在集合 | 3 | 01 |
#%summary | 顺着父亲一路走到根；顺手做路径压缩。
#@d ============ 查找 ============
#@d
#@d "X 属于哪个集合"，等价于"顺着 parent 一路往上，走到那个根"。
#@d **根的下标就是集合的编号**。
#@d
#@d 走一遍（假设 3 和 4 已经并到 1 上）：
#@d
#@d     下标:   0   1   2   3   4
#@d     parent: -4  0   0   1  -1
#@d
#@d   查 3：3 → 1 → 0，0 是根（parent[0] = -4 < 0）
#@d   查 4：4 自己就是根（parent[4] = -1）
#@d
#@d 所以 3 在集合 0 里，4 在集合 4 里，两者不同组。
#@d
#@d ============ 路径压缩：一行代码的优化 ============
#@d
#@d 如果每次都老老实实走到根，遇到很长的链会慢。所以加一个"顺手"的动作：
#@d
#@d     return S->parent[X] = Find(S, S->parent[X]);
#@d              ↑ 这一句赋值就是路径压缩
#@d
#@d 它做的是：**递归返回的路上，把沿途每个结点的父亲都直接改成根**。
#@d
#@d 效果是：
#@d
#@d   压缩前   3 → 1 → 0          查 3 要走 3 步
#@d   压缩后   3 → 0              下次查 3 只要 1 步
#@d
#@d 而且不只是 3，**沿途所有结点**都被挂到根上了。所以第一次查可能慢，
#@d 之后就会很快。
#@d
#@d ============ 平摊下来接近 O(1) ============
#@d
#@d 严格的分析要用到反阿克曼函数 α(n)（增长极慢，n 到宇宙原子数量级时
#@d α(n) 也只有 4）。所以实际可以说：
#@d
#@d     **路径压缩 + 按大小合并 → 每次操作的平摊代价接近 O(1)**
#@d
#@d 两个优化谁更重要？路径压缩贡献更大，但两个一起用才是最优。

#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 那句 return S->parent[X] = Find(...) 是拿赋值当表达式用，Python 不让这么写，
#@d   只能拆成两行：先把结果存回 S.parent[X]，再把 S.parent[X] 返回，效果一模一样。
#@d   C 的递归要几万层才爆栈，Python 默认递归 1000 层就报 RecursionError ——
#@d   不过有路径压缩撑着，树很浅，正常用根本碰不到这个上限。

#@s 找到 X 所在集合的根（同时做路径压缩）
#@d 返回值是根的下标，也就是"集合编号"
def Find(S, X):
    #@s 自己是根 → 找到了
    if S.parent[X] < 0:
        return X

    #@s 否则继续往上找，并把结果直接写回自己的 parent —— 这就是路径压缩
    #@d 递归返回的时候，X 的 parent 被改成了根的下标。
    #@d 所以这条路劲上的每个结点，第二次查都会是"一步到根"。
    S.parent[X] = Find(S, S.parent[X])
    return S.parent[X]

#@s 只查不压缩的版本，用来对比效果
#@d 写出来是为了说明"压缩到底省了什么"，实际使用时永远用上面那个。
def FindNoCompress(S, X):
    #@s 一路往上，不改任何东西
    while S.parent[X] >= 0:
        X = S.parent[X]
    #@s 返回根
    return X
#%end

#%module | 03 | Union | Union —— 合并两个集合 | 3 | 01,02 |
#%summary | 把小的那棵树挂到大的下面 —— 这是"按大小合并"。
#@d ============ 合并 ============
#@d
#@d "把 X 和 Y 并到一组"，做法是：
#@d
#@d   ① 分别找到两个根
#@d   ② 让其中一个根认另一个根当父亲
#@d   ③ 更新新根的大小
#@d
#@d ============ 为什么要按大小合并 ============
#@d
#@d 随便挂会出问题。假设总是"把 X 的根挂到 Y 的根下面"：
#@d
#@d   依次合并 (1,2) (2,3) (3,4) (4,5) …
#@d
#@d        1
#@d         \
#@d          2
#@d           \
#@d            3        ← 退化成一条链，查找变成 O(n)
#@d             \
#@d              4
#@d
#@d 按大小合并就不会：**永远把小树挂到大树下面**。
#@d
#@d   合并 (1,2)     1 和 2 一样大，随便挂 → 1(大小2)
#@d   合并 (2,3)     3 是小树（大小1），挂到 1 下面
#@d   合并 (3,4)     4 挂到 1 下面
#@d
#@d        1
#@d       / \
#@d      2   3
#@d          \
#@d           4
#@d
#@d 树高只有 2。原因很直观：**每次合并最多让树高增加 1，
#@d 而且只有当两个树一样大时才会增加**。所以树高是 O(log n)。
#@d
#@d ============ 代码里的大小比较 ============
#@d
#@d 因为大小存的是**负数**（-1 表示 1 个元素、-4 表示 4 个元素），
#@d 所以"谁更大"要用 `<` 而不是 `>`：
#@d
#@d     S->parent[Root2] < S->parent[Root1]   →   Root2 更大

#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 的 void 函数想提前收工就写 return;，Python 写一个光秃秃的 return，一个意思。
#@d   C 的 S->parent[Root2] += S->parent[Root1]; 在 Python 里能原样照写，
#@d   列表里那个格子就是原地加，不会另外复制一份出来。
#@d   老坑还是那个老坑：传进来的必须是根。Python 也不会替你检查，
#@d   传个非根的下标进去照样悄悄把结构搞坏 —— 所以调用前一定先 Find。

#@s 把 Root1 和 Root2 所在的两个集合合并
#@d 参数必须是**根的下标**，不是任意元素 —— 所以调用前先 Find。
def Union(S, Root1, Root2):
    #@s 同一个集合没必要合并
    if Root1 == Root2:
        return

    #@s 如果 Root2 更大（负数更小），就把 Root1 挂到 Root2 下面
    if S.parent[Root2] < S.parent[Root1]:
        #@s 大小相加（两个负数相加，得到新的负数大小）
        S.parent[Root2] += S.parent[Root1]
        #@s Root1 认 Root2 当父亲
        S.parent[Root1] = Root2
    #@s 否则 Root1 更大，反着来
    else:
        S.parent[Root1] += S.parent[Root2]
        S.parent[Root2] = Root1
#%end

#%module | 04 | IsConnected | IsConnected —— 判断是否同组 | 2 | 01,02 |
#%summary | 两边分别找到根，根相同就是同组。
#@d ============ 判断连通 ============
#@d
#@d 这是并查集最常被问的问题，实现只有两行：
#@d
#@d     return Find(S, X) == Find(S, Y);
#@d
#@d 因为**根就是集合编号** —— 两个元素同组，等价于它们的根是同一个结点。
#@d
#@d 注意一定要比较**根**，不能比较"父亲"。两个元素的父亲可能是同一个，
#@d 也可能不同但根相同（比如一个挂了中间层）。只有根相等才是真的同组。

#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 返回的是 int，0 和 1 当假和真用；Python 直接返回 True/False，
#@d   用的人照样写 if IsConnected(...)，一点区别都感觉不到。
#@d   函数体那一行和 C 一字不差，只是不用再套那对大括号了。

#@s 判断 X 和 Y 是否在同一个集合里
def IsConnected(S, X, Y):
    #@s 分别找根，相同即同组
    #@d 注意这里两次 Find 都会顺带做路径压缩，所以判断本身也让结构变好了。
    return Find(S, X) == Find(S, Y)
#%end

#%module | 05 | CountSets | CountSets —— 数一数有几个集合 | 1 | 01 |
#%summary | 数数组里还有几个负数 —— 那正好就是根的个数。
#@d ============ 数集合 ============
#@d
#@d 因为只有根存的是负数，所以"数有几个集合"就是"数数组里有几个负数"。
#@d 一行循环就够。
#@d
#@d 这个操作在图论里很有用：**无向图的连通分量个数**就等于
#@d "把每条边两端的点并起来之后，还剩几个集合"。
#@d
#@d 举个具体例子：n 个点、m 条边，
#@d
#@d     for (每条边 (u, v))  Union(Find(u), Find(v));
#@d     连通分量数 = CountSets();
#@d
#@d 这就是 Kruskal 最小生成树算法里"判断加这条边会不会成环"所用的全部机制。

#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 的 for (i = 0; i < S->n; i++) 在 Python 里写成 for i in range(S.n)，
#@d   range(S.n) 吐出来正好是 0 到 n-1，和 C 的 i < n 对得上，不会多跑一轮。
#@d   计数那行 count++ 要写成 count += 1 —— Python 里没有 ++ 这个运算符。

#@s 返回当前还有几个集合
def CountSets(S):
    #@s 循环用
    #@d C 这里是 int i; 那一行，Python 不用提前声明，下面的 for 会自己把 i 造出来。
    #@s 计数
    count = 0

    #@s 数是负数的位置
    for i in range(S.n):
        if S.parent[i] < 0:
            count += 1

    #@s 返回
    return count
#%end

#%module | 06 | CheckCycle | CheckCycle —— 判断无向图有没有环 | 3 | 01,02,03 |
#%summary | 逐条加边：两端已经连通，这条边就构成环。
#@d ============ 并查集最经典的应用 ============
#@d
#@d 给一个无向图，怎么判断它有没有环？
#@d
#@d 想法很直接：**一条一条地把边加进去，每次看两端是不是已经连通**。
#@d
#@d   · 两端还不连通 → 这条边只是把两个集合合并，没成环
#@d   · 两端**已经连通** → 说明之前已经有一条路径把它们连起来了，
#@d                      现在再加一条，就绕成了一个圈
#@d
#@d 走一遍这个图：
#@d
#@d       0 ── 1          边：(0,1) (1,2) (2,0)
#@d        \  /
#@d          2
#@d
#@d   加 (0,1)：0 和 1 不同组 → 合并   { 0,1 } { 2 }
#@d   加 (1,2)：1 和 2 不同组 → 合并   { 0,1,2 }
#@d   加 (2,0)：2 和 0 **同组** → 成环！
#@d
#@d ============ 为什么这样对 ============
#@d
#@d 关键点：**处理到某条边时，前面所有边都已经并进并查集了**。
#@d
#@d 所以"两端已经连通"意味着"存在一条只用前面的边构成的路径"，
#@d 把当前这条边加上去，就形成了一个环。
#@d
#@d 反过来，如果加完所有边都没成环，那这个图就是森林（若干棵树）。
#@d
#@d 这也是 Kruskal 算法的核心：**不断加"不成环"的最短边**，加够 n-1 条
#@d 就得到了最小生成树。判断"会不会成环"用的就是这个函数。

#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 的边表是 int edges[][2]，Python 写成 [[0, 1], [1, 2], [2, 0]] 这样的列表，
#@d   取端点还是 edges[i][0]、edges[i][1]，两层下标和 C 一模一样。
#@d   返回值照 C 留着 1 和 0，没改成 True/False —— 反正后面 if 判断真假都一样。

#@s 判断无向图是否有环
#@d edges 是边表，每条边两个端点；edgeCount 是边数
#@d 返回 1 表示有环，0 表示是森林
def CheckCycle(S, edges, edgeCount):
    #@s 逐条加边
    #@d C 这里是 int i; 那一行，Python 的 for 自己造 i，不用先声明。
    #@s 两端的根
    #@d C 这里是 int r1, r2; 那一行，Python 到下面赋值的时候才有这两个名字。
    for i in range(edgeCount):
        #@s 找两端的根
        r1 = Find(S, edges[i][0])
        r2 = Find(S, edges[i][1])

        #@s 已经连通 → 这条边构成环
        if r1 == r2:
            return 1

        #@s 否则合并，继续下一条
        Union(S, r1, r2)

    #@s 全部加完都没成环
    return 0
#%end

#%module | 07 | FreeSet | FreeSet —— 释放 | 1 | 01 |
#%summary | 先放数组，再放结构体。
#@d 和别的结构一样：先放里面那个数组，再放外面这层壳。
#@d 反过来的话，壳没了就再也拿不到数组指针了。

#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   Python 里没有 free，你也没法叫它"现在就把这块内存还回去"：
#@d   没人再引用这个对象的时候，垃圾回收自己会收走。
#@d   所以这里只是把 parent 置成 None、n 归零，等于告诉 Python"我不再用它了"，
#@d   意思和 C 里先放数组、再放结构体那两步差不多。
#@d   空指针判断照样留着 —— Python 传进来 None 一样会出错，先挡一下更保险。

#@s 释放
def FreeSet(S):
    #@s 空指针不管
    if S is None:
        return
    #@s 先放数组
    S.parent = None
    #@s 再放结构
    S.n = 0
#%end

#%module | 08 | main | main —— 把并查集跑一遍 | 2 | 01,02,03,04,05,06,07 |
#%summary | 合并、判断、数集合，最后用它判断一个图有没有环。
#@d ============ 一个容易忽略的细节 ============
#@d
#@d Union 的参数必须是**根**，不是随便什么元素。
#@d
#@d 所以标准写法永远是：
#@d
#@d     Union(S, Find(S, X), Find(S, Y));
#@d
#@d 而不是
#@d
#@d     Union(S, X, Y);        ← 错！X 可能不是根
#@d
#@d 直接把非根结点的下标传进去，会把父亲关系搞乱，整个结构就毁了。
#@d 这个错误很隐蔽，因为程序不会崩，只是后续的 Find 给出错误结果。

#@d ============ 这段 Python 和 C 有什么不一样 ============
#@d
#@d   C 的 int main(void) 换成 if __name__ == '__main__':，这是 Python 的固定写法，
#@d   意思和 C 一样：从这里开始往下跑。
#@d   C 打印靠一堆 printf 加 %3d，Python 用 f'{值:3d}' 配 end='' 拼出来，效果一样。
#@d   C 那对大括号是给 tree 圈作用域的，Python 没有块作用域，直接一路写下去。

#@s 打印整个数组，方便看结构变化
def PrintSet(tag, S):
    #@d C 的 %3d 是"右对齐占 3 格"，Python 的 f'{v:3d}' 是一个意思。
    #@d 但 %3s 要当心：C 按**字节**算宽度，"根"正好 3 个字节，所以一格都不补；
    #@d Python 的 rjust 按字符算，会把"根"当成 1 个字补上 2 个空格，输出就错位了。
    #@d 所以这里不绕弯子：是根就打印"根"，不是根就打印 3 个空格，跟 C 出来的一模一样。
    print(f'{tag}\n  ', end='')
    for i in range(S.n):
        print(f'{S.parent[i]:3d}', end='')
    print('   ← parent 数组\n  ', end='')
    for i in range(S.n):
        print(f'{i:3d}', end='')
    print('   ← 元素下标\n  ', end='')
    for i in range(S.n):
        print('根' if S.parent[i] < 0 else '   ', end='')
    print('   负数就是根，绝对值是集合大小')

