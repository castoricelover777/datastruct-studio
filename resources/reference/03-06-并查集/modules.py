    #@s 6 个元素的并查集
    S = InitSet(6)
    #@s 无向图的边
    edges = [[0, 1], [1, 2], [2, 0]]
    #@s 环判断用的另一个并查集
    G = None

    #@s 初始状态
    PrintSet('初始（各自一组）:', S)
    print(f'集合个数 = {CountSets(S)}\n')

    #@s 合并几对
    Union(S, Find(S, 0), Find(S, 1))
    PrintSet('合并 0 和 1 之后:', S)

    #@s 判断连通
    print('0 和 1 同组吗？' + ('是' if IsConnected(S, 0, 1) else '不是'))
    print('0 和 2 同组吗？' + ('是' if IsConnected(S, 0, 2) else '不是') + '\n')

    #@s 再合并
    Union(S, Find(S, 2), Find(S, 3))
    Union(S, Find(S, 4), Find(S, 5))
    PrintSet('再合并 (2,3) 和 (4,5) 之后:', S)
    print(f'集合个数 = {CountSets(S)}')

    #@s 把两个大集合并起来
    Union(S, Find(S, 1), Find(S, 4))
    PrintSet('把 {0,1} 和 {4,5} 并起来之后:', S)
    print(f'集合个数 = {CountSets(S)}')
    print('（每次合并少一个集合，所以个数就是从 n 递减下来的）\n')

    #@s 路径压缩的效果
    print(f'查一次 3（会顺带压缩路径）: 根 = {Find(S, 3)}')
    PrintSet('查过 3 之后的数组:', S)
    print('（沿途结点的父亲都直接改成根了）\n')

    #@s 用并查集判断无向图有没有环
    G = InitSet(3)
    print('图：0-1，1-2，2-0（三角形，有环）')
    print('判断结果: ' + ('有环' if CheckCycle(G, edges, 3) else '没有环'))
    FreeSet(G)

    #@s 换一个没有环的图
    #@d C 里这对大括号是给 tree 圈作用域的，Python 没有块作用域，直接往下写就行。
    tree = [[0, 1], [1, 2]]
    T = InitSet(3)
    print('\n图：0-1，1-2（一条链，没有环）')
    print('判断结果: ' + ('有环' if CheckCycle(T, tree, 2) else '没有环'))
    print('（加完所有边都没遇到「两端已连通」，所以是森林）')
    FreeSet(T)

    #@s 释放
    FreeSet(S)
    #@s 正常结束
    #@d C 的 main 在这里 return 0;，Python 脚本跑到底就结束了，不用写这句。
