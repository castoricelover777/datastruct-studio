/*
 * ============================================================================
 *  数据结构研习社 —— 04 图 / 04-05 拓扑排序
 * ============================================================================
 *
 *  问题：一堆任务之间有先后依赖，怎么排出一个合法的执行顺序？
 *
 *  比如"先修课程"：
 *
 *      高等数学 ──→ 数据结构 ──→ 算法分析
 *           │           ↑
 *           └──→ 离散数学 ┘
 *
 *  用图来表示就是：**顶点是任务，有向边 A→B 表示"A 必须在 B 之前"**。
 *  这样的有向图叫 **AOV 网**（Activity On Vertex）。
 *
 *  于是问题变成：给所有顶点排个序，让每条边都从前面指向后面。
 *
 *  ============ 关键观察 ============
 *
 *  **入度为 0 的顶点没有任何前驱，随时可以做。**
 *
 *  所以算法很自然：
 *
 *      ① 找出所有入度为 0 的顶点，放进队列
 *      ② 取出一个，输出它，然后**把它的出边都删掉**
 *         （等价于"它的邻居少了一个前驱"，入度减 1）
 *      ③ 谁的入度变成 0 了，谁就入队
 *      ④ 重复到队空
 *
 *  ============ 有环怎么办 ============
 *
 *  如果图里有环（A 依赖 B、B 又依赖 A），那环上的顶点入度永远降不到 0，
 *  谁也进不了队。所以：
 *
 *      **输出的顶点数 < n  ⟺  图里有环**
 *
 *  这就顺手得到了"判断有向图有没有环"的方法。
 *
 *  标记约定同前（本文件本身可编译）。
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>

//%module | 01 | typedef | 头文件与 typedef | 2 |
//%summary | 有向图 + 入度数组。入度就是"有多少条边指向我"。
//@d ============ 有向图和无向图的存储差别 ============
//@d
//@d 只有一个：**有向图只填一个格子**。
//@d
//@d   g[i][j] = 1  表示有一条从 i 指向 j 的边
//@d
//@d 无向图要填 g[i][j] 和 g[j][i] 两个，有向图只填一个 —— 因为方向是有意义的。
//@d
//@d 所以这个矩阵**不对称**。如果打印出来发现对称了，那说明建图时写成了无向图。
//@d
//@d ============ 入度是什么 ============
//@d
//@d 顶点 v 的**入度** = 有多少条边指向 v = **有多少个任务必须在 v 之前完成**。
//@d
//@d   · 入度 = 0  →  没有前置任务，现在就能做
//@d   · 入度 > 0  →  还有前置任务没做完
//@d
//@d 所以拓扑排序从头到尾都在盯着这个数。
//@d
//@d ============ 出度 ============
//@d
//@d 顺便说一下**出度**：有多少条边从 v 指出去。
//@d
//@d   入度 = "我要等谁"
//@d   出度 = "谁要等我"
//@d
//@d 拓扑排序主要用入度，出度在做关键路径（AOE 网）时才用得上。

//@s 最多顶点数
#define MAXV 100

//@s 有向图（邻接矩阵）
typedef struct
{
//@s 顶点数
    int nv;
//@s 边数
    int ne;
//@s g[i][j] = 1 表示有一条 i → j 的边
    int g[MAXV][MAXV];
} DGraph;

//@s 状态码
#define OK 1
#define ERROR 0
typedef int Status;

//@s 用边表建有向图
//@d edges 每条边 { 起点, 终点 }
void CreateDGraph(DGraph *G, int nv, const int edges[][2], int edgeCount)
{
//@s 循环用
    int i, j;

//@s 记规模
    G->nv = nv;
    G->ne = edgeCount;

//@s 清零
    for (i = 0; i < nv; i++)
    {
        for (j = 0; j < nv; j++)
        {
            G->g[i][j] = 0;
        }
    }

//@s 逐条边（只填一个格子！）
//@d 这就是有向图和无向图在存储上的唯一区别。
    for (i = 0; i < edgeCount; i++)
    {
        G->g[edges[i][0]][edges[i][1]] = 1;
    }
}

//@s 计算每个顶点的入度
//@d 入度 = 第 j 列上有多少个 1。
void CalcIndegree(DGraph *G, int indegree[])
{
//@s 循环用
    int i, j;

//@s 先清零
    for (i = 0; i < G->nv; i++)
    {
        indegree[i] = 0;
    }

//@s 逐列累加
    for (i = 0; i < G->nv; i++)
    {
        for (j = 0; j < G->nv; j++)
        {
//@s 有一条 i→j 的边，j 的入度就加一
            if (G->g[i][j] != 0)
            {
                indegree[j]++;
            }
        }
    }
}

//@s 计算出度（拓扑排序用不上，但对比着看更清楚）
int OutDegree(DGraph *G, int v)
{
//@s 第 v 行上有多少个 1
    int i;
    int count = 0;

    for (i = 0; i < G->nv; i++)
    {
        if (G->g[v][i] != 0)
        {
            count++;
        }
    }
    return count;
}
//%end

//%module | 02 | TopSort | TopSort —— 拓扑排序（Kahn 算法） | 3 | 01 |
//%summary | 每次挑一个入度为 0 的输出，然后删掉它的出边。
//@d ============ 走一遍 ============
//@d
//@d 用这张课表：
//@d
//@d      0 ──→ 2 ──→ 4
//@d      ↓           ↑
//@d      1 ──→ 3 ────┘
//@d
//@d   边：(0,2) (0,1) (1,3) (2,4) (3,4)
//@d
//@d 各点入度：0 号 0、1 号 1、2 号 1、3 号 1、4 号 2
//@d
//@d   初始队列：只有 0（唯一的入度 0）
//@d
//@d   **第 1 步**：输出 0，删掉 0 的出边
//@d        到 2 的边没了 → 2 的入度 1→0，入队
//@d        到 1 的边没了 → 1 的入度 1→0，入队
//@d        队列 [2, 1]，已输出 0
//@d
//@d   **第 2 步**：输出 2，删掉 2 的出边
//@d        到 4 的边没了 → 4 的入度 2→1（还不是 0）
//@d        队列 [1]，已输出 0 2
//@d
//@d   **第 3 步**：输出 1，删掉 1 的出边
//@d        到 3 的边没了 → 3 入度 1→0，入队
//@d        队列 [3]，已输出 0 2 1
//@d
//@d   **第 4 步**：输出 3，删掉 3 的出边
//@d        到 4 的边没了 → 4 入度 1→0，入队
//@d        队列 [4]，已输出 0 2 1 3
//@d
//@d   **第 5 步**：输出 4，它没有出边
//@d        队列空，结束
//@d
//@d 结果：**0 2 1 3 4**
//@d
//@d ============ 为什么"删掉出边"就是入度减一 ============
//@d
//@d 因为入度的定义就是"有多少条边指向我"。
//@d 把某条指向我的边删掉，我的入度当然就少一。
//@d
//@d 代码里不用真的去改矩阵，只要把邻居的 indegree 减一就行 ——
//@d 这正是"用一个计数器代替真的删边"的常见技巧。
//@d
//@d ============ 注意拓扑排序不唯一 ============
//@d
//@d 如果某一时刻队列里有多个入度 0 的顶点，先输出谁都可以，
//@d 结果都是合法的。
//@d
//@d 所以做题时题目通常会规定"编号小的优先输出"，来固定答案。
//@d 我们这个实现用的是队列（先进先出），结果和入队顺序有关。

//@s 拓扑排序，结果放进 order 数组；返回排好的顶点数
//@d 返回值 < nv 表示图里有环，拓扑序不存在
int TopSort(DGraph *G, int order[])
{
//@s 入度数组（会一边用一边减）
    int indegree[MAXV];
//@s 队列：就地开数组
    int queue[MAXV];
//@s 队头、队尾
    int front = 0;
    int rear = 0;
//@s 已经输出了几个
    int count = 0;
//@s 循环用
    int i;
//@s 当前顶点
    int v;

//@s ① 先算好入度
    CalcIndegree(G, indegree);

//@s ② 入度为 0 的全部入队
//@d 它们是"没有前置任务"的那些，随时可以做。
    for (i = 0; i < G->nv; i++)
    {
        if (indegree[i] == 0)
        {
            queue[rear++] = i;
        }
    }

//@s ③ 队列不空就一直转
    while (front < rear)
    {
//@s 取出一个顶点
        v = queue[front++];

//@s 输出它
        order[count++] = v;

//@s ④ 删掉它的所有出边 —— 也就是让邻居的入度减一
        for (i = 0; i < G->nv; i++)
        {
            if (G->g[v][i] != 0)
            {
//@s 入度减一
//@d 先减再判断，写成 --indegree[i] == 0 就是"减完正好是 0"。
                if (--indegree[i] == 0)
                {
//@s 变成 0 就说明它的前置任务都做完了，可以入队
                    queue[rear++] = i;
                }
            }
        }
    }

//@s ④ 检查是不是所有顶点都输出了
//@d 输出数少于顶点数，说明剩下的顶点入度都降不到 0 —— 它们在环上。
    return count;
}

//@s 判断图里有没有环
//@d 判据就是"拓扑排序能不能排完所有顶点"。
int HasCycle(DGraph *G)
{
//@s 拓扑序
    int order[MAXV];
//@s 排出来的个数
    int n;

    n = TopSort(G, order);

//@s 排不满就是有环
    return n != G->nv;
}
//%end

//%module | 03 | DFSVisit | DFSVisit —— 深度优先的辅助函数 | 3 | 01 |
//@d 这个函数是给下一个模块（DFS 版拓扑排序）用的。
//@d
//@d 它做的事就是普通的深度优先，唯一的特别之处在**最后一行**：
//@d 访问完所有邻居之后，把顶点填到 order 数组的**尾部往前**的位置上。

//%summary | 深度优先遍历，回溯时把顶点从后往前填进 order。
void DFSVisit(DGraph *G, int v, int visited[], int order[], int *pos)
{
//@s 循环用
    int i;

//@s 标记已访问
    visited[v] = 1;

//@s 先递归所有邻居
    for (i = 0; i < G->nv; i++)
    {
        if (G->g[v][i] != 0 && visited[i] == 0)
        {
            DFSVisit(G, i, visited, order, pos);
        }
    }

//@s 邻居都处理完了，才把自己填进去
//@d 差别就在这一句的位置 —— 放在循环**之后**就是"后序"，
//@d 而逆后序正好就是拓扑序。
    order[(*pos)--] = v;
}
//%end

//%module | 04 | TopSortDFS | TopSortDFS —— 拓扑排序（DFS 逆后序） | 3 | 01,03 |
//%summary | 深度优先，回溯时把顶点填进数组尾部 —— 填完倒过来就是拓扑序。
//@d ============ 为什么"逆后序"就是拓扑序 ============
//@d
//@d 先想清楚后序是什么：**在树/图的 DFS 里，一个顶点的"后序位置"
//@d 是它的所有邻居都处理完之后才确定的。**
//@d
//@d 所以如果有一条边 A → B，那么：
//@d
//@d   · 从 A 出发会先递归到 B
//@d   · B 会**先于 A** 拿到后序位置
//@d   · 也就是说：**A 的后序位置 > B 的后序位置**（A 更靠后）
//@d
//@d 那我把后序位置**反过来用**（谁后序靠后就放前面），得到的就是：
//@d
//@d   · A 排在 B 前面
//@d
//@d 正好符合"A 必须在 B 之前"！
//@d
//@d 所以在代码里，从数组**最后往前**填就行了。
//@d
//@d ============ 和 Kahn 算法的对比 ============
//@d
//@d   Kahn（入度法）：思路直观，顺序好控制，还能顺手检测环
//@d   DFS 逆后序：   代码更短，不用算入度，但顺序不好控制
//@d
//@d 两者都能用。考试里 Kahn 更常见，因为它"看得见过程"。
//@d
//@d 注意：DFS 版**不能直接用来检测环**，它照样能输出一个序列 ——
//@d 只是有环时那个序列没有意义。要检测环得另外做标记（三种颜色）。

//@s 用 DFS 逆后序做拓扑排序
//@d 返回排好的顶点数（这里总是 nv，不检测环）
int TopSortDFS(DGraph *G, int order[])
{
//@s 访问标记
    int visited[MAXV];
//@s 填充位置（从最后一个位置开始往前）
    int pos;
//@s 循环用
    int i;

//@s 都还没访问
    for (i = 0; i < G->nv; i++)
    {
        visited[i] = 0;
    }

//@s 从末尾往前填
    pos = G->nv - 1;

//@s 每个没访问过的顶点都起一次 DFS
//@d 外层这个循环是为了处理"非连通"的有向图。
    for (i = 0; i < G->nv; i++)
    {
        if (visited[i] == 0)
        {
            DFSVisit(G, i, visited, order, &pos);
        }
    }

//@s 全部填满
    return G->nv;
}

//@s 打印一个序列
void PrintOrder(const char *tag, int order[], int n)
{
//@s 循环用
    int i;

    printf("%s", tag);
    for (i = 0; i < n; i++)
    {
        printf("%d ", order[i]);
    }
    printf("\n");
}
//%end

//%module | 05 | main | main —— 两种做法对着看 | 3 | 01,02,03,04 |
//%summary | 同一个 AOV 网，Kahn 和 DFS 逆后序给出两个合法的顺序。
//@d ============ 序列不一样，但都对 ============
//@d
//@d 拓扑排序不唯一。只要每条边都"从前往后"，就是合法答案。
//@d
//@d 所以两个算法给出不同的序列是**正常现象**，不用去对答案。
//@d 真正该检查的是：**结果里每条边的方向对不对**。
//@d
//@d 验证办法：记下每个顶点在结果里的位置，然后遍历所有边，
//@d 检查是不是"起点的位置 < 终点的位置"。

//@s 检查一个序列是不是合法拓扑序
//@d 返回 1 表示合法
int CheckOrder(DGraph *G, int order[])
{
//@s 每个顶点在序列里的位置
    int pos[MAXV];
//@s 循环用
    int i, j;

//@s 先记下位置
    for (i = 0; i < G->nv; i++)
    {
        pos[order[i]] = i;
    }

//@s 检查每条边
    for (i = 0; i < G->nv; i++)
    {
        for (j = 0; j < G->nv; j++)
        {
//@s 有边 i→j，那 i 必须排在 j 前面
            if (G->g[i][j] != 0 && pos[i] >= pos[j])
            {
                printf("  违反：边 %d→%d，但 %d 排在 %d 后面\n", i, j, i, j);
                return 0;
            }
        }
    }
    return 1;
}

//@s 主函数
int main(void)
{
//@s 课表：{ 先修课, 后续课 }
//@d   0 → 2 → 4
//@d   ↓       ↑
//@d   1 → 3 ──┘
    static const int edges[][2] = { { 0, 2 }, { 0, 1 }, { 1, 3 }, { 2, 4 }, { 3, 4 } };
//@s 顶点数、边数
    int nv = 5;
//@s 图
    DGraph G;
//@s 两个算法的结果
    int order1[MAXV];
    int order2[MAXV];
//@s 排序结果的长度
    int n1, n2;
//@s 入度数组
    int indegree[MAXV];
//@s 循环用
    int i, j;

//@s 建图
    CreateDGraph(&G, nv, edges, 5);

//@s 打印邻接矩阵
    printf("有向图的邻接矩阵（g[i][j]=1 表示 i→j）：\n");
    printf("      ");
    for (j = 0; j < nv; j++)
    {
        printf("%3d", j);
    }
    printf("\n");

    for (i = 0; i < nv; i++)
    {
        printf("  %2d [", i);
        for (j = 0; j < nv; j++)
        {
            printf("%3d", G.g[i][j]);
        }
        printf(" ]\n");
    }
    printf("（注意矩阵不对称 —— 有向图只填一个格子）\n\n");

//@s 打印入度出度
    CalcIndegree(&G, indegree);
    printf("各顶点的入度和出度：\n");
    for (i = 0; i < nv; i++)
    {
        printf("  顶点 %d：入度 = %d，出度 = %d\n", i, indegree[i], OutDegree(&G, i));
    }
    printf("（入度 = 我要等谁，出度 = 谁要等我）\n\n");

//@s Kahn 算法
    n1 = TopSort(&G, order1);
    printf("=== Kahn 算法（入度 + 队列）===\n");
    PrintOrder("  结果: ", order1, n1);
    printf("  排出了 %d / %d 个顶点\n", n1, nv);
    if (n1 == nv)
    {
        printf("  检查合法性: %s\n", CheckOrder(&G, order1) ? "每条边都是从前往后，合法" : "不合法");
    }

//@s DFS 逆后序
    n2 = TopSortDFS(&G, order2);
    printf("\n=== DFS 逆后序 ===\n");
    PrintOrder("  结果: ", order2, n2);
    printf("  检查合法性: %s\n", CheckOrder(&G, order2) ? "每条边都是从前往后，合法" : "不合法");

//@s 说明
    printf("\n两个序列不一样，但都合法 —— 拓扑排序不唯一\n");
    printf("（队列里有多个入度 0 的点时，先输出谁都可以）\n\n");

//@s 有环的情况
    {
//@s 一个三角形：0→1→2→0
        static const int cyc[][2] = { { 0, 1 }, { 1, 2 }, { 2, 0 } };
        DGraph C;
        int order[MAXV];
        int n;

        CreateDGraph(&C, 3, cyc, 3);
        n = TopSort(&C, order);

        printf("=== 有环的情况：0→1→2→0 ===\n");
        printf("  排出了 %d / 3 个顶点\n", n);
        printf("  有环: %s\n", n != 3 ? "是" : "不是");
        printf("  为什么？环上每个顶点的入度都是 1，谁也降不到 0，\n");
        printf("  所以一个都进不了队 —— 队列一直是空的\n");
        printf("  **输出顶点数 < n  就等价于  有环**\n");
    }

//@s 正常结束
    return 0;
}
//%end
