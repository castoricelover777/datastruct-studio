/*
 * ============================================================================
 *  数据结构研习社 —— 05 排序 / 05-02 堆排序与归并排序
 * ============================================================================
 *
 *  上一节的三个算法都是 O(n²)。这一节的两个能做到 **O(n log n)**，
 *  而且思路完全不同：
 *
 *      **堆排序**：借一个"最大堆"，每次把堆顶（最大值）换到末尾
 *      **归并排序**：分治 —— 把数组劈成两半各自排好，再合并两个有序段
 *
 *  为什么 O(n log n) 是个门槛？因为基于比较的排序，
 *  最坏情况下不可能比 O(n log n) 更快（这个结论可以严格证明）。
 *  所以能做到 O(n log n) 的算法，已经摸到了理论下限。
 *
 *  两者的取舍：
 *
 *      堆排序  原地排序（额外空间 O(1)），但**不稳定**
 *      归并排序 稳定，但要 **O(n) 的额外空间**
 *
 *  标记约定同前（本文件本身可编译）。
 * ============================================================================
 */

#include <stdio.h>
#include <stdlib.h>

//%module | 01 | typedef | 头文件与 typedef | 1 |
//%summary | 公共定义：元素类型、交换。注意这里的下标从 0 开始。
//@d ============ 下标从 0 开始，不是从 1 ============
//@d
//@d 03-04 讲堆的时候用的是 **1 起始**下标（0 号放哨兵），
//@d 因为那样父子关系公式最干净：左孩子 2i、右孩子 2i+1、父亲 i/2。
//@d
//@d 但排序是对**现成的数组**操作，数组下标天然是 0 起始的。
//@d 所以这里必须换成 0 起始的公式：
//@d
//@d     结点 i 的左孩子 = 2i + 1
//@d     结点 i 的右孩子 = 2i + 2
//@d     结点 i 的父亲   = (i - 1) / 2
//@d
//@d 这个转换很容易搞错，写的时候要盯住：**两个地方的下标基准不一样**。
//@d 好消息是除了这一个差别，堆的算法本身完全没变。
//@d
//@d ============ 最后一个非叶结点的下标 ============
//@d
//@d 1 起始时是 N/2，0 起始时变成 **N/2 - 1**。
//@d
//@d 建堆时要从它开始往前逐个下沉 —— 因为它之后的都是叶子，本身已经是合法的堆。

//@s 元素类型
typedef int ElementType;

//@s 状态码
#define OK 1
#define ERROR 0
typedef int Status;

//@s 交换两个元素
void Swap(ElementType *a, ElementType *b)
{
//@s 临时变量倒手
    ElementType t = *a;
    *a = *b;
    *b = t;
}
//%end

//%module | 02 | PercDown | PercDown —— 下沉（0 起始下标版） | 2 | 01 |
//%summary | 把位置 p 的元素在 N 个元素的范围里往下沉。
//@d ============ 和 03-04 的差别只有下标公式 ============
//@d
//@d 回顾一下下沉在做什么：
//@d
//@d   ① 看两个**孩子**里谁更大
//@d   ② 如果自己 >= 那个更大的孩子，位置对了，停
//@d   ③ 否则把孩子搬上来、自己继续往下
//@d
//@d 这里是**最大堆**（父 >= 子），所以找的是"更大的孩子" ——
//@d 03-04 讲最小堆时找的是"更小的孩子"，方向正好相反。
//@d
//@d ============ 为什么要带 N 这个参数 ============
//@d
//@d 因为堆排序的过程中，堆会**越来越小**：
//@d
//@d   每轮把堆顶换到数组末尾，末尾那个位置就"退出堆"了
//@d   下一轮下沉时就不能越过它
//@d
//@d 所以 N 是"当前堆的大小"，不是整个数组的长度。
//@d 这是堆排序里最容易被忽略的地方 —— 忘了改 N，排序结果就全乱了。

//@s 在下标 [0, N) 这个范围内，把 A[p] 往下沉到合适的位置
void PercDown(ElementType A[], int p, int N)
{
//@s 父结点下标（一路往下走）
    int parent;
//@s 较大的孩子下标
    int child;
//@s 暂存要下沉的元素
    ElementType x;

//@s 取出要下沉的元素
    x = A[p];

//@s 沿着"较大的孩子"一路往下
//@d 0 起始下标的左孩子是 2*parent + 1。
    for (parent = p; parent * 2 + 1 < N; parent = child)
    {
//@s 先假设较大的孩子是左孩子
        child = parent * 2 + 1;

//@s 如果有右孩子、且右孩子更大，就换成右孩子
//@d `child != N - 1` 判断有没有右孩子：N-1 是堆里最后一个下标，
//@d 如果左孩子正好是最后一个，那就没有右孩子。
        if (child != N - 1 && A[child] < A[child + 1])
        {
            child++;
        }

//@s 自己已经不小于那个较大的孩子 → 位置对了
        if (x >= A[child])
        {
            break;
        }

//@s 否则把孩子搬上来，自己继续往下比
        A[parent] = A[child];
    }

//@s 落位
    A[parent] = x;
}
//%end

//%module | 03 | HeapSort | HeapSort —— 堆排序 | 3 | 01,02 |
//%summary | 先建最大堆，再反复把堆顶换到末尾 —— 换完一次，末尾就多一个有序元素。
//@d ============ 两个阶段 ============
//@d
//@d **阶段一：建最大堆**
//@d
//@d 从最后一个非叶结点（下标 N/2 - 1）开始往前，逐个下沉。
//@d 做完之后，A[0] 就是整个数组的最大值。
//@d
//@d **阶段二：反复取堆顶**
//@d
//@d   ① 把 A[0]（堆顶，最大值）和 A[i]（堆的最后一个元素）**交换**
//@d   ② 堆的大小减一（i 那个位置从此"退出堆"，它就是排好的部分）
//@d   ③ 对新堆顶做一次下沉，恢复堆序
//@d
//@d 走一遍 { 5, 1, 4, 2, 8, 3 }：
//@d
//@d   建堆后：{ 8, 5, 4, 2, 1, 3 }     ← 8 在堆顶
//@d
//@d   第 1 轮：8 和 3 交换 → { 3, 5, 4, 2, 1 | 8 }，下沉恢复 → { 5, 3, 4, 2, 1 | 8 }
//@d   第 2 轮：5 和 1 交换 → { 1, 3, 4, 2 | 5, 8 }，下沉恢复 → { 4, 3, 1, 2 | 5, 8 }
//@d   第 3 轮：4 和 2 交换 → { 2, 3, 1 | 4, 5, 8 }，下沉恢复 → { 3, 2, 1 | 4, 5, 8 }
//@d   ...
//@d   最后：{ 1, 2, 3, 4, 5, 8 }
//@d
//@d 注意竖线右边的部分**越来越长**，而且已经有序 —— 这就是"排好的部分"。
//@d
//@d ============ 为什么是 O(n log n) ============
//@d
//@d   建堆：O(n)（03-04 讲过为什么不是 O(n log n)）
//@d   阶段二：n-1 轮，每轮一次下沉 = O(log n)  →  O(n log n)
//@d
//@d 加起来还是 O(n log n)，而且**建堆那部分是白赚的**。
//@d
//@d ============ 堆排序的取舍 ============
//@d
//@d   **好处**：原地排序，额外空间只有几个变量，O(1)
//@d   **坏处**：不稳定。因为"堆顶和末尾交换"这个动作会跨越很长的距离，
//@d           把相同元素的相对顺序打乱。
//@d
//@d 所以需要稳定排序时不能用堆排序。而且实测上它通常比快排慢 ——
//@d 因为下沉时的比较访问是"跳跃式"的，对 CPU 缓存不友好。

//@s 堆排序（升序）
void HeapSort(ElementType A[], int N)
{
//@s 循环用
    int i;

//@s 阶段一：从最后一个非叶结点开始，逐个下沉，建成最大堆
//@d 0 起始下标下，最后一个非叶结点是 N/2 - 1。
    for (i = N / 2 - 1; i >= 0; i--)
    {
        PercDown(A, i, N);
    }

//@s 阶段二：反复把堆顶换到末尾
//@d i 从 N-1 递减到 1。i 就是"堆的最后一个位置"，
//@d 换过去之后 A[i] 就归位了。
    for (i = N - 1; i > 0; i--)
    {
//@s 堆顶（当前最大值）换到末尾
        Swap(&A[0], &A[i]);

//@s 堆缩小一格，然后恢复堆序
//@d 这里传的是 i 而不是 N —— 因为 A[i] 已经归位，不能再参与堆的调整。
        PercDown(A, 0, i);
    }
}
//%end

//%module | 04 | Merge | Merge —— 合并两个有序段 | 3 | 01 |
//%summary | 两个有序段各自从头比，谁小先放谁 —— 归并排序的核心动作。
//@d ============ 合并做的事 ============
//@d
//@d 假设数组里有两段**各自已经有序**：
//@d
//@d   下标  0  1  2  |  3  4  5
//@d   值    1  5  8     2  4  9
//@d         ← 左段 →     ← 右段 →
//@d
//@d 要把它们合并成一个有序的 { 1, 2, 4, 5, 8, 9 }。
//@d
//@d 做法就是**两个人比大小**：
//@d
//@d   左段指针在 1，右段指针在 2 → 1 小，取 1
//@d   左段指针在 5，右段指针在 2 → 2 小，取 2
//@d   左段指针在 5，右段指针在 4 → 4 小，取 4
//@d   左段指针在 5，右段指针在 9 → 5 小，取 5
//@d   左段指针在 8，右段指针在 9 → 8 小，取 8
//@d   左段空了，右段剩下的直接搬过来 → 9
//@d
//@d ============ 为什么要用额外数组 ============
//@d
//@d 因为**不能就地合并**：
//@d
//@d 如果直接在原数组里写，A[0] 被新值覆盖之后，原来那个 1 就没了。
//@d 所以必须先把结果放到一个临时数组里，最后再整段拷回去。
//@d
//@d 这就是归并排序"需要 O(n) 额外空间"的来源 —— 也是它最大的缺点。
//@d
//@d ============ 稳定性就藏在一个符号里 ============
//@d
//@d 比较时写的是 `A[L] <= A[R]`，**带了等号**。
//@d
//@d 意思是"两边相等时优先取左边的"。因为左边的元素在原数组里本来就更靠前，
//@d 优先取它能保持相对顺序 —— **这就保证了归并排序是稳定的**。
//@d
//@d 如果写成 `<`，相等时就会取右边的，稳定性就没了。
//@d
//@d ============ 参数为什么这么别扭 ============
//@d
//@d 这里用的是教材里的经典写法，参数是 (L, R, RightEnd)：
//@d
//@d     L        左段的起点
//@d     R        右段的起点（同时也是左段的终点 + 1）
//@d     RightEnd 右段的终点
//@d
//@d 于是左段是 [L, R-1]、右段是 [R, RightEnd]。
//@d 这样传参的好处是**不用再单独传"左段终点"** —— 它等于 R-1。

//@s 把 A[L..R-1] 和 A[R..RightEnd] 两段合并
//@d 结果先放 TmpA，最后拷回 A
void Merge(ElementType A[], ElementType TmpA[], int L, int R, int RightEnd)
{
//@s 左段的终点（右段起点左边那个）
    int LeftEnd = R - 1;
//@s 往 TmpA 里填的位置
    int Tmp = L;
//@s 本段一共多少个元素（拷回时要用）
    int NumElements = RightEnd - L + 1;
//@s 循环用
    int i;

//@s 两边都还有元素时，比较着取
    while (L <= LeftEnd && R <= RightEnd)
    {
//@s 左边不大于右边 → 取左边
//@d 这里的 `<=` 就是稳定性的保证：相等时优先取左边（原数组里更靠前的）。
        if (A[L] <= A[R])
        {
            TmpA[Tmp++] = A[L++];
        }
//@s 否则取右边
        else
        {
            TmpA[Tmp++] = A[R++];
        }
    }

//@s 左边还有剩的，直接搬
    while (L <= LeftEnd)
    {
        TmpA[Tmp++] = A[L++];
    }

//@s 右边还有剩的，直接搬
    while (R <= RightEnd)
    {
        TmpA[Tmp++] = A[R++];
    }

//@s 把合并结果拷回原数组
//@d 从后往前拷，正好和 RightEnd 递减对上。
    for (i = 0; i < NumElements; i++, RightEnd--)
    {
        A[RightEnd] = TmpA[RightEnd];
    }
}
//%end

//%module | 05 | MSort | MSort —— 递归分治 | 3 | 01,04 |
//%summary | 劈成两半、各自排好、再合并 —— 分治的标准三步。
//@d ============ 分治的三步 ============
//@d
//@d   ① **分**：把 [L, RightEnd] 从中间劈成两半
//@d   ② **治**：递归地把两半各自排好
//@d   ③ **合**：合并两个有序段（用上一个模块的 Merge）
//@d
//@d 走一遍 { 5, 1, 4, 2, 8, 3 }：
//@d
//@d   [5 1 4 2 8 3]
//@d    劈成 [5 1 4] 和 [2 8 3]
//@d      [5 1 4] 劈成 [5 1] 和 [4]
//@d        [5 1] 劈成 [5] 和 [1] → 合并 → [1 5]
//@d        [1 5] 和 [4] → 合并 → [1 4 5]
//@d      [2 8 3] 劈成 [2 8] 和 [3]
//@d        [2 8] 劈成 [2] 和 [8] → 合并 → [2 8]
//@d        [2 8] 和 [3] → 合并 → [2 3 8]
//@d    最后 [1 4 5] 和 [2 3 8] → 合并 → [1 2 3 4 5 8]
//@d
//@d ============ 递归的出口 ============
//@d
//@d `if (L < RightEnd)` —— 只处理"至少两个元素"的情况。
//@d
//@d 只剩一个元素时，它自己就是有序的，不用做任何事，直接返回。
//@d 这就是递归的出口。
//@d
//@d ============ 为什么是 O(n log n) ============
//@d
//@d **分了多少层？** 每次劈一半，一共 log n 层。
//@d
//@d **每层做多少事？** 每一层把所有元素都合并了一遍，总共 O(n)。
//@d
//@d 所以总复杂度 = 层数 × 每层工作量 = **log n × n = O(n log n)**。
//@d
//@d 这个分析很干净，而且它是**任何情况下都是 O(n log n)** ——
//@d 不像快排那样有"最坏情况退化成 O(n²)"的隐患。

//@s 把 A[L..RightEnd] 归并排序，TmpA 是临时空间
void MSort(ElementType A[], ElementType TmpA[], int L, int RightEnd)
{
//@s 中间位置
    int Center;

//@s 至少两个元素才需要处理（一个元素本身有序）
    if (L < RightEnd)
    {
//@s ① 分：从中间劈开
        Center = (L + RightEnd) / 2;

//@s ② 治：左半边排好
        MSort(A, TmpA, L, Center);

//@s 治：右半边排好
        MSort(A, TmpA, Center + 1, RightEnd);

//@s ③ 合：两段都已经有序，合并它们
//@d 注意右段的起点是 Center + 1，终点是 RightEnd。
        Merge(A, TmpA, L, Center + 1, RightEnd);
    }
}
//%end

//%module | 06 | MergeSort | MergeSort —— 归并排序的对外接口 | 2 | 01,05 |
//%summary | 分配临时数组、调用分治、释放。
//@d ============ 为什么要单独包一层 ============
//@d
//@d 临时数组 TmpA **只需要分配一次**，而不是每次 Merge 都分配。
//@d
//@d 如果在 Merge 里面 malloc，那要 malloc n 次，开销巨大 ——
//@d 这是初学者很容易犯的错。
//@d
//@d 所以 MSort 把 TmpA 当作参数一路传下去，只在最外层分配一次。
//@d 用户调用时只需要传数组和长度。
//@d
//@d ============ 分配失败怎么办 ============
//@d
//@d 归一化处理：打印一行提示就返回，不至于让程序崩掉。
//@d 实际工程里可能会退化到别的排序（比如堆排序，它不需要额外空间）。

//@s 归并排序（对外的接口）
void MergeSort(ElementType A[], int N)
{
//@s 临时数组
    ElementType *TmpA = (ElementType *)malloc(N * sizeof(ElementType));

//@s 分配失败就不用归并了（原地算法没有这个风险）
    if (TmpA == NULL)
    {
        printf("临时空间分配失败，无法归并排序\n");
        return;
    }

//@s 调用分治
    MSort(A, TmpA, 0, N - 1);

//@s 释放临时空间
    free(TmpA);
}
//%end

//%module | 07 | PrintArray | PrintArray —— 打印与检查 | 1 | 01 |
//%summary | 打印数组、检查是否有序。
//@d ============ 自查工具 ============
//@d
//@d 排序写完怎么看对不对？最省事的两件事：
//@d
//@d   ① 把结果打印出来扫一眼
//@d   ② 自动检查"每个元素都不大于它后面那个"
//@d
//@d 第二件事看着简单，但很管用 —— 手写容易漏掉边界情况（比如长度为 0 或 1）。
//@d
//@d 排序算法的 bug 往往很隐蔽：大部分数据都对，只在某个特定排列下出错。
//@d 所以每改一次都要重新跑一遍检查。

void PrintArray(const ElementType A[], int N)
{
//@s 循环用
    int i;

    printf("[");
    for (i = 0; i < N; i++)
    {
        printf("%d", A[i]);
        if (i < N - 1)
        {
            printf(", ");
        }
    }
    printf("]");
}

//@s 检查是否有序
int IsSorted(const ElementType A[], int N)
{
//@s 循环用
    int i;

    for (i = 0; i + 1 < N; i++)
    {
        if (A[i] > A[i + 1])
        {
            return 0;
        }
    }
    return 1;
}
//%end

//%module | 08 | main | main —— 两个算法对着跑 | 2 | 01,02,03,04,05,06,07 |
//%summary | 同一组数据，堆排序和归并排序；都输出有序结果。
//@d ============ 这一节的重点是"取舍" ============
//@d
//@d 两个算法都是 O(n log n)，都排得对。选哪个看需求：
//@d
//@d   内存紧张、不在乎稳定性        →  堆排序（原地，O(1) 额外空间）
//@d   需要保持相同元素的相对顺序    →  归并排序（稳定，但要 O(n) 空间）
//@d
//@d 还有一个很实际的使用场景：**外部排序**。
//@d
//@d 数据大到内存装不下时，会先把每块排好、写回磁盘，再做多路归并 ——
//@d 那种场合下归并是唯一可行的选择，因为它只需要"顺序读两段"。

//@s 主函数
int main(void)
{
//@s 测试数据
    ElementType a[] = { 5, 1, 4, 2, 8, 3, 9, 0, 7, 6 };
//@s 长度
    int n = 10;
//@s 工作副本
    ElementType b1[10], b2[10];
//@s 循环用
    int i;

//@s 原始
    printf("原始数据: ");
    PrintArray(a, n);
    printf("\n\n");

//@s 堆排序
    for (i = 0; i < n; i++) b1[i] = a[i];
    HeapSort(b1, n);
    printf("堆排序  : ");
    PrintArray(b1, n);
    printf("  %s\n", IsSorted(b1, n) ? "有序 ✓" : "还是乱的 ✗");

//@s 归并排序
    for (i = 0; i < n; i++) b2[i] = a[i];
    MergeSort(b2, n);
    printf("归并排序: ");
    PrintArray(b2, n);
    printf("  %s\n\n", IsSorted(b2, n) ? "有序 ✓" : "还是乱的 ✗");

//@s 两种排序结果应该一致
    {
        int same = 1;
        for (i = 0; i < n; i++)
        {
            if (b1[i] != b2[i]) same = 0;
        }
        printf("两个结果一致: %s\n\n", same ? "是（说明都排对了）" : "不是（有一个错了）");
    }

//@s 演示堆排序的阶段一
    {
        ElementType c[] = { 5, 1, 4, 2, 8, 3 };
        printf("=== 看堆排序的建堆过程 ===\n");
        printf("原始:     ");
        PrintArray(c, 6);
        printf("\n");

//@s 手工只做建堆部分
        for (i = 6 / 2 - 1; i >= 0; i--)
        {
            PercDown(c, i, 6);
        }
        printf("建堆之后: ");
        PrintArray(c, 6);
        printf("\n（最大值 8 被顶到了 A[0]，这就是最大堆的性质）\n");
    }

//@s 对比表
    printf("\n=== 两个算法的取舍 ===\n");
    printf("  堆排序  ：原地，额外空间 O(1)；但**不稳定**\n");
    printf("  归并排序：稳定；但要 O(n) 的额外空间\n");
    printf("\n都是 O(n log n) —— 这已经是基于比较的排序能达到的理论下限\n");

//@s 正常结束
    return 0;
}
