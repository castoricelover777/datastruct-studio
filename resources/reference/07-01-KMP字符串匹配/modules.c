//%module | 06 | main | main —— 和对暴力匹配对跑 | 1 | 01,02,04,05 |
//%summary | 同一组数据分别跑两个算法，对照匹配位置与比较次数。
//@d ============ 为什么 main 里只做对照，不做讲解 ============
//@d
//@d 这一节的每一个知识点在 04、05 两个模块里已经讲完了。
//@d main 的职责只有一件：**把两个算法放在同一组输入上跑**，
//@d 让"结果一样、代价不同"这件事变成看得见的数字。
//@d
//@d 注意 main 模块里只允许有 main —— 辅助函数一律独立成模块，
