/*
 * ============================================================================
 *  数据结构研习社 —— 07 我已学习的高级算法 / 07-01 KMP 字符串匹配
 * ============================================================================
 *
 *  在字符串 S 里找模式串 P —— 这件事在编辑器里按 Ctrl+F、在 DNA 序列里找基因、
 *  在日志里 grep 关键字，每天都在发生。所以它值得一个线性的算法。
 *
 *  ============ 暴力匹配慢在哪 ============
 *
 *      主串  a b a b a b a b            P = a b a b
 *
 *  暴力做法：从主串每个位置开始，逐字符和模式串比：
 *
 *      a b a b a b a b
 *      a b a b                  ← 位置 0 比中
 *        a b a b                ← 位置 1 第一步就错，重来
 *          a b a b              ← 位置 2 比中
 *            ...
 *
 *  问题在"错一次就退回去"：模式串往后挪一格，前面已经比过的字符**又比一遍**。
 *  主串 aaaa...ab、模式串 aaab 这种输入下，比较次数是 O(n·m)。
 *
 *  ============ KMP 的想法：错的时候别退那么多 ============
 *
 *  观察：位置 2 匹配失败时，主串上第 2~3 个字符是 "ab"，它本身就是模式串的前缀。
 *  也就是说"我已经知道这几个字符长什么样了"，没必要回头再读一遍主串 ——
 *  **主串指针永远不后退**，只把模式串往后滑。
 *
 *  滑多少、滑到哪，全靠一张预先算好的表（match / next 数组）：
 *
 *      match[j] = P[0..j] 的「最长相等前后缀」的长度
 *
 *  这一个定义就是整个 KMP 的核心。07-01 这一节把它讲透，
 *  剩下的部分（buildMatch 怎么算、search 怎么用）都是它的推论。
 *
 *  标记约定同前：//%module 划模块，//@s 精简档也保留，//@d 只有详细档保留，
 *  本文件本身可以直接编译。
 * ============================================================================
 */

