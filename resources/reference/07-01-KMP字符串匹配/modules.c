//%module | 02 | NaiveMatch | NaiveMatch —— 暴力匹配（对照组） | 1 | 01 |
//%summary | 从主串每个位置开始逐字符比，作为 KMP 的对照基准。
//@d ============ 先写下"笨办法"，才有比较的对象 ============
//@d
//@d 算法课上一个常见的坏习惯：只讲最优解，不讲它到底优化了什么。
//@d 这一模块故意把 O(n·m) 的写法放在最前面，因为**KMP 的每一行都是为了
//@d 消掉这里的某一次重复比较**。
//@d
//@d 两层循环的语义：
//@d
//@d     for (i = 0; i + m <= n; i++)     ← 主串的每个起手位置都试一遍
//@d         for (j = 0; j < m && S[i+j] == P[j]; j++)   ← 从这儿往后逐字符比
//@d
//@d 内层 while 退出时有两种情况：
//@d
//@d     j == m    比完了整个模式串 → 在 i 处匹配成功
//@d     S[i+j] != P[j]             → 这个起手位置失败，换下一个 i
//@d
//@d ============ 复杂度到底差多少 ============
//@d
//@d 最好情况：第一个字符就不匹配，每次只比 1 次 → O(n)
//@d 最坏情况：S = "aaaa...a"、P = "aaab" → 每个位置都要比 m 次 → O(n·m)
//@d
//@d n = 100 万、m = 1000 时，最坏要 10 亿次比较 —— 这就是要 KMP 的理由。
//@d 而且注意：KMP 的 O(n+m) 是**最坏情况**的保证，不是"平均情况"。

//@s 暴力匹配：从每个位置起手，逐字符比
//@s 返回第一次匹配的下标，找不到返回 -1
//@s 最坏 O(n*m)：主串指针会退回去重比
//@s S = "aaaaaab"、P = "aaab" 就是最坏情况
int NaiveMatch(const char *S, const char *P)
{
//@s m 是模式串长度，n 是主串长度
    int n = (int)strlen(S);
    int m = (int)strlen(P);
    int i, j;

//@s 空模式串约定：在任何位置都算匹配，返回 0
    if (m == 0) return 0;
//@s 模式串比主串还长，不可能匹配
    if (n < m) return -1;

//@s 主串的每个起手位置都试一遍；i + m > n 时后面长度不够，不必再试
    for (i = 0; i + m <= n; i++)
    {
//@s 从 i 开始逐个字符比，遇到不同就跳出
        for (j = 0; j < m && S[i + j] == P[j]; j++)
        {
//@s 空循环体：比较和推进都在 for 的头部完成了
        }
//@s j 走到 m 说明整个模式串都比中了
        if (j == m) return i;
//@s 否则这个 i 失败 —— 主串指针退回到 i+1，前面比过的字符全部作废
    }

//@s 所有起手位置都试过还没中，说明主串里没有这个模式串
    return -1;
}

//%end

//%module | 03 | match | match —— 最长相等前后缀 | 3 | 01 |
//%summary | match[j] 是 P[0..j] 的最长相等前后缀长度；ShowMatchCalc 把某一位的推算过程打出来。
//@d ============ 先搞清楚"前后缀"是什么 ============
//@d
//@d 对串 P[0..j]，**前缀**是从头开始的连续一段，**后缀**是到结尾的连续一段。
//@d 我们要的是"相等的前缀和后缀里最长的那一对"的长度。
//@d
//@d 注意两个限定：
//@d   1. "真"前后缀 —— 前后缀不能是整个串本身（否则长度永远是 j+1，没信息）
//@d   2. 只看长度，不用关心是哪一段（长度定了，内容就定了）
//@d
//@d ============ 逐个看一遍，就明白它在数什么 ============
//@d
//@d P = a b a b a c
//@d
//@d   j=0  "a"           真前后缀只有空串 → match[0] = 0
//@d   j=1  "ab"          "a" != "b"              → 0
//@d   j=2  "aba"         "a" == "a"（前 a 后 a）  → 1
//@d   j=3  "abab"        "ab" == "ab"            → 2
//@d   j=4  "ababa"       "aba" == "aba"          → 3
//@d   j=5  "ababac"      前后缀怎么都对不上        → 0
//@d
//@d 所以 match = { 0, 0, 1, 2, 3, 0 }。
//@d
//@d ============ 它为什么能决定"滑多远" ============
//@d
//@d 假设在 P 的第 j 个字符处和主串失配了。这说明：
//@d
//@d     S[i .. i+j-1] == P[0 .. j-1]        ← 前面这 j 个字符已经确认相等
//@d
//@d 既然主串里这 j 个字符等于 P 的前 j 个字符，那么"P 的前 j 个字符的某个后缀"
//@d 同时也等于主串对应位置的内容。我们想让模式串尽量少往后挪，就要找一个
//@d **既是 P 的前缀、又是 P[0..j-1] 的后缀**的最长子串 —— 那正是 match[j-1]。
//@d
//@d 于是：失配时不需要把 j 清 0，只需要 j = match[j-1]。
//@d 主串指针 i 一动不动 —— 这就是 KMP 省下的那部分工作。
//@d
//@d ============ 一个容易记混的点 ============
//@d
//@d match[j] 描述的是 **P[0..j]** 这个前缀的**内部结构**，和主串无关。
//@d 它回答的问题是："P 自己前 j+1 个字符里，开头和结尾最多重叠多少个字符？"
//@d 想清楚这一点，buildMatch 的递推就不难理解了。

//@s match[j] = P[0..j] 的最长相等前后缀长度（真前后缀，不含整串）
//@s match[0] 恒为 0：长度 1 的串没有真前后缀
//@s "ababaca" 的 match 是 { 0, 0, 1, 2, 3, 0, 1 }

//@s 把 P[0..j] 的候选前后缀逐个列出来，直到找到最长的那一对
//@s 只依赖本模块：不需要 match 表，直接按定义硬算，"看得见的定义"才不容易记混
//@s 返回找到的最长长度；找不到返回 0
//@s 注意这里是最朴素的写法 O(j)，只为把定义讲清楚 —— 整表的 O(m) 算法在 04
int ShowMatchCalc(const char *P, int j)
{
    int k;

//@s 候选长度从大到小试：j 往下减到 1（真前后缀最长只能是 j）
    for (k = j; k >= 1; k--)
    {
        int t;
        int same = 1;

//@s 比"长度为 k 的前缀"和"长度为 k 的后缀"是否逐字符相等
        for (t = 0; t < k; t++)
        {
            if (P[t] != P[j - k + 1 + t])
            {
                same = 0;
                break;
            }
        }

//@s 第一个相等的 k 就是最长的，直接返回
        if (same) return k;
    }

//@s 连长度 1 都对不上，说明没有相等的真前后缀
    return 0;
}

