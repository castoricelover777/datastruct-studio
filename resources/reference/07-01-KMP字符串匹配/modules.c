//%module | 04 | buildMatch | buildMatch —— 递推地算出 match 表 | 3 | 01 |
//%summary | 用"上一位的结果"推下一位，O(m) 算出整张 match 表。
//@d ============ 为什么能 O(m) 算出来 ============
//@d
//@d 有了 match[j-1]，match[j] 只有两种可能：
//@d
//@d   ① 如果 P[j] == P[match[j-1]]，那正好接上 → match[j] = match[j-1] + 1
//@d
//@d      P = a b a b ?        match[3] = 2（"ab"）
//@d          └─┘ └─┘         如果 ? == P[2] == 'a'，那 "aba" 也是前后缀 → 3
//@d
//@d   ② 如果 P[j] != P[match[j-1]]，就退一步看**次长**的相等前后缀。
//@d      次长是谁？正是 match[match[j-1] - 1] —— 对"最长的那一段"再求一次 match。
//@d
//@d      一直退到匹配上、或者退成 0 为止。退到 0 还不匹配，match[j] 就是 0。
//@d
//@d ============ 关键洞察：这个过程不回头 ============
//@d
//@d 看起来里面套了个 while 会退化，其实不会：因为 match[j] <= match[j-1] + 1，
//@d 而每次进 while 都让候选值至少减 1 —— 摊还下来整个循环是 O(m) 的。
//@d
//@d 一句话：外层循环往前走 j 一步，内层循环只把"已匹配的长度"往回退，
//@d 退的总次数不会超过前进的总步数。
//@d
//@d ============ 一个真实的例子，跟着走一遍 ============
//@d
//@d P = a b a b a c
//@d
//@d   j=1  P[1]='b' vs P[0]='a' 不等 → 退到 0 → match[1]=0
//@d   j=2  P[2]='a' vs P[0]='a' 相等 → match[2]=match[1]+1=1
//@d   j=3  P[3]='b' vs P[1]='b' 相等 → match[3]=match[2]+1=2
//@d   j=4  P[4]='a' vs P[2]='a' 相等 → match[4]=match[3]+1=3
//@d   j=5  P[5]='c' vs P[3]='b' 不等 → 退到 match[2]=1，再比 P[5] vs P[1]='b' 还不行
//@d        → 退到 match[0]=0，比 P[5] vs P[0]='a' 仍不行 → match[5]=0

//@s 就地填好调用者给的 match 数组（长度必须 >= m）
//@s match[0] = 0 是递推起点，从 j = 1 开始
//@s 失配时用 match[match[j-1]-1] 往后退，退到 0 为止
//@s 整体 O(m)：内层的回退总次数不超过外层的前进次数
void buildMatch(const char *P, int *match)
{
    int m = (int)strlen(P);
    int j;
    int k;

    if (m == 0) return;

//@s 长度为 1 的前缀没有真前后缀，起点固定是 0
    match[0] = 0;

    for (j = 1; j < m; j++)
    {
//@s k 表示"当前考虑的最长相等前后缀长度"，从上一格的结果开始试
        k = match[j - 1];

//@s 一直退到能接上（P[j] == P[k]）或者退无可退（k == 0）
        while (k > 0 && P[j] != P[k])
        {
//@s 次长的候选：对已经匹配的那一段再求一次它的匹配长度
            k = match[k - 1];
        }

//@s 能接上，长度加一
        if (P[j] == P[k])
        {
            match[j] = k + 1;
        }
        else
        {
//@s 退到 0 都对不上，说明没有任何真前后缀相等
            match[j] = 0;
        }
    }
}

