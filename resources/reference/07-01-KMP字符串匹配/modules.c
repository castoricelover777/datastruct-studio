//%module | 01 | typedef | 头文件与 typedef | 1 |
//%summary | 字符串就是字符数组，KMP 只需要两个东西：模式串和它的 match 表。
//@d ============ 为什么 KMP 的接口这么简单 ============
//@d
//@d 暴力匹配需要"主串 + 模式串 + 两个下标 + 两层循环"，参数一堆。
//@d KMP 把它压到只剩两样：
//@d
//@d     S        主串（只读，指针永不后退）
//@d     P        模式串（只读）
//@d     match    P 的"最长相等前后缀"表，长度和 P 一样
//@d
//@d 注意 match 表是**模式串自己的性质**，和主串无关 ——
//@d 所以同一个模式串在多个主串里查找时，这张表只需要算一次。
//@d 这是 KMP 能工程化的关键：把"预处理模式串"和"扫描主串"分成两步。
//@d
//@d ============ 下标从 0 开始 ============
//@d
//@d 教材里 KMP 的 next 数组常常从 1 开始（next[1] = 0），那是为了配合
//@d "字符串从下标 1 存"的写法。这里统一用 C 的习惯 **从 0 开始**：
//@d
//@d     P         a  b  a  b  a  c
//@d     下标      0  1  2  3  4  5
//@d     match     0  0  1  2  3  0
//@d
//@d match[0] 永远是 0（长度为 1 的串没有真前后缀），这是递推的起点。

//@s 下标统一从 0 开始，和 C 的习惯一致
//@s match[j] = P[0..j] 的最长相等前后缀长度（"真"前后缀，不含整个串本身）
//@s 例子：P = "ababaca" 时 match = { 0, 0, 1, 2, 3, 0, 1 }

//@d ============ match 表用什么类型装 ============
//@d
//@s MatchTable 是"整型数组"的类型别名，长度由调用者保证（至少 strlen(P)）
//@s 用 typedef 而不是裸 int*，是为了让函数签名自解释：
//@s     void buildMatch(const char *P, MatchTable match)
//@s 一眼能看出第二个参数是"存 match 表的数组"，而不是随便一个 int 指针
typedef int MatchTable[64];

//@d 和前面几节一样，用宏定义状态码，让函数返回值有意义
//@s 找不到时的返回值，比裸写 -1 好读
