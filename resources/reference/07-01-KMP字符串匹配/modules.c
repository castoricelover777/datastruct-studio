//@s 场景二：S 全是 a、P 以 c 结尾 —— 这是暴力匹配的最坏情况
//@s 场景三：P 在 S 中间，前面有一大段干扰字符
//@s 场景四：P 不在 S 里，两个算法都该返回 -1
//@s 每个场景都打印下标和 match 表，一眼能看出 match 表只依赖 P
int main(void)
{
    const char *S[4] = { "abababab", "aaaaaaaaab", "xxababacxx", "abcdef" };
    const char *P[4] = { "abab",     "aaab",       "ababac",     "xyz" };
    int match[64];
    int t;

    printf("暴力匹配 vs KMP —— 同一组输入，两个算法各跑一遍\n");
    printf("下标都从 0 开始\n\n");

    for (t = 0; t < 4; t++)
    {
        int n = (int)strlen(S[t]);
        int m = (int)strlen(P[t]);
        int naive, kmp;

        buildMatch(P[t], match);

        naive = NaiveMatch(S[t], P[t]);
        kmp = KMPMatch(S[t], P[t], match);

        printf("场景 %d：S = \"%s\"，P = \"%s\"\n", t + 1, S[t], P[t]);
        printf("  match 表（只看 P，和 S 无关）：");

        {
            int j;
            for (j = 0; j < m; j++)
            {
                printf(" %d", match[j]);
            }
        }

        printf("\n");
        printf("  NaiveMatch → %d\n", naive);
        printf("  KMPMatch   → %d\n", kmp);
        printf("  两者一致：%s\n\n", naive == kmp ? "是" : "否（有问题！）");
        (void)n;
    }

    printf("四个场景两个算法的结果必须完全一致 ——\n");
    printf("KMP 只是把「重复比较」省掉了，不会改变答案\n");

    return 0;
}
