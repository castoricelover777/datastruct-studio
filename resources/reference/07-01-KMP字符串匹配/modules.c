//%module | 05 | KMPMatch | KMPMatch —— 主串指针不后退的匹配 | 3 | 01,04 |
//%summary | 失配时只动模式串：j = match[j-1]，主串指针永不后退。
//@d ============ 和暴力匹配逐行对照 ============
//@d
//@d 暴力匹配是双层 for，每次失败 i 往前挪一格、j 清 0。
//@d KMP 只有一个 while，i 和 j 各自只往前走：
//@d
//@d     while (i < n && j < m)
//@d         if (S[i] == P[j])  { i++; j++; }        ← 匹配，两个一起前进
//@d         else if (j > 0)      j = match[j-1];      ← 失配，只退 j，i 不动
//@d         else               i++;                  ← j 已经是 0，只能让 i 前进
//@d
//@d 三个分支都要有，缺一不可：
//@d
//@d   · 少了第三个分支，j == 0 且失配时会死循环（i 不前进、j 也不动）
//@d   · 少了第二个分支，就退化成暴力匹配
//@d
//@d ============ 复杂度为什么是 O(n + m) ============
//@d
//@d 看 i 和 j 的总变化量：
//@d   · i 只增不减，最多增 n 次
//@d   · j 每次匹配成功 +1，而失配分支让 j 至少减 1
//@d   · 所以 j 减少的总次数 <= j 增加的总次数 <= n
//@d
//@d 于是 while 的循环次数是 O(n)，加上预处理模式串的 O(m)，合计 **O(n + m)**。
//@d 注意这是**最坏情况**的保证 —— 暴力匹配的最坏情况是 O(n·m)。
//@d
//@d ============ 返回值约定 ============
//@d
//@d 返回模式串在主串里**第一次**出现的起始下标；找不到返回 -1。
//@d 循环结束时如果 j == m，说明整个模式串都匹配上了，
//@d 此时主串已经走到 i，匹配的起点就是 i - m。

//@s 失败函数（match 表）由 buildMatch 预先算好，传进来
//@s match 为 NULL 时先把模式串长度当 0 处理，避免解引用空指针
//@s 返回第一次出现的下标；找不到返回 -1
//@s 三个分支的顺序不能换：先比、再退 j、最后才动 i
int KMPMatch(const char *S, const char *P, const int *match)
{
    int n = (int)strlen(S);
    int m = (int)strlen(P);
    int i = 0;
    int j = 0;

//@s 空模式串约定和暴力匹配保持一致：返回 0
    if (m == 0) return 0;
//@s 没有 match 表就没法跳转，直接返回找不到（防御性写法）
    if (match == NULL) return -1;

//@s 两个指针都没走到各自末尾时继续
    while (i < n && j < m)
    {
//@s ① 当前字符相等：两个指针一起前进
        if (S[i] == P[j])
        {
            i++;
            j++;
        }
//@s ② 失配且 j > 0：主串指针不动，模式串往回滑到 match[j-1]
        else if (j > 0)
        {
            j = match[j - 1];
        }
//@s ③ 失配且 j == 0：模式串已经退无可退，只能让主串往前走一格
        else
        {
            i++;
        }
    }

//@s j 走到 m 说明模式串整体匹配上了，起点是 i - m
//@s 否则主串已扫完，返回 -1
    return (j == m) ? (i - m) : -1;
}

