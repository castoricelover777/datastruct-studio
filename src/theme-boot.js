/* ==========================================================================
   LinkList Studio —— 主题启动脚本
   ---------------------------------------------------------------------------
   这个文件必须在 <head> 里同步引入，而且必须是页面里**第一个**脚本。

   原因：主进程启动窗口时会把上次保存的主题通过 URL 参数带进来
   （loadFile 的 search 选项）。在这里同步把它写到 <html data-theme> 上，
   第一帧就画成正确的颜色。否则深色主题的用户每次启动都会先看到一帧白屏，
   再跳成深色 —— 很刺眼。

   界面随后会在 app:init 拿到真实设置后再校正一次（以防参数缺失）。
   ========================================================================== */
(function () {
  'use strict';
  try {
    var m = /[?&]theme=(dark|light)\b/.exec(window.location.search || '');
    if (m) document.documentElement.setAttribute('data-theme', m[1]);
  } catch (e) {
    /* 读不到就保持 HTML 里的默认值 */
  }
})();
